"""
Multi-cell (multi-region active-active) deployment topology generator.

A "cell" is one AWS region plus its availability zones. This planner generates
Terraform, nginx upstream config, a FastAPI health endpoint, and a Markdown
failover runbook to wire N cells together with global traffic routing.

Default regions: us-east-1, eu-west-1, ap-southeast-1

Output layout (under output_dir/cell-architecture/):
  main.tf
  nginx-cell-router.conf
  cell_health.py
  FAILOVER_RUNBOOK.md
"""
from __future__ import annotations

import logging
from pathlib import Path
from typing import List

logger = logging.getLogger(__name__)

DEFAULT_REGIONS: List[str] = ["us-east-1", "eu-west-1", "ap-southeast-1"]

# ── Terraform ─────────────────────────────────────────────────────────────────


def generate_cell_terraform(slug: str, regions: List[str]) -> str:
    """
    Terraform module creating identical EKS infrastructure per region, wired
    together with AWS Global Accelerator and Route53 latency-based routing.
    VPC peering links cells for cross-cell service discovery.
    """
    # Build per-region module blocks
    region_modules: List[str] = []
    endpoint_group_lines: List[str] = []
    route53_records: List[str] = []
    vpc_peering_blocks: List[str] = []

    for i, region in enumerate(regions):
        safe = region.replace("-", "_")
        region_modules.append(f"""\
module "cell_{safe}" {{
  source  = "./modules/cell-eks"
  slug    = "{slug}"
  region  = "{region}"
  cell_id = "{i}"

  vpc_cidr           = "10.{(i + 1) * 10}.0.0/16"
  availability_zones = data.aws_availability_zones.{safe}.names
  eks_version        = "1.29"
  node_instance_type = "t3.medium"
  node_min           = 2
  node_max           = 6
  node_desired       = 3
}}

data "aws_availability_zones" "{safe}" {{
  provider = aws.{safe}
  state    = "available"
}}

provider "aws" {{
  alias  = "{safe}"
  region = "{region}"
}}
""")
        endpoint_group_lines.append(f"""\
    endpoint_group {{
      endpoint_group_region = "{region}"
      traffic_dial_percentage = 100
      health_check_path     = "/cell/health"
      health_check_interval = 30
      threshold_count       = 2
      endpoint_configuration {{
        endpoint_id = module.cell_{safe}.alb_arn
        weight      = 100
      }}
    }}""")
        route53_records.append(f"""\
resource "aws_route53_record" "{safe}_latency" {{
  zone_id        = aws_route53_zone.main.zone_id
  name           = "api.{slug}.io"
  type           = "A"
  set_identifier = "{region}"
  latency_routing_policy {{
    region = "{region}"
  }}
  alias {{
    name                   = module.cell_{safe}.alb_dns_name
    zone_id                = module.cell_{safe}.alb_zone_id
    evaluate_target_health = true
  }}
}}""")

    # VPC peering between all pairs
    for i, r1 in enumerate(regions):
        for j, r2 in enumerate(regions):
            if j <= i:
                continue
            s1 = r1.replace("-", "_")
            s2 = r2.replace("-", "_")
            vpc_peering_blocks.append(f"""\
resource "aws_vpc_peering_connection" "{s1}_{s2}" {{
  provider    = aws.{s1}
  vpc_id      = module.cell_{s1}.vpc_id
  peer_vpc_id = module.cell_{s2}.vpc_id
  peer_region = "{r2}"
  auto_accept = false
  tags = {{ Name = "{slug}-peer-{r1}-{r2}" }}
}}

resource "aws_vpc_peering_connection_accepter" "{s1}_{s2}_accept" {{
  provider                  = aws.{s2}
  vpc_peering_connection_id = aws_vpc_peering_connection.{s1}_{s2}.id
  auto_accept               = true
}}""")

    modules_block = "\n".join(region_modules)
    endpoint_block = "\n".join(endpoint_group_lines)
    r53_block = "\n".join(route53_records)
    peering_block = "\n\n".join(vpc_peering_blocks)

    return f"""\
# {slug} — Multi-cell active-active Terraform
# Regions: {", ".join(regions)}
# Generated by AetherOS cell_planner

terraform {{
  required_version = ">= 1.6"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
  backend "s3" {{
    bucket = "{slug}-tf-state"
    key    = "cell-architecture/terraform.tfstate"
    region = "{regions[0]}"
  }}
}}

# ── Cell modules ──────────────────────────────────────────────────────────────

{modules_block}

# ── Global Accelerator ────────────────────────────────────────────────────────

resource "aws_globalaccelerator_accelerator" "main" {{
  name            = "{slug}-global"
  ip_address_type = "IPV4"
  enabled         = true
}}

resource "aws_globalaccelerator_listener" "https" {{
  accelerator_arn = aws_globalaccelerator_accelerator.main.id
  client_affinity = "SOURCE_IP"
  protocol        = "TCP"
  port_range {{
    from_port = 443
    to_port   = 443
  }}
}}

resource "aws_globalaccelerator_endpoint_group" "cells" {{
  listener_arn = aws_globalaccelerator_listener.https.id
{endpoint_block}
}}

# ── Route53 latency routing ───────────────────────────────────────────────────

resource "aws_route53_zone" "main" {{
  name = "{slug}.io"
}}

{r53_block}

# ── VPC Peering (cross-cell service discovery) ────────────────────────────────

{peering_block}
"""


# ── nginx cell router ─────────────────────────────────────────────────────────


def generate_cell_router_config(slug: str, regions: List[str]) -> str:
    """
    nginx upstream config for cell routing.
    Primary cell gets 70 % weight; on health failure all traffic goes to secondary.
    Sticky sessions via consistent_hash on $http_x_tenant_id.
    """
    if not regions:
        regions = DEFAULT_REGIONS

    primary = regions[0]
    secondaries = regions[1:]

    upstream_lines = [f"    server {primary}.internal.{slug}.io:443 weight=70;"]
    for region in secondaries:
        share = 30 // max(len(secondaries), 1)
        upstream_lines.append(
            f"    server {region}.internal.{slug}.io:443 weight={share};"
        )

    upstream_block = "\n".join(upstream_lines)

    secondary_fallback = ""
    if secondaries:
        fallback_servers = "\n".join(
            f"    server {r}.internal.{slug}.io:443;" for r in secondaries
        )
        secondary_fallback = f"""\
# Fallback upstream — used when primary cell is unhealthy
upstream {slug}_secondary {{
{fallback_servers}
    keepalive 32;
}}
"""

    return f"""\
# {slug} — Cell Router nginx configuration
# Primary: {primary} (70%)
# Secondaries: {", ".join(secondaries) if secondaries else "none"}
# Sticky sessions: consistent hash on X-Tenant-Id header

upstream {slug}_cells {{
{upstream_block}
    keepalive 64;
    # Consistent hashing on tenant_id for session stickiness
    hash $http_x_tenant_id consistent;
}}

{secondary_fallback}
server {{
    listen 443 ssl http2;
    server_name api.{slug}.io;

    ssl_certificate     /etc/ssl/certs/{slug}.crt;
    ssl_certificate_key /etc/ssl/private/{slug}.key;
    ssl_protocols       TLSv1.2 TLSv1.3;

    # Cell health check endpoint for Route53
    location /cell/health {{
        proxy_pass         https://{slug}_cells;
        proxy_set_header   Host $host;
        proxy_set_header   X-Real-IP $remote_addr;
        proxy_connect_timeout 5s;
        proxy_read_timeout    10s;
    }}

    location / {{
        proxy_pass         https://{slug}_cells;
        proxy_set_header   Host $host;
        proxy_set_header   X-Real-IP $remote_addr;
        proxy_set_header   X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header   X-Tenant-Id $http_x_tenant_id;
        proxy_connect_timeout 10s;
        proxy_read_timeout    60s;
        proxy_next_upstream error timeout http_500 http_502 http_503;
        proxy_next_upstream_tries {len(regions)};
    }}
}}
"""


# ── FastAPI health endpoint ───────────────────────────────────────────────────


def generate_cell_health_check(slug: str) -> str:
    """
    FastAPI endpoint: GET /cell/health
    Returns cell_id, region, status, latency_ms, db_connected, queue_connected.
    Used by Route53 health checker and Global Accelerator.
    """
    return f'''\
"""
Cell health check endpoint for {slug}.

Route53 and AWS Global Accelerator call GET /cell/health to determine cell
availability. Returns HTTP 200 when healthy, 503 when degraded.

Mount this router: app.include_router(cell_router)

Environment variables:
  CELL_ID      — unique identifier for this cell (e.g. "cell-0")
  AWS_REGION   — current AWS region
  DATABASE_URL — used to verify DB connectivity
  KAFKA_BROKERS — comma-separated broker list for queue connectivity check
"""
from __future__ import annotations

import asyncio
import logging
import os
import time

from fastapi import APIRouter, Response, status

logger = logging.getLogger(__name__)

cell_router = APIRouter(prefix="/cell", tags=["cell-health"])

CELL_ID = os.getenv("CELL_ID", "cell-0")
AWS_REGION = os.getenv("AWS_REGION", "us-east-1")


async def _check_db() -> bool:
    """Verify database connectivity — replace with your async DB pool ping."""
    try:
        import asyncpg  # type: ignore[import]
        # asyncpg wants the plain scheme, the app's URL is often "postgresql+asyncpg://..."
        db_url = os.getenv("DATABASE_URL", "").replace("+asyncpg", "")
        conn = await asyncpg.connect(db_url, timeout=3)
        await conn.fetchval("SELECT 1")
        await conn.close()
        return True
    except Exception as exc:
        logger.warning("cell_health: DB check failed: %s", exc)
        return False


async def _check_queue() -> bool:
    """Verify Kafka broker connectivity — replace with your Kafka client check."""
    try:
        brokers = os.getenv("KAFKA_BROKERS", "kafka:9092").split(",")
        host, port_str = brokers[0].split(":")
        # non-blocking: a blocking socket here would stall every request while a broker is down
        _, writer = await asyncio.wait_for(asyncio.open_connection(host, int(port_str)), timeout=2)
        writer.close()
        return True
    except Exception as exc:
        logger.warning("cell_health: queue check failed: %s", exc)
        return False


@cell_router.get("/health")
async def cell_health(response: Response) -> dict:
    """Return health status for this cell. Used by Route53 and Global Accelerator."""
    start = time.monotonic()
    db_ok = await _check_db()
    queue_ok = await _check_queue()
    latency_ms = int((time.monotonic() - start) * 1000)

    healthy = db_ok  # queue is non-critical — only DB gates overall health
    cell_status = "healthy" if healthy else "degraded"

    if not healthy:
        response.status_code = status.HTTP_503_SERVICE_UNAVAILABLE

    return {{
        "cell_id": CELL_ID,
        "region": AWS_REGION,
        "slug": "{slug}",
        "status": cell_status,
        "latency_ms": latency_ms,
        "db_connected": db_ok,
        "queue_connected": queue_ok,
    }}
'''


# ── Failover runbook ──────────────────────────────────────────────────────────


def generate_failover_runbook(slug: str, regions: List[str]) -> str:
    """
    Markdown runbook for manual cell failover: identify → reroute → promote DB → verify.
    """
    if not regions:
        regions = DEFAULT_REGIONS

    primary = regions[0]
    secondary = regions[1] if len(regions) > 1 else "secondary-region"

    region_list = "\n".join(f"- `{r}`" for r in regions)
    weight_cmds = "\n".join(
        f"aws route53 change-resource-record-sets --hosted-zone-id $ZONE_ID "
        f"--change-batch '{{\"Changes\":[{{\"Action\":\"UPSERT\",\"ResourceRecordSet\":{{\"Name\":\"api.{slug}.io\",\"Type\":\"A\",\"Region\":\"{r}\",\"Weight\":0,\"SetIdentifier\":\"{r}\",\"AliasTarget\":{{\"HostedZoneId\":\"$ALB_ZONE_{r.replace('-','_').upper()}\",\"DNSName\":\"$ALB_{r.replace('-','_').upper()}\",\"EvaluateTargetHealth\":true}}}}}}]}}'"
        for r in [primary]
    )

    return f"""\
# {slug} — Cell Failover Runbook

**Last Updated:** Generated by AetherOS cell_planner
**Severity:** P0 — execute immediately when a cell becomes unreachable

## Cell Inventory

{region_list}

**Primary cell:** `{primary}`
**Secondary cell(s):** `{secondary}`

---

## Step 1 — Identify the Degraded Cell

```bash
# Check cell health across all regions
for REGION in {" ".join(regions)}; do
  echo "=== $REGION ==="
  curl -sf https://$REGION.internal.{slug}.io/cell/health || echo "UNREACHABLE"
done
```

Also check:
- AWS Console → Global Accelerator → Endpoint health
- Route53 → Health Checks → filter by `{slug}`
- CloudWatch alarms: `{slug}-*-cell-unhealthy`

---

## Step 2 — Reroute Traffic Away from Degraded Cell

### Option A — Route53 weight update (preferred)

Set the failing region weight to 0 so Route53 stops sending traffic there:

```bash
export ZONE_ID=$(aws route53 list-hosted-zones-by-name --dns-name {slug}.io \\
  --query 'HostedZones[0].Id' --output text | cut -d/ -f3)
{weight_cmds}
```

### Option B — Global Accelerator dial-down

```bash
aws globalaccelerator update-endpoint-group \\
  --endpoint-group-arn $GA_ENDPOINT_GROUP_ARN \\
  --traffic-dial-percentage 0 \\
  --region us-west-2   # Global Accelerator API lives in us-west-2
```

---

## Step 3 — Promote Read Replica to Primary (DB failover)

If the primary cell's database is the cause of degradation:

```bash
# Identify the read replica in the healthy region
export REPLICA_ID=$(aws rds describe-db-instances \\
  --query "DBInstances[?DBInstanceIdentifier.contains(@, '{slug}') && DBInstanceStatus=='available' && ReadReplicaSourceDBInstanceIdentifier!=null].DBInstanceIdentifier" \\
  --output text --region {secondary})

# Promote the replica (breaks replication, makes it writable)
aws rds promote-read-replica \\
  --db-instance-identifier $REPLICA_ID \\
  --region {secondary}

# Update DATABASE_URL secret in the healthy cell
aws secretsmanager update-secret \\
  --secret-id {slug}/database-url \\
  --secret-string "postgresql://..." \\
  --region {secondary}

# Rolling restart the application pods to pick up the new URL
kubectl rollout restart deployment/{slug}-api -n {slug} --context {secondary}
```

---

## Step 4 — Verify Recovery

```bash
# All health checks should return 200 with status=healthy
for REGION in {" ".join(regions)}; do
  echo "=== $REGION ===" && curl -s https://api.{slug}.io/cell/health | python3 -m json.tool
done

# Confirm Route53 health checks are green
aws route53 list-health-checks --query \\
  'HealthChecks[?HealthCheckConfig.FullyQualifiedDomainName==`api.{slug}.io`].{{Id:Id,Status:HealthCheckConfig.FullyQualifiedDomainName}}'
```

---

## Step 5 — Post-Incident

1. File a post-mortem in Notion under `{slug} / Incidents`
2. Restore the degraded cell once root cause is fixed
3. Re-enable Route53 weights to previous values
4. Update this runbook if any steps were missing or incorrect
"""


# ── Package orchestrator ──────────────────────────────────────────────────────


def generate_cell_package(
    slug: str,
    regions: List[str] | None,
    output_dir: Path,
) -> Path:
    """
    Write the complete cell-architecture package under output_dir/cell-architecture/.

    Layout:
      cell-architecture/
        main.tf
        nginx-cell-router.conf
        cell_health.py
        FAILOVER_RUNBOOK.md
    """
    effective_regions = regions if regions else DEFAULT_REGIONS
    cell_dir = output_dir / "cell-architecture"
    cell_dir.mkdir(parents=True, exist_ok=True)

    (cell_dir / "main.tf").write_text(
        generate_cell_terraform(slug, effective_regions)
    )
    (cell_dir / "nginx-cell-router.conf").write_text(
        generate_cell_router_config(slug, effective_regions)
    )
    (cell_dir / "cell_health.py").write_text(
        generate_cell_health_check(slug)
    )
    (cell_dir / "FAILOVER_RUNBOOK.md").write_text(
        generate_failover_runbook(slug, effective_regions)
    )

    logger.info(
        "cell_planner: cell-architecture package written to %s (regions=%s)",
        cell_dir,
        effective_regions,
    )
    return cell_dir
