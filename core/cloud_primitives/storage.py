"""
MinIO S3-compatible object storage infrastructure generator for AetherOS Layer 5.

Generates MinIO Helm values, bucket policies, .env snippets, Python boto3 clients,
and docker-compose blocks as files inside a generated project's output directory.
"""
from __future__ import annotations

import json
import logging
import re
from pathlib import Path
from typing import List

logger = logging.getLogger(__name__)


def bucket_name(slug: str, table: str) -> str:
    """S3 bucket for an entity: lower-case letters, digits and hyphens only (underscores are invalid)."""
    return re.sub(r"[^a-z0-9-]+", "-", f"{slug}-{table}s".lower()).strip("-")


def bucket_env_var(table: str) -> str:
    """Environment variable that holds the entity's bucket name. The ONE definition: the .env
    file and the generated client both use it (they used to derive it separately and disagree)."""
    return "BUCKET_" + re.sub(r"[^A-Z0-9]+", "_", f"{table}s".upper())


def generate_minio_helm_values(slug: str, storage_size_gb: int = 50) -> str:
    """Helm values.yaml for MinIO Operator — 3 replicas, persistence, pre-provisioned buckets."""
    return f"""\
## MinIO Operator Helm values — generated by AetherOS for {slug}
minio:
  replicas: 3
  persistence:
    enabled: true
    size: {storage_size_gb}Gi
    storageClass: "standard"
  resources:
    requests:
      memory: "512Mi"
      cpu: "250m"
    limits:
      memory: "2Gi"
      cpu: "1000m"
  rootUser: minio-admin
  rootPassword: ""  # Set via Kubernetes secret: {slug}-minio-root-creds
  environment:
    MINIO_BROWSER_REDIRECT_URL: "https://{slug}-console.internal"
  consoleIngress:
    enabled: true
    host: "{slug}-console.internal"
  ingress:
    enabled: true
    host: "{slug}-minio.internal"
  metrics:
    serviceMonitor:
      enabled: true
      additionalLabels:
        release: prometheus
"""


def generate_bucket_policy(entity_name: str, slug: str) -> str:
    """JSON bucket policy: read for authenticated users, write for app service account."""
    bucket = bucket_name(slug, entity_name)
    policy = {
        "Version": "2012-10-17",
        "Statement": [
            {
                "Effect": "Allow",
                "Principal": {"AWS": [f"arn:aws:iam:::user/{slug}-app-sa"]},
                "Action": [
                    "s3:GetObject",
                    "s3:PutObject",
                    "s3:DeleteObject",
                    "s3:ListBucket",
                ],
                "Resource": [
                    f"arn:aws:s3:::{bucket}",
                    f"arn:aws:s3:::{bucket}/*",
                ],
            },
            {
                "Effect": "Allow",
                "Principal": {"AWS": [f"arn:aws:iam:::user/{slug}-readonly"]},
                "Action": ["s3:GetObject", "s3:ListBucket"],
                "Resource": [
                    f"arn:aws:s3:::{bucket}",
                    f"arn:aws:s3:::{bucket}/*",
                ],
            },
        ],
    }
    return json.dumps(policy, indent=2)


def generate_storage_env(slug: str, bucket_names: List[str]) -> str:
    """Generates .env.storage snippet with MinIO endpoint, credentials, and per-entity bucket vars."""
    lines = [
        f"# MinIO / S3-compatible storage — generated by AetherOS for {slug}",
        "MINIO_ENDPOINT=http://minio:9000",
        f"MINIO_ACCESS_KEY={slug}-app-sa",
        "MINIO_SECRET_KEY=CHANGE_ME_IN_PRODUCTION",
        "MINIO_USE_SSL=false",
        "",
    ]
    for bucket in bucket_names:
        # bucket = "<slug>-<table>s": the variable is the one the generated client reads for <table>
        lines.append(f"BUCKET_{re.sub(r'[^A-Z0-9]+', '_', bucket.removeprefix(slug + '-').upper())}={bucket}")
    lines.append("")
    return "\n".join(lines)


def generate_python_storage_client(entities: List[dict]) -> str:
    """Python class using boto3: upload, download, presigned_url per entity."""
    entity_cases_upload = "\n        ".join(
        f'if entity == "{e.get("table", "item")}": bucket = self.bucket_{e.get("table", "item")}'
        for e in entities
    )
    entity_buckets_init = "\n        ".join(
        f'self.bucket_{e.get("table", "item")} = os.environ["{bucket_env_var(e.get("table", "item"))}"]'
        for e in entities
    )

    return f"""\
\"\"\"
S3-compatible storage client — generated by AetherOS.
Uses boto3 against MinIO (or AWS S3 when MINIO_ENDPOINT is set to AWS).
\"\"\"
from __future__ import annotations

import logging
import os
from typing import BinaryIO, Optional

import boto3
from botocore.config import Config
from botocore.exceptions import BotoCoreError, ClientError

logger = logging.getLogger(__name__)


class StorageClient:
    \"\"\"Per-entity S3-compatible storage backed by MinIO.\"\"\"

    def __init__(self) -> None:
        endpoint = os.environ.get("MINIO_ENDPOINT", "http://minio:9000")
        access_key = os.environ.get("MINIO_ACCESS_KEY", "")
        secret_key = os.environ.get("MINIO_SECRET_KEY", "")
        use_ssl = os.environ.get("MINIO_USE_SSL", "false").lower() == "true"

        self._s3 = boto3.client(
            "s3",
            endpoint_url=endpoint,
            aws_access_key_id=access_key,
            aws_secret_access_key=secret_key,
            use_ssl=use_ssl,
            config=Config(signature_version="s3v4"),
        )
        {entity_buckets_init}

    def _bucket_for(self, entity: str) -> str:
        {entity_cases_upload}
        raise ValueError(f"Unknown entity: {{entity}}")

    def upload_file(self, entity: str, file: BinaryIO, key: str) -> str:
        \"\"\"Upload file-like object to entity bucket. Returns the object key.\"\"\"
        bucket = self._bucket_for(entity)
        try:
            self._s3.upload_fileobj(file, bucket, key)
            logger.info("storage: uploaded s3://%s/%s", bucket, key)
            return key
        except (BotoCoreError, ClientError) as e:
            logger.warning("storage: upload failed entity=%s key=%s: %s", entity, key, e)
            raise

    def download_file(self, entity: str, key: str) -> bytes:
        \"\"\"Download object from entity bucket. Returns raw bytes.\"\"\"
        bucket = self._bucket_for(entity)
        try:
            response = self._s3.get_object(Bucket=bucket, Key=key)
            return response["Body"].read()
        except (BotoCoreError, ClientError) as e:
            logger.warning("storage: download failed entity=%s key=%s: %s", entity, key, e)
            raise

    def presigned_url(self, entity: str, key: str, expires: int = 3600) -> str:
        \"\"\"Generate a pre-signed GET URL for the object. Default TTL: 3600 seconds.\"\"\"
        bucket = self._bucket_for(entity)
        try:
            url = self._s3.generate_presigned_url(
                "get_object",
                Params={{"Bucket": bucket, "Key": key}},
                ExpiresIn=expires,
            )
            return url
        except (BotoCoreError, ClientError) as e:
            logger.warning("storage: presign failed entity=%s key=%s: %s", entity, key, e)
            raise
"""


def generate_minio_docker_compose(slug: str) -> str:
    """docker-compose service block for MinIO single-node (non-Kubernetes builds)."""
    return f"""\
  # MinIO object storage — generated by AetherOS for {slug}
  minio:
    image: minio/minio:RELEASE.2024-01-13T07-53-03Z
    command: server /data --console-address ":9001"
    environment:
      MINIO_ROOT_USER: minio-admin
      MINIO_ROOT_PASSWORD: ${{MINIO_SECRET_KEY:-changeme}}
    ports:
      - "9000:9000"
      - "9001:9001"
    volumes:
      - minio_data:/data
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:9000/minio/health/live"]
      interval: 30s
      timeout: 10s
      retries: 3
    networks:
      - {slug}_network

volumes:
  minio_data:
"""


def generate_storage_package(
    entities: List[dict],
    slug: str,
    output_dir: Path,
    deployment_target: str,
) -> Path:
    """
    Orchestrates storage file generation and writes to output_dir/storage/.

    Returns the storage directory Path.
    """
    storage_dir = output_dir / "storage"
    storage_dir.mkdir(parents=True, exist_ok=True)

    bucket_names = [bucket_name(slug, e.get("table", "item")) for e in entities]

    # Helm values (for Kubernetes deployments)
    (storage_dir / "minio-values.yaml").write_text(
        generate_minio_helm_values(slug)
    )

    # Per-entity bucket policies
    policies_dir = storage_dir / "bucket-policies"
    policies_dir.mkdir(exist_ok=True)
    for entity in entities:
        table = entity.get("table", "item")
        policy_file = policies_dir / f"{table}-policy.json"
        policy_file.write_text(generate_bucket_policy(table, slug))

    # .env snippet
    (storage_dir / ".env.storage").write_text(
        generate_storage_env(slug, bucket_names)
    )

    # Python boto3 client
    (storage_dir / "storage_client.py").write_text(
        generate_python_storage_client(entities)
    )

    # Docker Compose block (always generated; useful even for k8s local dev)
    (storage_dir / "docker-compose.storage.yml").write_text(
        generate_minio_docker_compose(slug)
    )

    logger.info(
        "storage: generated %d bucket policies at %s (target=%s)",
        len(entities),
        storage_dir,
        deployment_target,
    )
    return storage_dir
