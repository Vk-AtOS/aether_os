"""
Kong API Gateway configuration generator (DB-less declarative mode) for AetherOS Layer 5.

Generates Kong declarative YAML, Helm values, and writes them to a generated
project's output directory.
"""
from __future__ import annotations

import logging
from pathlib import Path
from typing import Dict, List

logger = logging.getLogger(__name__)


def generate_kong_declarative_config(
    services: List[Dict], slug: str, cors_origins: List[str] | None = None, redis_host: str = "",
) -> str:
    """
    Kong declarative YAML (_format_version: "3.0") in DB-less mode.

    Each service gets: rate-limit plugin (100 req/min), JWT auth plugin, and a CORS plugin only when
    cors_origins is given (the app's own CORS_ORIGINS handle browsers otherwise: origin "*" together with
    credentials let any website make credentialed calls). The rate limit counts in Redis when redis_host
    is set; "local" counts per Kong replica, so two replicas allow twice the limit.
    One route per service with strip_path=true.

    services = [{"name": str, "port": int, "path_prefix": str}, ...]
    """
    services_block = ""
    routes_block = ""
    plugins_block = ""

    policy = "redis" if redis_host else "local"
    redis_line = f"      redis_host: {redis_host}\n" if redis_host else ""
    origins = "\n".join(f"        - {o}" for o in (cors_origins or []))
    for svc in services:
        name = svc.get("name", "service")
        port = svc.get("port", 8000)
        prefix = svc.get("path_prefix", f"/{name}")

        services_block += f"""\
  - name: {slug}-{name}
    url: http://{name}:{port}
    connect_timeout: 5000
    read_timeout: 60000
    write_timeout: 60000
    retries: 3
"""
        routes_block += f"""\
  - name: {slug}-{name}-route
    service: {slug}-{name}
    paths:
      - {prefix}
    strip_path: true
    preserve_host: false
    protocols:
      - http
      - https
"""
        plugins_block += f"""\
  - name: rate-limiting
    service: {slug}-{name}
    config:
      minute: 100
      policy: {policy}
{redis_line}      fault_tolerant: true
      hide_client_headers: false

  - name: jwt
    service: {slug}-{name}
    config:
      key_claim_name: kid
      claims_to_verify:
        - exp
      maximum_expiration: 3600

""" + (f"""\
  - name: cors
    service: {slug}-{name}
    config:
      origins:
{origins}
      methods:
        - GET
        - POST
        - PUT
        - DELETE
        - OPTIONS
        - PATCH
      headers:
        - Accept
        - Authorization
        - Content-Type
        - X-Request-ID
      exposed_headers:
        - X-Auth-Token
      credentials: true
      max_age: 3600
      preflight_continue: false

""" if cors_origins else "")

    return f"""\
## Kong declarative config (DB-less) — generated by AetherOS for {slug}
_format_version: "3.0"
_transform: true

services:
{services_block}
routes:
{routes_block}
plugins:
{plugins_block}consumers: []
"""


def generate_kong_helm_values(slug: str) -> str:
    """
    Kong Helm values: dbless mode, declarative config via ConfigMap, 2 replicas,
    admin API disabled externally, proxy on 80/443.
    """
    return f"""\
## Kong API Gateway Helm values — generated by AetherOS for {slug}
deployment:
  kong:
    enabled: true

replicaCount: 2

env:
  database: "off"
  declarative_config: /kong/declarative/kong.yaml
  admin_listen: "127.0.0.1:8001"  # Admin API not exposed externally
  proxy_listen: "0.0.0.0:8000, 0.0.0.0:8443 ssl"

volumes:
  - name: kong-declarative-config
    configMap:
      name: {slug}-kong-config

volumeMounts:
  - name: kong-declarative-config
    mountPath: /kong/declarative

proxy:
  enabled: true
  type: LoadBalancer
  http:
    enabled: true
    servicePort: 80
    containerPort: 8000
  tls:
    enabled: true
    servicePort: 443
    containerPort: 8443

admin:
  enabled: false  # Admin API disabled for external access — use kubectl port-forward

resources:
  requests:
    cpu: "250m"
    memory: "256Mi"
  limits:
    cpu: "1000m"
    memory: "512Mi"

podDisruptionBudget:
  enabled: true
  maxUnavailable: 1

autoscaling:
  enabled: true
  minReplicas: 2
  maxReplicas: 10
  targetCPUUtilizationPercentage: 70
"""


def generate_gateway_package(
    services: List[Dict],
    slug: str,
    output_dir: Path,
) -> Path:
    """
    Writes kong.yaml + Helm values to output_dir/gateway/ and returns the directory.
    """
    gateway_dir = output_dir / "gateway"
    gateway_dir.mkdir(parents=True, exist_ok=True)

    (gateway_dir / "kong.yaml").write_text(
        generate_kong_declarative_config(services, slug)
    )
    (gateway_dir / "kong-values.yaml").write_text(
        generate_kong_helm_values(slug)
    )

    logger.info(
        "gateway: generated Kong config for %d services at %s",
        len(services),
        gateway_dir,
    )
    return gateway_dir
