"""
FallbackLLMClient — tries multiple LLM providers in sequence until one succeeds.

Priority order:
  1. Bedrock (Amazon Nova Pro) — if AWS creds present
  2. OpenRouter (mistral-7b free tier) — if OPENROUTER_API_KEY present
  3. Ollama (local DeepSeek Coder) — if Ollama reachable on localhost

Set LLM_BACKEND=fallback (or leave unset) to use this client.
"""

from __future__ import annotations

import logging
import os
from typing import Optional

logger = logging.getLogger(__name__)


class FallbackLLMClient:
    """Tries Bedrock → OpenRouter → Ollama, returns first successful patch."""

    def __init__(self) -> None:
        self._providers: list = []
        self._build_chain()

    def _build_chain(self) -> None:
        # 1. Bedrock — requires AWS creds
        if os.environ.get("AWS_ACCESS_KEY_ID"):
            try:
                from src.slm.bedrock_client import BedrockClient
                self._providers.append(("Bedrock", BedrockClient()))
            except Exception as e:
                logger.warning("Bedrock unavailable: %s", e)

        # 2. Anthropic — requires ANTHROPIC_API_KEY
        if os.environ.get("ANTHROPIC_API_KEY"):
            try:
                from src.slm.anthropic_client import AnthropicClient
                self._providers.append(("Anthropic", AnthropicClient()))
            except Exception as e:
                logger.warning("Anthropic unavailable: %s", e)

        # 3. OpenRouter — requires API key
        if os.environ.get("OPENROUTER_API_KEY"):
            try:
                from src.slm.openrouter_client import OpenRouterClient
                self._providers.append(("OpenRouter", OpenRouterClient()))
            except Exception as e:
                logger.warning("OpenRouter unavailable: %s", e)

        # 4. Ollama — local, no key needed
        try:
            from src.slm.ollama_client import OllamaClient
            client = OllamaClient()
            if client.is_available():
                self._providers.append(("Ollama", client))
        except Exception as e:
            logger.warning("Ollama unavailable: %s", e)

        if not self._providers:
            logger.error(
                "FallbackLLMClient: no LLM providers available. "
                "Set AWS creds, OPENROUTER_API_KEY, or run Ollama locally."
            )

    def generate_patch(self, system_prompt: str, user_prompt: str, max_retries: int = 3) -> Optional[str]:
        for name, provider in self._providers:
            logger.info("FallbackLLMClient: trying %s", name)
            try:
                result = provider.generate_patch(system_prompt, user_prompt, max_retries)
                if result:
                    logger.info("FallbackLLMClient: patch generated by %s", name)
                    return result
                logger.warning("FallbackLLMClient: %s returned no patch, trying next", name)
            except Exception as e:
                logger.warning("FallbackLLMClient: %s raised %s, trying next", name, e)

        logger.error("FallbackLLMClient: all providers exhausted, no patch generated")
        return None

    @property
    def active_provider_names(self) -> list[str]:
        return [name for name, _ in self._providers]
