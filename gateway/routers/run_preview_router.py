@router.post("/factory/runs/{run_id}/push-github")
async def push_run_to_github(
    run_id: str,
    req: Dict[str, Any],
    user: Dict[str, Any] = _current_user(),
):
    """Push the generated project to a new GitHub repository."""
    github_token = req.get("github_token", "")
    repo_name = req.get("repo_name", "")
    if not github_token or not repo_name:
        raise HTTPException(status_code=422, detail="github_token and repo_name are required")
    sf = get_session_factory()
    async with sf() as session:
        run = (await session.execute(
            select(Run).where(Run.id == run_id, Run.org_id == user["org_id"])
        )).scalar_one_or_none()
    if not run:
        raise HTTPException(status_code=404, detail="Run not found")
    project_dir = Path.home() / ".aether_os" / "projects" / run_id
    if not project_dir.exists():
        raise HTTPException(status_code=404, detail="Project files not found")
    if not re.fullmatch(r"[A-Za-z0-9._-]{1,100}", repo_name):
        raise HTTPException(status_code=422, detail="repo_name may only contain letters, digits, '.', '_' and '-'")
    # The clean export, never the raw workspace: no keys, .env, stage folders or preview rewrites (KAN-268).
    try:
        files, manifest = await asyncio.to_thread(
            export_files, project_dir, (run.project_name or run_id).replace(" ", "_"))
    except ExportError as e:
        raise HTTPException(status_code=422, detail={"message": str(e), "findings": [str(f) for f in e.findings]}) from e
    headers = {
        "Authorization": f"token {github_token}",
        "Accept": "application/vnd.github.v3+json",
    }
    async with httpx.AsyncClient(timeout=30) as gh:
        create_res = await gh.post(
            "https://api.github.com/user/repos",
            json={
                "name": repo_name,
                "description": "Generated by AetherOS Factory",
                "private": req.get("public") is not True,      # private unless the caller explicitly asks (KAN-69 F22)
                "auto_init": False,
            },
            headers=headers,
        )
        if create_res.status_code not in (201, 422):
            raise HTTPException(
                status_code=502,
                detail=f"GitHub repo creation failed: {create_res.text}",
            )
        user_res = await gh.get("https://api.github.com/user", headers=headers)
        if user_res.status_code != 200:
            raise HTTPException(status_code=502, detail=f"GitHub token rejected: {user_res.text[:200]}")
        gh_user = user_res.json().get("login", "")
        info = await gh.get(f"https://api.github.com/repos/{gh_user}/{repo_name}", headers=headers)
        if info.status_code != 200:
            raise HTTPException(status_code=502, detail=f"GitHub repo {gh_user}/{repo_name} not readable: {info.text[:200]}")
        repo_data = info.json()
        try:
            pushed = await push_files(
                github_token, f"{gh_user}/{repo_name}", files, branch=repo_data.get("default_branch") or "main",
                message="Initial commit from AetherOS", client=gh)
        except PushError as e:
            logger.warning("GitHub push of run %s failed: %s (%d file errors)", run_id, e, len(e.errors))
            raise HTTPException(status_code=502, detail={"message": str(e), "errors": e.errors}) from e
    return {"html_url": repo_data.get("html_url", f"https://github.com/{gh_user}/{repo_name}"),
            "files_pushed": pushed["files_pushed"], "commit_sha": pushed["commit_sha"],
            "branch": pushed["branch"], "manifest_files": manifest["file_count"]}


@router.get("/factory/runs/{run_id}/traces")
async def get_run_traces(
    run_id: str,
    phase: Optional[str] = Query(None),
    limit: int = Query(100, le=500),
    user: Dict[str, Any] = Depends(require_run_user),
):
    """Return LLM call traces for a pipeline run."""
    sf = get_session_factory()
    async with sf() as db:
        q = select(LLMTrace).where(LLMTrace.run_id == run_id)
        if phase:
            q = q.where(LLMTrace.phase == phase)
        q = q.order_by(LLMTrace.created_at.asc()).limit(limit)
        result = await db.execute(q)
        traces = result.scalars().all()
    return [
        {
            "id": t.id,
            "phase": t.phase,
            "task_type": t.task_type,
            "model": t.model,
            "attempt": t.attempt,
            "duration_ms": t.duration_ms,
            "tokens_in": t.tokens_in,
            "tokens_out": t.tokens_out,
            "parsed_ok": t.parsed_ok,
            "error": t.error,
            "created_at": t.created_at.isoformat() if t.created_at else None,
            "has_prompt": bool(t.prompt),
            "has_response": bool(t.raw_response),
        }
        for t in traces
    ]
@router.get("/factory/runs/{run_id}/traces/{trace_id}")
async def get_trace_detail(
    run_id: str,
    trace_id: str,
    user: Dict[str, Any] = Depends(require_run_user),
):
    """Return full prompt and response for a single trace."""
    sf = get_session_factory()
    async with sf() as db:
        result = await db.execute(
            select(LLMTrace).where(
                LLMTrace.id == trace_id,
                LLMTrace.run_id == run_id,
            )
        )
        trace = result.scalar_one_or_none()
        if not trace:
            raise HTTPException(status_code=404, detail="Trace not found")
    return {
        "id": trace.id,
        "phase": trace.phase,
        "task_type": trace.task_type,
        "model": trace.model,
        "prompt": trace.prompt,
        "raw_response": trace.raw_response,
        "parsed_ok": trace.parsed_ok,
        "error": trace.error,
        "attempt": trace.attempt,
        "duration_ms": trace.duration_ms,
        "tokens_in": trace.tokens_in,
        "tokens_out": trace.tokens_out,
        "created_at": trace.created_at.isoformat() if trace.created_at else None,
    }
@router.get("/factory/runs/{run_id}/frontend-spec")
async def get_frontend_spec(
    run_id: str,
    user: Dict[str, Any] = _current_user(),
):
    """Retrieve the frontend spec attached to a run."""
    sf = get_session_factory()
    async with sf() as session:
        run = await session.get(Run, run_id)
        if not run or run.org_id != user["org_id"]:
            raise HTTPException(status_code=404, detail="Run not found")
        row = await session.get(RunSpec, (run_id, "frontend"))
    return {"spec": row.spec if row else {}}
@router.post("/factory/runs/{run_id}/frontend-spec")
async def save_frontend_spec(
    run_id: str,
    body: Dict[str, Any],
    user: Dict[str, Any] = _current_user(),
):
    """Save / overwrite the frontend spec for a run."""
    spec = body.get("spec") or body
    sf = get_session_factory()
    async with sf() as session:
        run = await session.get(Run, run_id)
        if not run or run.org_id != user["org_id"]:
            raise HTTPException(status_code=404, detail="Run not found")
        row = await session.get(RunSpec, (run_id, "frontend"))
        if row:
            row.spec = spec
            row.updated_at = __import__("datetime").datetime.now(
                __import__("datetime").timezone.utc
            )
        else:
            session.add(RunSpec(run_id=run_id, spec_type="frontend", spec=spec))
        await session.commit()
    return {"status": "saved"}
