"""
P05b Mobile — React Native (Expo) app generation.

Activated when build_profile.frontend_framework == "react_native".
Generates a complete Expo app that connects to the backend generated by P04.
"""
from __future__ import annotations

import logging
from pathlib import Path
from typing import Any, Dict, List

from aether_os.phases.base import TaskResult
from aether_os.phases.utils import get_domain_ir
from aether_os.phases.p05b_mobile.rn_generator import generate_rn_project

logger = logging.getLogger(__name__)


async def run(phase_input: Any, memory_ctx: List[Dict], output_dir: Path) -> TaskResult:
    output_dir.mkdir(parents=True, exist_ok=True)
    data = phase_input.input_data or {}

    build_profile = data.get("build_profile") or {}
    frontend_fw = build_profile.get("frontend_framework", "react")

    if frontend_fw != "react_native":
        logger.info("p05b_mobile: frontend_framework=%s — skipping", frontend_fw)
        return TaskResult(
            output_path=str(output_dir),
            confidence=1.0,
            metadata={"skipped": True, "reason": f"frontend_framework={frontend_fw}"},
            success=True,
        )

    domain_ir = get_domain_ir(data)
    entities = domain_ir.get("entities") or []
    if not entities:
        entities = [{"table": "item", "fields": [{"name": "name", "type": "string"}]}]

    project_name = data.get("project_name") or "Generated App"
    # Use the live_url if the backend is running, otherwise default to localhost
    api_base_url = data.get("live_url") or "http://localhost:8000"

    try:
        mobile_dir = await generate_rn_project(entities, project_name, output_dir, api_base_url)
        logger.info("p05b_mobile: Expo app generated at %s (%d entities)", mobile_dir, len(entities))
        return TaskResult(
            output_path=str(mobile_dir),
            confidence=0.85,
            metadata={"mobile_dir": str(mobile_dir), "entity_count": len(entities)},
            success=True,
        )
    except Exception as e:
        logger.error("p05b_mobile: generation failed: %s", e)
        return TaskResult(output_path=str(output_dir), confidence=0.0, metadata={}, success=False)
