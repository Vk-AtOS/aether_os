"""P15 Handoff — generate complete technical delivery package.

Produces inside docs/ and postman/:
  docs/README.md          — setup guide, env vars, local + deploy instructions
  docs/ARCHITECTURE.md    — system overview with Mermaid component diagram
  docs/DATABASE.md        — entity ERD (Mermaid) and field descriptions
  docs/API.md             — every endpoint documented (method, path, auth, request/response)
  docs/RUNBOOK.md         — deploy, scale, backup, restore, common errors
  docs/PERMISSIONS.md     — roles and what each role can do
  docs/DEVELOPMENT.md     — how to add a new entity / new role
  postman/collection.json — importable Postman collection

Makes 4 focused LLM calls rather than one large call.
"""
from __future__ import annotations
import json
import logging
import re
import uuid
from pathlib import Path
from typing import Any, Dict, List

from aether_os.phases.base import TaskResult

logger = logging.getLogger(__name__)


def _strip_md_fences(text: str) -> str:
    text = re.sub(r"^```(?:json|markdown|yaml)?\s*\n?", "", text.strip())
    text = re.sub(r"\n?```\s*$", "", text.strip())
    return text.strip()


def _ctx_summary(data: dict) -> str:
    """Build a compact context string for LLM prompts."""
    domain = data.get("domain", "general")
    project_name = data.get("project_name", "App")
    raw_input = data.get("raw_input", "")[:2000]
    entities = []
    ir_path = data.get("domain_ir_path", "")
    if ir_path:
        try:
            ir = json.loads(Path(ir_path).read_text())
            entities = [e.get("name", "") for e in ir.get("entities", [])[:15]]
        except Exception as exc:
            logger.debug("p15: failed to read domain_ir for entity list (non-fatal): %s", exc)
    if not entities:
        arch = data.get("architecture_json", {})
        if isinstance(arch, dict):
            entities = [t.get("table", t.get("name", "")) for t in arch.get("database_schema", [])[:15]]
    permission_model = data.get("permission_model", {})
    roles = list(permission_model.get("roles", [])) if permission_model else []
    integration_map = data.get("integration_map", {})
    integrations = [i.get("name", "") for i in integration_map.get("integrations", [])] if integration_map else []
    arch_doc = data.get("architecture_json", {})
    tech_stack = arch_doc.get("tech_stack", {}) if isinstance(arch_doc, dict) else {}

    return (
        f"Project: {project_name}\n"
        f"Domain: {domain}\n"
        f"Description: {raw_input}\n"
        f"Tech stack: {json.dumps(tech_stack)}\n"
        f"Entities: {', '.join(e for e in entities if e)}\n"
        f"Roles: {', '.join(str(r) for r in roles)}\n"
        f"Integrations: {', '.join(str(i) for i in integrations)}\n"
    )


async def run(phase_input: Any, memory_ctx: List[Dict], output_dir: Path) -> TaskResult:
    """Generate the handoff package via 4 focused LLM calls."""
    output_dir.mkdir(parents=True, exist_ok=True)
    docs_dir = output_dir / "docs"
    docs_dir.mkdir(exist_ok=True)
    postman_dir = output_dir / "postman"
    postman_dir.mkdir(exist_ok=True)

    data: dict = getattr(phase_input, "input_data", {}) or {}
    project_name = data.get("project_name", "App")
    domain = data.get("domain", "general")
    ctx = _ctx_summary(data)

    files_written: List[str] = []

    # Graceful fallback if LLM is unavailable
    try:
        from aether_os.core.llm.client import get_llm_client
        llm = get_llm_client()
    except Exception as exc:
        logger.warning("p15: LLM client unavailable — writing stub handoff docs: %s", exc)
        llm = None

    # ── Call A: README + ARCHITECTURE ──────────────────────────────────────────
    readme_content = f"# {project_name}\n\nGenerated by AetherOS.\n\n## Setup\n\n```bash\npip install -r requirements.txt\nuvicorn src.main:app --reload\n```\n"
    arch_content = f"# Architecture\n\n## Overview\n\n{project_name} ({domain} domain) — auto-generated full-stack application.\n\n## Stack\n\nSee README.md for details.\n"

    if llm:
        try:
            prompt_a = f"""\
You are writing technical documentation for a delivered software project.

Context:
{ctx}

Write two documentation files in Markdown:

FILE 1 — docs/README.md:
- Project description (2-3 sentences)
- Prerequisites (Python 3.11+, Node 20+, Docker, PostgreSQL)
- Local setup steps (clone, .env, pip install, uvicorn)
- Environment variables table (DATABASE_URL, SECRET_KEY, CORS_ORIGINS, REDIS_URL)
- How to run tests
- How to deploy to production (docker-compose up --build)

FILE 2 — docs/ARCHITECTURE.md:
- System overview paragraph
- Mermaid component diagram (```mermaid graph TD) showing: Frontend → API → DB, API → Redis, API → External integrations
- Tech stack table
- Key design decisions (3-5 bullet points)

Return JSON: {{"readme": "<markdown>", "architecture": "<markdown>"}}
Return ONLY JSON, no markdown fences around the JSON itself."""
            result_a = await llm.call(prompt_a, task_type="analysis", max_tokens=3000)
            result_a = _strip_md_fences(result_a)
            parsed_a = json.loads(result_a)
            readme_content = parsed_a.get("readme", readme_content)
            arch_content = parsed_a.get("architecture", arch_content)
        except Exception as exc:
            logger.warning("p15: Call A failed: %s", exc)

    (docs_dir / "README.md").write_text(readme_content)
    (docs_dir / "ARCHITECTURE.md").write_text(arch_content)
    files_written += ["docs/README.md", "docs/ARCHITECTURE.md"]

    # ── Call B: DATABASE + API docs ───────────────────────────────────────────
    db_content = f"# Database Schema\n\n## Entities\n\n{project_name} uses a relational database with the entities listed in the domain IR.\n"
    api_content = f"# API Reference\n\n## Base URL\n\n`http://localhost:8000/api`\n\n## Authentication\n\nAll endpoints require `Authorization: Bearer <token>` except `/auth/login` and `/auth/register`.\n"

    if llm:
        try:
            prompt_b = f"""\
You are writing technical documentation for a delivered software project.

Context:
{ctx}

Write two documentation files in Markdown:

FILE 1 — docs/DATABASE.md:
- Introduction paragraph
- Mermaid ERD diagram (```mermaid erDiagram) for all entities with their key fields and relationships
- Table-by-table description: purpose, key fields, indexes

FILE 2 — docs/API.md:
- Base URL section
- Authentication section (JWT Bearer token flow)
- For EACH entity, document ALL CRUD endpoints:
  | Method | Path | Auth | Request Body | Response |
  (use a Markdown table)
- Error codes section (400/401/403/404/422/500)

Return JSON: {{"database": "<markdown>", "api": "<markdown>"}}
Return ONLY JSON, no markdown fences around the JSON itself."""
            result_b = await llm.call(prompt_b, task_type="analysis", max_tokens=4000)
            result_b = _strip_md_fences(result_b)
            parsed_b = json.loads(result_b)
            db_content = parsed_b.get("database", db_content)
            api_content = parsed_b.get("api", api_content)
        except Exception as exc:
            logger.warning("p15: Call B failed: %s", exc)

    (docs_dir / "DATABASE.md").write_text(db_content)
    (docs_dir / "API.md").write_text(api_content)
    files_written += ["docs/DATABASE.md", "docs/API.md"]

    # ── Call C: RUNBOOK + PERMISSIONS + DEVELOPMENT ────────────────────────────
    runbook_content = f"# Runbook\n\n## Deploy\n\n```bash\ndocker-compose up --build -d\n```\n\n## Scale\n\nUpdate replicas in k8s/deployment.yaml and apply.\n\n## Backup\n\n```bash\n./scripts/backup.sh\n```\n\n## Common Errors\n\n- **502 Bad Gateway**: API container crashed — check `docker-compose logs app`\n- **DB connection refused**: PostgreSQL not ready — wait for healthcheck\n"
    perms_content = f"# Permissions\n\nThis application uses role-based access control (RBAC).\n\n## Roles\n\nSee the permission model generated by p02c_permission_modeling for full details.\n"
    dev_content = f"# Development Guide\n\n## Adding a New Entity\n\n1. Add the entity to `src/models.py`\n2. Add schemas to `src/schemas.py`\n3. Add CRUD routes to `src/routers/crud.py`\n4. Run `alembic revision --autogenerate -m 'add entity'`\n5. Run `alembic upgrade head`\n"

    if llm:
        try:
            prompt_c = f"""\
You are writing technical documentation for a delivered software project.

Context:
{ctx}

Write three documentation files in Markdown:

FILE 1 — docs/RUNBOOK.md:
- How to deploy (docker-compose, K8s helm install)
- How to scale horizontally (K8s HPA config)
- Backup procedure (pg_dump + S3)
- Restore procedure
- How to debug common errors (5 most likely errors with diagnostic steps)
- Monitoring: health endpoint, logs, Prometheus metrics

FILE 2 — docs/PERMISSIONS.md:
- Overview of RBAC/ABAC model
- Table of roles and what each can do per resource (use a Markdown table)
- How to add a new role
- Row-level security rules if any

FILE 3 — docs/DEVELOPMENT.md:
- How to add a new entity (step-by-step: model, schema, router, migration)
- How to add a new role with permissions
- How to add a new integration (where to put the client, how to wire it)
- Code style and conventions used in this project
- How to run tests and linting

Return JSON: {{"runbook": "<markdown>", "permissions": "<markdown>", "development": "<markdown>"}}
Return ONLY JSON, no markdown fences around the JSON itself."""
            result_c = await llm.call(prompt_c, task_type="analysis", max_tokens=4000)
            result_c = _strip_md_fences(result_c)
            parsed_c = json.loads(result_c)
            runbook_content = parsed_c.get("runbook", runbook_content)
            perms_content = parsed_c.get("permissions", perms_content)
            dev_content = parsed_c.get("development", dev_content)
        except Exception as exc:
            logger.warning("p15: Call C failed: %s", exc)

    (docs_dir / "RUNBOOK.md").write_text(runbook_content)
    (docs_dir / "PERMISSIONS.md").write_text(perms_content)
    (docs_dir / "DEVELOPMENT.md").write_text(dev_content)
    files_written += ["docs/RUNBOOK.md", "docs/PERMISSIONS.md", "docs/DEVELOPMENT.md"]

    # ── Call D: Postman collection ─────────────────────────────────────────────
    # Build a basic Postman collection from the architecture JSON endpoints
    arch_doc = data.get("architecture_json", {})
    endpoints = []
    if isinstance(arch_doc, dict):
        endpoints = arch_doc.get("api_endpoints", [])[:30]

    postman_collection: dict = {
        "info": {
            "_postman_id": str(uuid.uuid4()),
            "name": f"{project_name} API",
            "description": f"Auto-generated Postman collection for {project_name}",
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
        },
        "auth": {
            "type": "bearer",
            "bearer": [{"key": "token", "value": "{{access_token}}", "type": "string"}],
        },
        "variable": [
            {"key": "base_url", "value": "http://localhost:8000/api", "type": "string"},
            {"key": "access_token", "value": "", "type": "string"},
        ],
        "item": [],
    }

    if llm and endpoints:
        try:
            endpoints_json = json.dumps(endpoints[:20], indent=2)
            prompt_d = f"""\
Generate a Postman Collection v2.1 JSON for the API of "{project_name}".

API base URL variable: {{{{base_url}}}} = http://localhost:8000/api
Auth: Bearer token in variable {{{{access_token}}}}

Endpoints:
{endpoints_json}

Always include:
- POST /auth/login (body: email, password) — set access_token in Tests script
- POST /auth/register (body: email, password, name)
- GET /health (no auth)

For each endpoint:
- Include realistic example request body
- Set Authorization header to Bearer {{{{access_token}}}} for protected routes

Return ONLY valid Postman Collection v2.1 JSON (the complete collection object).
No explanation, no markdown fences."""
            result_d = await llm.call(prompt_d, task_type="code_generation", max_tokens=4000)
            result_d = _strip_md_fences(result_d)
            parsed_d = json.loads(result_d)
            if isinstance(parsed_d, dict) and ("item" in parsed_d or "info" in parsed_d):
                postman_collection = parsed_d
        except Exception as exc:
            logger.warning("p15: Call D (Postman) failed, using stub: %s", exc)
            # Build stub items from endpoints list
            items = []
            for ep in endpoints[:20]:
                method = ep.get("method", "GET")
                path = ep.get("path", "/")
                items.append({
                    "name": f"{method} {path}",
                    "request": {
                        "method": method,
                        "url": {"raw": f"{{{{base_url}}}}{path}", "host": ["{{base_url}}"], "path": path.strip("/").split("/")},
                        "header": [{"key": "Authorization", "value": "Bearer {{access_token}}"}],
                    },
                })
            postman_collection["item"] = items

    (postman_dir / "collection.json").write_text(json.dumps(postman_collection, indent=2))
    files_written.append("postman/collection.json")

    # Write manifest
    manifest = {
        "phase": "p15_handoff",
        "project_name": project_name,
        "domain": domain,
        "files_written": files_written,
        "total_files": len(files_written),
    }
    manifest_path = output_dir / "handoff_manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2))

    logger.info("p15: handoff package complete — %d files written", len(files_written))

    return TaskResult(
        output_path=str(output_dir),
        confidence=0.9,
        metadata={
            "files_written": files_written,
            "total_files": len(files_written),
            "project_name": project_name,
        },
        issues=[],
        success=True,
    )
