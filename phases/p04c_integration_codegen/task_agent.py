"""P04c Integration Codegen — generate async client code for each discovered integration.

Reads integration_map from accumulated context (set by p01b_integration_discovery).
For named integrations (Stripe, SendGrid, Twilio, OpenAI, RAG), uses a deterministic
production-ready template — no LLM needed, no hallucinated code.
For unknown integrations, falls back to an LLM-generated generic httpx client.
Also generates services/__init__.py and services/integration_manager.py.
"""
from __future__ import annotations
import json
import logging
import re
from pathlib import Path
from typing import Any, Dict, List

from aether_os.phases.base import TaskResult
from aether_os.phases.p04c_integration_codegen.templates import match_template

logger = logging.getLogger(__name__)

_HTTPX_CLIENT_EXAMPLE = """\
Example of a well-structured async httpx client:

```python
import httpx
import asyncio
import logging
from typing import Any, Dict, Optional

logger = logging.getLogger(__name__)

class ExampleClient:
    BASE_URL = "https://api.example.com/v1"

    def __init__(self, api_key: str):
        self.api_key = api_key
        self._client: Optional[httpx.AsyncClient] = None

    async def _get_client(self) -> httpx.AsyncClient:
        if self._client is None:
            self._client = httpx.AsyncClient(
                base_url=self.BASE_URL,
                headers={"Authorization": f"Bearer {self.api_key}"},
                timeout=30.0,
            )
        return self._client

    async def _request(self, method: str, path: str, **kwargs) -> Dict[str, Any]:
        client = await self._get_client()
        for attempt in range(3):
            try:
                response = await client.request(method, path, **kwargs)
                response.raise_for_status()
                return response.json()
            except httpx.HTTPStatusError as exc:
                if exc.response.status_code < 500 or attempt == 2:
                    raise
                await asyncio.sleep(2 ** attempt)
        return {}

    async def close(self):
        if self._client:
            await self._client.aclose()
            self._client = None
```
"""


def _slugify(name: str) -> str:
    """Convert integration name to a Python-safe module name."""
    return re.sub(r"[^a-z0-9_]", "_", name.lower()).strip("_")


def _fallback_client(integration: dict) -> str:
    """Generate a minimal stub client when LLM is unavailable."""
    name = integration.get("name", "Unknown")
    slug = _slugify(name)
    auth_method = integration.get("auth_method", "api_key")
    endpoints = integration.get("endpoints_needed", [])

    env_var = f"{name.upper().replace(' ', '_')}_API_KEY"
    if auth_method == "oauth2":
        env_var = f"{name.upper().replace(' ', '_')}_CLIENT_SECRET"

    endpoints_code = "\n".join(
        f"    async def {_slugify(ep)}(self, **kwargs) -> dict:\n"
        f"        \"\"\"Call {name} {ep} endpoint.\"\"\"\n"
        f"        return await self._request('POST', '/{ep.replace('_', '-')}', json=kwargs)\n"
        for ep in endpoints[:8]
    ) or "    pass\n"

    return f'''\
"""Auto-generated {name} client — generated by AetherOS."""
from __future__ import annotations
import asyncio
import logging
import os
from typing import Any, Dict, Optional

import httpx

logger = logging.getLogger(__name__)


class {name.replace(" ", "")}Client:
    """{name} integration client."""

    BASE_URL = "https://api.{slug.replace("_", ".")}.com"

    def __init__(self):
        self.api_key = os.getenv("{env_var}", "")
        self._client: Optional[httpx.AsyncClient] = None

    async def _get_client(self) -> httpx.AsyncClient:
        if self._client is None:
            self._client = httpx.AsyncClient(
                base_url=self.BASE_URL,
                headers={{"Authorization": f"Bearer {{self.api_key}}"}},
                timeout=30.0,
            )
        return self._client

    async def _request(self, method: str, path: str, **kwargs) -> Dict[str, Any]:
        """Make an authenticated request with retry logic."""
        client = await self._get_client()
        for attempt in range(3):
            try:
                response = await client.request(method, path, **kwargs)
                response.raise_for_status()
                return response.json()
            except httpx.HTTPStatusError as exc:
                logger.error("{name} API error %s: %s", exc.response.status_code, exc.response.text[:200])
                if exc.response.status_code < 500 or attempt == 2:
                    raise
                await asyncio.sleep(2 ** attempt)
            except Exception as exc:
                if attempt == 2:
                    raise
                logger.warning("{name} request failed (attempt %d): %s", attempt + 1, exc)
                await asyncio.sleep(2 ** attempt)
        return {{}}

{endpoints_code}

    async def close(self) -> None:
        """Close the underlying HTTP client."""
        if self._client:
            await self._client.aclose()
            self._client = None


{slug}_client = {name.replace(" ", "")}Client()
'''


async def run(phase_input: Any, memory_ctx: List[Dict], output_dir: Path) -> TaskResult:
    """Generate integration clients for each discovered integration."""
    output_dir.mkdir(parents=True, exist_ok=True)

    data: dict = getattr(phase_input, "input_data", {}) or {}
    integration_map: dict = data.get("integration_map", {})

    # Also check the p01b output path
    if not integration_map:
        p01b_output = data.get("p01b_integration_discovery_output", {})
        if isinstance(p01b_output, dict):
            integration_map = p01b_output.get("integration_map", {})

    integrations = integration_map.get("integrations", []) if isinstance(integration_map, dict) else []

    if not integrations:
        logger.info("p04c: no integrations in context — skipping")
        out_path = output_dir / "integration_codegen.json"
        out_path.write_text(json.dumps({"skipped": True, "reason": "no integrations discovered"}))
        return TaskResult(
            output_path=str(out_path),
            confidence=1.0,
            metadata={"skipped": True, "clients_generated": 0},
            success=True,
        )

    # Determine where to write generated service files
    project_dir = Path(data.get("project_dir", str(output_dir.parent)))
    # Try to find the actual backend src dir
    src_dir = None
    for candidate in [
        project_dir / "p04a_backend_codegen" / "src",
        project_dir / "p04_backend" / "backend_codegen" / "src",
        project_dir / "src",
    ]:
        if candidate.exists():
            src_dir = candidate
            break

    if src_dir is None:
        src_dir = output_dir / "src"
        src_dir.mkdir(parents=True, exist_ok=True)

    services_dir = src_dir / "services"
    services_dir.mkdir(parents=True, exist_ok=True)

    clients_generated: List[str] = []
    llm = None
    try:
        from aether_os.core.llm.client import get_llm_client
        llm = get_llm_client()
    except Exception as exc:
        logger.warning("p04c: LLM unavailable — using stub clients: %s", exc)

    for integration in integrations[:8]:  # cap at 8 to avoid excessive LLM calls
        name = integration.get("name", "Unknown")
        int_type = integration.get("type", "api")
        auth_method = integration.get("auth_method", "api_key")
        endpoints = integration.get("endpoints_needed", [])
        slug = _slugify(name)

        # Check if this is a named integration with a production-ready template
        template_entry = match_template(name)

        if template_entry:
            gen_fn, out_filename = template_entry
            client_path = services_dir / out_filename
            try:
                client_code = gen_fn(output_dir=services_dir, config=integration)
                client_path.write_text(client_code)
                module_name = out_filename.replace(".py", "")
                clients_generated.append(module_name)
                logger.info("p04c: named template used for %s → %s", name, out_filename)
            except Exception as exc:
                logger.warning("p04c: named template for %s failed: %s — using stub", name, exc)
            continue

        # Unknown integration — use LLM or stub fallback
        client_path = services_dir / f"{slug}_client.py"
        client_code = _fallback_client(integration)

        if llm:
            try:
                prompt = f"""\
Generate a production-ready Python async integration client for {name} ({int_type}).

Authentication: {auth_method}
Endpoints needed: {', '.join(endpoints[:10])}

Requirements:
- Use httpx.AsyncClient for async HTTP
- Implement authentication: {auth_method}
- Add retry logic with exponential backoff (3 attempts, max 2^n seconds)
- Custom exception classes: {name.replace(" ", "")}Error, {name.replace(" ", "")}AuthError, {name.replace(" ", "")}RateLimitError
- Implement each endpoint as an async method with docstring
- Load credentials from environment variables (os.getenv)
- Implement async close() method
- Create a module-level singleton instance

{_HTTPX_CLIENT_EXAMPLE}

Return ONLY valid Python code. No markdown fences, no explanation.
File: services/{slug}_client.py"""

                result = await llm.call(prompt, task_type="code_generation", max_tokens=2500)
                if result and len(result.strip()) > 200:
                    result = re.sub(r"^```(?:python)?\s*\n?", "", result.strip())
                    result = re.sub(r"\n?```\s*$", "", result.strip())
                    try:
                        import ast
                        ast.parse(result)
                        client_code = result
                        logger.info("p04c: LLM client generated for %s (%d chars)", name, len(client_code))
                    except SyntaxError as syn:
                        logger.warning("p04c: LLM client SyntaxError for %s: %s — using stub", name, syn)
            except Exception as exc:
                logger.warning("p04c: LLM call for %s failed: %s — using stub", name, exc)

        client_path.write_text(client_code)
        clients_generated.append(f"{slug}_client")
        logger.info("p04c: wrote %s", client_path)

    # Write services/__init__.py so the directory is a proper package
    (services_dir / "__init__.py").write_text(
        '"""Auto-generated services package — AetherOS p04c_integration_codegen."""\n'
    )

    # Generate integration_manager.py
    manager_imports = "\n".join(
        f"from services.{c} import *  # noqa: F401,F403" for c in clients_generated
    )
    manager_py = f'''\
"""Integration manager — imports and initializes all discovered clients.
Generated by AetherOS p04c_integration_codegen.
"""
from __future__ import annotations
import logging

logger = logging.getLogger(__name__)

{manager_imports}

__all__ = {json.dumps(clients_generated)}
'''
    (services_dir / "integration_manager.py").write_text(manager_py)
    clients_generated.append("integration_manager")

    # Write summary
    summary = {
        "integrations_processed": len(integrations),
        "clients_generated": clients_generated,
    }
    out_path = output_dir / "integration_codegen.json"
    out_path.write_text(json.dumps(summary, indent=2))
    logger.info("p04c: generated %d integration clients", len(clients_generated) - 1)

    return TaskResult(
        output_path=str(out_path),
        confidence=0.88,
        metadata=summary,
        success=True,
    )
