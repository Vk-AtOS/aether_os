"""
P21 SRE Agent Generator — generates a self-healing SRE operator alongside every deployment.

Runs after P15 handoff. Reads: architecture.json, monitoring config, domain_knowledge.json.
Outputs: k8s/sre-agent-cronjob.yaml, scripts/sre_failure_classifier.py, docs/REMEDIATION_PLAYBOOK.md

The generated SRE agent is a Kubernetes CronJob that:
  1. Polls Prometheus for the application's alert rules
  2. Classifies failures using the generated failure_classifier
  3. Applies pre-approved remediations (HPA scale-up, config patch)
  4. Pages via PagerDuty/OpsGenie for unclassified failures
"""
from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Tuple

from aether_os.phases.base import TaskResult

logger = logging.getLogger(__name__)

# Domain-specific Prometheus failure patterns injected into the classifier
_DOMAIN_PATTERNS: Dict[str, str] = {
    "healthcare": '''\
    "SlowClaimsProcessing": {
        "prometheus_query": 'http_request_duration_seconds_p95{app="{app_name}", path="/claims"} > 5',
        "remediation": "kubectl scale deployment/{app_name} --replicas=4",
        "severity": "warning",
    },''',
    "fintech": '''\
    "TransactionQueueDepth": {
        "prometheus_query": 'kafka_consumer_lag_sum{app="{app_name}"} > 1000',
        "remediation": "kubectl scale deployment/{app_name} --replicas=4",
        "severity": "critical",
    },''',
    "ecommerce": '''\
    "InventoryAPITimeout": {
        "prometheus_query": 'http_request_duration_seconds_p95{app="{app_name}", path="/inventory"} > 5',
        "remediation": "kubectl rollout restart deployment/{app_name}",
        "severity": "warning",
    },''',
}


def _build_cronjob_yaml(app_name: str, namespace: str, domain: str) -> str:
    """Return a Kubernetes CronJob YAML string for the SRE agent."""
    return f"""\
apiVersion: batch/v1
kind: CronJob
metadata:
  name: {app_name}-sre-agent
  namespace: {namespace}
  labels:
    app.kubernetes.io/name: {app_name}-sre-agent
    app.kubernetes.io/managed-by: aetheros
spec:
  schedule: "*/5 * * * *"  # every 5 minutes
  concurrencyPolicy: Forbid
  successfulJobsHistoryLimit: 3
  failedJobsHistoryLimit: 3
  jobTemplate:
    spec:
      backoffLimit: 0
      template:
        spec:
          serviceAccountName: {app_name}-sre-agent
          containers:
          - name: sre-agent
            image: python:3.12-slim
            command:
            - /bin/sh
            - -c
            - |
              pip install requests --quiet && python3 /scripts/sre_failure_classifier.py
            env:
            - name: PROMETHEUS_URL
              value: "http://prometheus:9090"
            - name: APP_NAME
              value: "{app_name}"
            - name: DOMAIN
              value: "{domain}"
            - name: PAGERDUTY_KEY
              valueFrom:
                secretKeyRef:
                  name: {app_name}-sre-secrets
                  key: pagerduty-key
                  optional: true
            volumeMounts:
            - name: sre-scripts
              mountPath: /scripts
          volumes:
          - name: sre-scripts
            configMap:
              name: {app_name}-sre-scripts
          restartPolicy: OnFailure
---
apiVersion: v1
kind: ServiceAccount
metadata:
  name: {app_name}-sre-agent
  namespace: {namespace}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: {app_name}-sre-role
  namespace: {namespace}
rules:
- apiGroups: ["apps"]
  resources: ["deployments", "deployments/scale"]
  verbs: ["get", "patch", "update"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: {app_name}-sre-binding
  namespace: {namespace}
subjects:
- kind: ServiceAccount
  name: {app_name}-sre-agent
roleRef:
  kind: Role
  name: {app_name}-sre-role
  apiGroup: rbac.authorization.k8s.io
"""


def _build_classifier_script(app_name: str, domain: str) -> str:
    """Return a Python SRE failure classifier script as a string."""
    raw_domain_patterns = _DOMAIN_PATTERNS.get(domain, "")
    # Replace app_name placeholder inside the domain pattern string
    domain_patterns = raw_domain_patterns.replace("{app_name}", app_name)

    return f"""\
#!/usr/bin/env python3
\"\"\"
SRE Failure Classifier — generated by AetherOS for {app_name}.
Polls Prometheus alerts and applies automated remediations.
Domain: {domain}
\"\"\"
import os
import requests
import subprocess
import logging

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger("{app_name}-sre")

PROMETHEUS_URL = os.environ.get("PROMETHEUS_URL", "http://prometheus:9090")
APP_NAME = os.environ.get("APP_NAME", "{app_name}")
PAGERDUTY_KEY = os.environ.get("PAGERDUTY_KEY", "")

FAILURE_PATTERNS = {{
    "CrashLoopBackOff": {{
        "prometheus_query": 'kube_pod_container_status_restarts_total{{app="{app_name}"}} > 3',
        "remediation": "kubectl rollout restart deployment/{app_name}",
        "severity": "critical",
    }},
    "HighMemory": {{
        "prometheus_query": 'container_memory_usage_bytes{{app="{app_name}"}} > 1800000000',
        "remediation": "kubectl scale deployment/{app_name} --replicas=3",
        "severity": "warning",
    }},
    "HighLatency": {{
        "prometheus_query": 'http_request_duration_seconds_p95{{app="{app_name}"}} > 2',
        "remediation": "kubectl scale deployment/{app_name} --replicas=3",
        "severity": "warning",
    }},
    # Domain-specific patterns for {domain}:
{domain_patterns}
}}


def query_prometheus(prom_query: str) -> list:
    \"\"\"Return Prometheus instant query result list; empty on any error.\"\"\"
    try:
        resp = requests.get(
            f"{{PROMETHEUS_URL}}/api/v1/query",
            params={{"query": prom_query}},
            timeout=10,
        )
        return resp.json().get("data", {{}}).get("result", [])
    except Exception as exc:
        logger.error("Prometheus query failed for %r: %s", prom_query, exc)
        return []


def apply_remediation(failure_name: str, command: str) -> bool:
    \"\"\"Run a kubectl remediation command. Returns True on success.\"\"\"
    try:
        result = subprocess.run(
            command.split(),
            check=True,
            timeout=60,
            capture_output=True,
            text=True,
        )
        logger.info("Remediation applied for %s: %s", failure_name, result.stdout.strip())
        return True
    except subprocess.CalledProcessError as exc:
        logger.error("Remediation command failed for %s: %s", failure_name, exc.stderr.strip())
        return False
    except Exception as exc:
        logger.error("Unexpected error applying remediation for %s: %s", failure_name, exc)
        return False


def page_oncall(failure_name: str, app_name: str, severity: str) -> None:
    \"\"\"Send a PagerDuty alert for failures that could not be auto-remediated.\"\"\"
    if not PAGERDUTY_KEY:
        logger.warning("No PAGERDUTY_KEY set — cannot page on-call for %s", failure_name)
        return
    try:
        payload = {{
            "routing_key": PAGERDUTY_KEY,
            "event_action": "trigger",
            "payload": {{
                "summary": f"[{{severity.upper()}}] {{failure_name}} detected in {{app_name}}",
                "source": f"sre-agent/{{app_name}}",
                "severity": severity,
            }},
        }}
        resp = requests.post(
            "https://events.pagerduty.com/v2/enqueue",
            json=payload,
            timeout=10,
        )
        logger.info("PagerDuty alert sent for %s: %s", failure_name, resp.status_code)
    except Exception as exc:
        logger.error("Failed to send PagerDuty alert for %s: %s", failure_name, exc)


def check_and_remediate() -> None:
    \"\"\"Main loop: check every failure pattern and remediate if triggered.\"\"\"
    logger.info("SRE agent starting check cycle for %s", APP_NAME)
    triggered_unresolved = []

    for failure_name, config in FAILURE_PATTERNS.items():
        result = query_prometheus(config["prometheus_query"])
        if not result:
            continue

        logger.warning("Detected %s for %s — applying remediation", failure_name, APP_NAME)
        success = apply_remediation(failure_name, config["remediation"])
        if not success:
            triggered_unresolved.append((failure_name, config["severity"]))

    # Page on-call for any failure we could not auto-remediate
    for failure_name, severity in triggered_unresolved:
        page_oncall(failure_name, APP_NAME, severity)

    logger.info("SRE agent check cycle complete — %d unresolved failure(s)", len(triggered_unresolved))


if __name__ == "__main__":
    check_and_remediate()
"""


def _build_playbook(app_name: str, domain: str, namespace: str) -> str:
    """Return a REMEDIATION_PLAYBOOK.md markdown string."""
    domain_section = ""
    if domain in _DOMAIN_PATTERNS:
        domain_note = {
            "healthcare": "SlowClaimsProcessing — auto-scales to 4 replicas when /claims p95 > 5s",
            "fintech": "TransactionQueueDepth — auto-scales when Kafka consumer lag > 1000 messages",
            "ecommerce": "InventoryAPITimeout — restarts deployment when /inventory p95 > 5s",
        }.get(domain, "")
        if domain_note:
            domain_section = f"\n- **{domain.title()} Domain Pattern**: {domain_note}"

    return f"""\
# Remediation Playbook — {app_name}

Generated by AetherOS P21 SRE Agent Generator.
Domain: {domain} | Namespace: {namespace}

## Overview

The `{app_name}-sre-agent` Kubernetes CronJob runs every 5 minutes, polling Prometheus
for the failure patterns listed below. When a pattern fires, it applies a pre-approved
kubectl remediation automatically. If the remediation command fails, an alert is sent
to PagerDuty for human escalation.

## Monitored Failure Patterns

| Failure | Prometheus Query | Auto-Remediation | Severity |
|---------|-----------------|------------------|----------|
| CrashLoopBackOff | `kube_pod_container_status_restarts_total{{app="{app_name}"}} > 3` | `kubectl rollout restart deployment/{app_name}` | critical |
| HighMemory | `container_memory_usage_bytes{{app="{app_name}"}} > 1800 MB` | Scale to 3 replicas | warning |
| HighLatency | `http_request_duration_seconds_p95{{app="{app_name}"}} > 2s` | Scale to 3 replicas | warning |{domain_section}

## Escalation Policy

1. **Auto-remediation attempted** — SRE agent applies the kubectl command.
2. **Command fails** — PagerDuty alert fired (severity matches the pattern).
3. **No PagerDuty key** — warning logged; alert NOT sent (set `PAGERDUTY_KEY` secret).
4. **After 3 failed rollouts** — manually investigate: `kubectl describe pods -l app={app_name} -n {namespace}`

## Accessing Prometheus Dashboards

- Prometheus UI: `kubectl port-forward svc/prometheus 9090:9090 -n monitoring`
- Query alerts: `http://localhost:9090/api/v1/rules`
- Query pattern: `http://localhost:9090/api/v1/query?query=<prometheus_query>`

## Manual Remediation Steps

### CrashLoopBackOff
```bash
kubectl rollout restart deployment/{app_name} -n {namespace}
kubectl rollout status deployment/{app_name} -n {namespace}
kubectl logs -l app={app_name} -n {namespace} --tail=100
```

### High Memory / High Latency
```bash
kubectl scale deployment/{app_name} --replicas=3 -n {namespace}
# To revert:
kubectl scale deployment/{app_name} --replicas=1 -n {namespace}
```

### Redeploy from scratch
```bash
kubectl rollout undo deployment/{app_name} -n {namespace}
kubectl rollout status deployment/{app_name} -n {namespace}
```

## SRE Agent Deployment

The CronJob and RBAC resources are in `k8s/sre-agent-cronjob.yaml`:

```bash
kubectl apply -f k8s/sre-agent-cronjob.yaml
# Verify:
kubectl get cronjob {app_name}-sre-agent -n {namespace}
```

The failure classifier script is mounted via ConfigMap. Update it by editing
`scripts/sre_failure_classifier.py` and re-applying the ConfigMap:

```bash
kubectl create configmap {app_name}-sre-scripts \\
  --from-file=sre_failure_classifier.py=scripts/sre_failure_classifier.py \\
  -n {namespace} --dry-run=client -o yaml | kubectl apply -f -
```
"""


async def run(phase_input: Any, memory_ctx: List[Dict], output_dir: Path) -> TaskResult:
    """Generate SRE operator scaffold: CronJob YAML, failure classifier, remediation playbook."""
    output_dir.mkdir(parents=True, exist_ok=True)

    data: dict = getattr(phase_input, "input_data", {}) or {}

    # Read app metadata from architecture or deployment config
    arch: dict = data.get("architecture") or data.get("architecture_json") or {}
    deployment_config: dict = data.get("deployment_config") or {}

    app_name: str = (
        data.get("project_name")
        or arch.get("project_name")
        or deployment_config.get("app_name")
        or "app"
    )
    # Kubernetes-safe name: lowercase, hyphens only
    app_name = app_name.lower().replace("_", "-").replace(" ", "-")

    domain: str = data.get("domain", "general")
    namespace: str = deployment_config.get("namespace") or arch.get("namespace") or "default"

    logger.info("p21_sre_agent: generating SRE scaffold for app=%s domain=%s ns=%s", app_name, domain, namespace)

    # ── Output directory layout ────────────────────────────────────────────────
    k8s_dir = output_dir / "k8s"
    scripts_dir = output_dir / "scripts"
    docs_dir = output_dir / "docs"
    k8s_dir.mkdir(exist_ok=True)
    scripts_dir.mkdir(exist_ok=True)
    docs_dir.mkdir(exist_ok=True)

    # ── 1. Kubernetes CronJob YAML ─────────────────────────────────────────────
    cronjob_yaml = _build_cronjob_yaml(app_name, namespace, domain)
    cronjob_path = k8s_dir / "sre-agent-cronjob.yaml"
    cronjob_path.write_text(cronjob_yaml)
    logger.info("p21_sre_agent: wrote %s", cronjob_path)

    # ── 2. Failure classifier Python script ────────────────────────────────────
    classifier_script = _build_classifier_script(app_name, domain)
    classifier_path = scripts_dir / "sre_failure_classifier.py"
    classifier_path.write_text(classifier_script)
    logger.info("p21_sre_agent: wrote %s", classifier_path)

    # ── 3. Remediation playbook ────────────────────────────────────────────────
    playbook_md = _build_playbook(app_name, domain, namespace)
    playbook_path = docs_dir / "REMEDIATION_PLAYBOOK.md"
    playbook_path.write_text(playbook_md)
    logger.info("p21_sre_agent: wrote %s", playbook_path)

    files_written = [
        "k8s/sre-agent-cronjob.yaml",
        "scripts/sre_failure_classifier.py",
        "docs/REMEDIATION_PLAYBOOK.md",
    ]

    # ── 4. G8: Extended sre/ directory (operator, classifier, remediation, canary, manifests)
    try:
        from aether_os.phases.p21_sre_agent.sre_generators import write_all_sre_artifacts
        sre_files = write_all_sre_artifacts(output_dir, app_name, namespace)
        files_written.extend(sre_files)
        logger.info("p21_sre_agent: wrote %d sre/ artifacts", len(sre_files))
    except Exception as exc:
        logger.warning("p21_sre_agent: sre/ artifact generation failed (non-critical): %s", exc)

    return TaskResult(
        output_path=str(output_dir),
        confidence=0.95,
        metadata={
            "app_name": app_name,
            "domain": domain,
            "namespace": namespace,
            "files_written": files_written,
        },
        issues=[],
        success=True,
    )
