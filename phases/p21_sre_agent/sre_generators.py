logger = logging.getLogger(__name__)

# Failure classification matrix (alertname → category)
FAILURE_MATRIX = {
    "CrashLoopBackOff": "code_crash",
    "OOMKilled": "memory_exhaustion",
    "HighLatency": "latency_degradation",
    "DBPoolExhausted": "connection_pool",
    "CertExpiring": "certificate",
    "HighErrorRate": "elevated_errors",
}


def write_sre_operator(sre_dir: Path, app_name: str, namespace: str) -> None:
    """Write sre/operator.py — watches AlertManager webhook and dispatches remediations."""
    operator_src = f'''\
#!/usr/bin/env python3
"""
SRE Kubernetes Operator — generated by AetherOS for {app_name}.

Watches an AlertManager webhook endpoint and dispatches automated remediations
based on the failure classification matrix.

Runs as a long-lived server inside a Kubernetes Deployment (see sre/manifests/).
"""
from __future__ import annotations

import hmac
import json
import logging
import os
from http.server import BaseHTTPRequestHandler, HTTPServer
from typing import Any, Dict

from failure_classifier import classify_alert
from remediation_generator import generate_remediation, apply_remediation

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger("{app_name}-sre-operator")

APP_NAME = os.environ.get("APP_NAME", "{app_name}")
NAMESPACE = os.environ.get("NAMESPACE", "{namespace}")
OPERATOR_PORT = int(os.environ.get("OPERATOR_PORT", "9876"))
# Shared secret AlertManager must send as 'Authorization: Bearer <token>'. Unset => every request is refused.
WEBHOOK_TOKEN = os.environ.get("WEBHOOK_TOKEN", "")
MAX_BODY = 1_000_000


class AlertWebhookHandler(BaseHTTPRequestHandler):
    """HTTP handler for AlertManager webhook POST requests."""

    def do_POST(self) -> None:  # noqa: N802
        supplied = self.headers.get("Authorization", "")
        if not WEBHOOK_TOKEN or not hmac.compare_digest(supplied, "Bearer " + WEBHOOK_TOKEN):
            self.send_response(401)
            self.end_headers()
            return
        try:
            length = min(int(self.headers.get("Content-Length", 0)), MAX_BODY)
            body = self.rfile.read(length)
            payload: Dict[str, Any] = json.loads(body.decode("utf-8"))
        except Exception as exc:
            logger.error("webhook: failed to parse request body: %s", exc)
            self.send_response(400)
            self.end_headers()
            return

        alerts = payload.get("alerts", [])
        logger.info("webhook: received %d alert(s)", len(alerts))

        for alert in alerts:
            alertname = alert.get("labels", {{}}).get("alertname", "Unknown")
            status = alert.get("status", "firing")
            if status != "firing":
                continue

            category = classify_alert(alertname, alert.get("labels", {{}}))
            logger.info("alert %s → category %s", alertname, category)

            remediation = generate_remediation(category, APP_NAME, NAMESPACE)
            if remediation:
                success = apply_remediation(remediation, alertname)
                if not success:
                    logger.warning("remediation failed for %s — manual intervention required", alertname)
            else:
                logger.warning("no remediation available for category %s", category)

        self.send_response(200)
        self.end_headers()
        self.wfile.write(b"ok")

    def log_message(self, format: str, *args: Any) -> None:  # noqa: A002
        logger.debug("http: " + format % args)


def main() -> None:
    server = HTTPServer(("0.0.0.0", OPERATOR_PORT), AlertWebhookHandler)
    logger.info("SRE Operator listening on port %d for app=%s", OPERATOR_PORT, APP_NAME)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        logger.info("SRE Operator shutting down")
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
'''
    (sre_dir / "operator.py").write_text(operator_src, encoding="utf-8")


def write_sre_failure_classifier(sre_dir: Path, app_name: str) -> None:
    """Write sre/failure_classifier.py — maps alert labels to failure categories."""
    categories_repr = repr(FAILURE_MATRIX)
    classifier_src = f'''\
#!/usr/bin/env python3
"""
SRE Failure Classifier — generated by AetherOS for {app_name}.

Maps AlertManager alert names and labels to structured failure categories.
Used by the SRE operator to select the correct automated remediation.
"""
from __future__ import annotations

import re
from typing import Dict

# Primary classification matrix: alertname → failure category
FAILURE_MATRIX: Dict[str, str] = {categories_repr}

# Latency threshold patterns (from alert annotations)
_LATENCY_PATTERN = re.compile(r"p95_latency.*?(\\d+(?:\\.\\d+)?)\\s*ms", re.IGNORECASE)
_CERT_DAYS_PATTERN = re.compile(r"cert.*?(\\d+)\\s*days?", re.IGNORECASE)
_ERROR_RATE_PATTERN = re.compile(r"error_rate.*?(\\d+(?:\\.\\d+)?)\\s*%", re.IGNORECASE)


def classify_alert(alertname: str, labels: Dict[str, str]) -> str:
    """
    Classify an alert into a failure category.

    Returns one of:
      code_crash | memory_exhaustion | latency_degradation |
      connection_pool | certificate | elevated_errors | unknown

    Args:
        alertname: the AlertManager alertname label value
        labels: full label dict from the alert
    """
    # Direct match
    if alertname in FAILURE_MATRIX:
        return FAILURE_MATRIX[alertname]

    # Pattern-based fallback using annotations
    annotations_str = " ".join(str(v) for v in labels.values())

    if _LATENCY_PATTERN.search(annotations_str):
        match = _LATENCY_PATTERN.search(annotations_str)
        if match and float(match.group(1)) > 500:
            return "latency_degradation"

    if _CERT_DAYS_PATTERN.search(annotations_str):
        match = _CERT_DAYS_PATTERN.search(annotations_str)
        if match and int(match.group(1)) < 7:
            return "certificate"

    if _ERROR_RATE_PATTERN.search(annotations_str):
        match = _ERROR_RATE_PATTERN.search(annotations_str)
        if match and float(match.group(1)) > 5.0:
            return "elevated_errors"

    return "unknown"
'''
    (sre_dir / "failure_classifier.py").write_text(classifier_src, encoding="utf-8")


def write_sre_remediation_generator(sre_dir: Path, app_name: str, namespace: str) -> None:
    """Write sre/remediation_generator.py — selects and applies kubectl remediation."""
    remediation_src = f'''\
#!/usr/bin/env python3
"""
SRE Remediation Generator — generated by AetherOS for {app_name}.

Selects the appropriate kubectl command for a failure category and applies it.
Falls back to an LLM-generated remediation suggestion for unknown categories.
"""
from __future__ import annotations

import logging
import os
from typing import Optional

{K8S_API_SRC}
logger = logging.getLogger("{app_name}-remediation")

APP_NAME = os.environ.get("APP_NAME", "{app_name}")
NAMESPACE = os.environ.get("NAMESPACE", "{namespace}")

# Pre-approved kubectl remediations per failure category
_REMEDIATIONS = {{
    "code_crash": "kubectl rollout restart deployment/{{app}} -n {{ns}}",
    "memory_exhaustion": "kubectl scale deployment/{{app}} --replicas=2 -n {{ns}}",
    "latency_degradation": "kubectl scale deployment/{{app}} --replicas=3 -n {{ns}}",
    "connection_pool": "kubectl rollout restart deployment/{{app}} -n {{ns}}",
    # certificate: deliberately absent. Deleting a TLS secret is destructive and needs a human.
    "elevated_errors": "kubectl rollout restart deployment/{{app}} -n {{ns}}",
}}


def generate_remediation(category: str, app_name: str, namespace: str) -> Optional[str]:
    """
    Return the kubectl command for a failure category, or None if unknown.

    Args:
        category: failure category from failure_classifier.classify_alert()
        app_name: Kubernetes deployment name
        namespace: Kubernetes namespace
    """
    template = _REMEDIATIONS.get(category)
    if not template:
        return None
    return template.format(app=app_name, ns=namespace)


def apply_remediation(command: str, alert_name: str) -> bool:
    """
    Execute a pre-approved remediation through the Kubernetes API (no kubectl binary).

    Returns True on success, False on failure.
    Always logs the outcome. Never raises.
    """
    try:
        run_remediation(command)
        logger.info("remediation applied for %s: %s", alert_name, command)
        return True
    except Exception as exc:
        logger.error("remediation failed for %s: %s", alert_name, exc)
        return False
'''
    (sre_dir / "remediation_generator.py").write_text(remediation_src, encoding="utf-8")


