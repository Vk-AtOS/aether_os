def write_all_sre_artifacts(output_dir: Path, app_name: str, namespace: str) -> list:
    """
    Write the complete sre/ directory structure to output_dir.

    Returns list of relative paths written.
    """
    sre_dir = output_dir / "sre"
    sre_dir.mkdir(exist_ok=True)

    files_written = []

    try:
        write_sre_operator(sre_dir, app_name, namespace)
        files_written.append("sre/operator.py")
    except Exception as exc:
        logger.warning("p21: write_sre_operator failed: %s", exc)

    try:
        write_sre_failure_classifier(sre_dir, app_name)
        files_written.append("sre/failure_classifier.py")
    except Exception as exc:
        logger.warning("p21: write_sre_failure_classifier failed: %s", exc)

    try:
        write_sre_remediation_generator(sre_dir, app_name, namespace)
        files_written.append("sre/remediation_generator.py")
    except Exception as exc:
        logger.warning("p21: write_sre_remediation_generator failed: %s", exc)

    try:
        write_sre_canary_runner(sre_dir, app_name, namespace)
        files_written.append("sre/canary_runner.py")
    except Exception as exc:
        logger.warning("p21: write_sre_canary_runner failed: %s", exc)

    try:
        write_sre_manifests(sre_dir, app_name, namespace)
        files_written.extend([
            "sre/manifests/operator-deployment.yaml",
            "sre/manifests/sre-rbac.yaml",
            "sre/manifests/alertmanager-webhook.yaml",
        ])
    except Exception as exc:
        logger.warning("p21: write_sre_manifests failed: %s", exc)

    logger.info("p21: wrote %d sre/ artifacts", len(files_written))
    return files_written
