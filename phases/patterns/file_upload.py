from __future__ import annotations

import os
import uuid
from pathlib import Path

import aiofiles
from fastapi import APIRouter, Depends, File, HTTPException, UploadFile, status
from fastapi.responses import FileResponse

router = APIRouter(prefix="/uploads", tags=["uploads"])

UPLOAD_DIR = Path(os.getenv("UPLOAD_DIR", "/tmp/uploads"))
MAX_UPLOAD_MB = int(os.getenv("MAX_UPLOAD_MB", "10"))
MAX_UPLOAD_BYTES = MAX_UPLOAD_MB * 1024 * 1024
ALLOWED_TYPES = {
    "image/jpeg", "image/png", "image/gif", "image/webp",
    "application/pdf",
    "text/plain", "text/csv",
    "application/msword",
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
}

UPLOAD_DIR.mkdir(parents=True, exist_ok=True)

# In-memory registry (replace with DB in production)
_registry: dict[str, dict] = {}


@router.post("/", status_code=201)
async def upload_file(file: UploadFile = File(...)) -> dict:
    """Upload a file. Returns file metadata including download URL."""
    if file.content_type not in ALLOWED_TYPES:
        raise HTTPException(status_code=415, detail=f"File type not allowed: {file.content_type}")

    contents = await file.read()
    if len(contents) > MAX_UPLOAD_BYTES:
        raise HTTPException(status_code=413, detail=f"File exceeds {MAX_UPLOAD_MB}MB limit")

    file_id = str(uuid.uuid4())
    suffix = Path(file.filename or "upload").suffix or ""
    dest = UPLOAD_DIR / f"{file_id}{suffix}"

    async with aiofiles.open(dest, "wb") as f:
        await f.write(contents)

    record = {
        "id": file_id,
        "filename": file.filename,
        "content_type": file.content_type,
        "size": len(contents),
        "path": str(dest),
        "url": f"/uploads/{file_id}",
    }
    _registry[file_id] = record
    return record


@router.get("/{file_id}")
async def download_file(file_id: str) -> FileResponse:
    """Download an uploaded file by ID."""
    record = _registry.get(file_id)
    if not record:
        raise HTTPException(status_code=404, detail="File not found")
    path = Path(record["path"])
    if not path.exists():
        raise HTTPException(status_code=410, detail="File no longer available")
    return FileResponse(path=path, filename=record["filename"], media_type=record["content_type"])


@router.delete("/{file_id}", status_code=204)
async def delete_file(file_id: str) -> None:
    """Delete an uploaded file."""
    record = _registry.pop(file_id, None)
    if not record:
        raise HTTPException(status_code=404, detail="File not found")
    path = Path(record["path"])
    if path.exists():
        path.unlink()
