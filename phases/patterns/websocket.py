class ConnectionManager:
    """Thread-safe WebSocket room manager."""

    def __init__(self) -> None:
        self._rooms: Dict[str, List[WebSocket]] = {}
        self._lock = asyncio.Lock()

    async def connect(self, room_id: str, ws: WebSocket) -> None:
        await ws.accept()
        async with self._lock:
            self._rooms.setdefault(room_id, []).append(ws)
        logger.info("WS connect: room=%s connections=%d", room_id, len(self._rooms[room_id]))

    async def disconnect(self, room_id: str, ws: WebSocket) -> None:
        async with self._lock:
            conns = self._rooms.get(room_id, [])
            if ws in conns:
                conns.remove(ws)
            if not conns:
                self._rooms.pop(room_id, None)

    async def broadcast(self, room_id: str, message: dict) -> int:
        """Broadcast JSON message to all connections in a room. Returns count of recipients."""
        conns = list(self._rooms.get(room_id, []))
        dead: List[WebSocket] = []
        for ws in conns:
            try:
                await ws.send_json(message)
            except Exception as e:
                logger.warning("websocket broadcast: send failed, marking connection dead: %s", e)
                dead.append(ws)
        # Clean up dead connections
        if dead:
            async with self._lock:
                for ws in dead:
                    self._rooms.get(room_id, []).remove(ws) if ws in self._rooms.get(room_id, []) else None
        return len(conns) - len(dead)

    def room_count(self, room_id: str) -> int:
        return len(self._rooms.get(room_id, []))


