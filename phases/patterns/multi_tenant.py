@router.post("/{org_id}/invite", status_code=201)
async def invite_to_org(org_id: str, body: dict, request: Request):
    """Create a signed invite URL for an email address.

    Body: {email: str, role: "admin"|"member"}
    Returns: {invite_url: str, expires_in_hours: int}
    """
    _require_deps()
    from sqlalchemy import select
    current_user = await _current_user_dep(request)
    async for db in _db_dep():
        membership = await db.execute(
            select(OrganizationMember).where(
                OrganizationMember.org_id == org_id,
                OrganizationMember.user_id == current_user.id,
                OrganizationMember.role.in_(["owner", "admin"]),
            )
        )
        if not membership.scalar_one_or_none():
            raise HTTPException(403, "owner or admin role required to invite")
        role = body.get("role", "member")
        if role not in ("owner", "admin", "member"):
            raise HTTPException(422, "role must be owner, admin, or member")
        token = _create_invite_token(str(org_id), role, current_user.id)
        base_url = os.getenv("APP_BASE_URL", "http://localhost:8000")
        invite_url = f"{base_url}/orgs/accept-invite?token={token}"
        logger.info(
            "org invite created: org=%s by=%s role=%s", org_id, current_user.id, role
        )
        return {"invite_url": invite_url, "expires_in_hours": _INVITE_EXPIRY_HOURS}


@router.post("/accept-invite", status_code=200)
async def accept_invite(body: dict, request: Request):
    """Accept an invite token and add the current user to the org.

    Body: {token: str}
    """
    _require_deps()
    from sqlalchemy import select
    token = body.get("token", "")
    if not token:
        raise HTTPException(422, "token is required")
    try:
        payload = _decode_invite_token(token)
    except Exception as exc:
        logger.warning("accept_invite: invalid/expired token: %s", exc)
        raise HTTPException(400, "invite token is invalid or has expired")
    org_id = payload["org_id"]
    role = payload.get("role", "member")
    current_user = await _current_user_dep(request)
    async for db in _db_dep():
        existing = await db.execute(
            select(OrganizationMember).where(
                OrganizationMember.org_id == org_id,
                OrganizationMember.user_id == current_user.id,
            )
        )
        if existing.scalar_one_or_none():
            return {"status": "already_member", "org_id": org_id}
        member = OrganizationMember(
            id=uuid.uuid4(),
            org_id=org_id,
            user_id=current_user.id,
            role=role,
        )
        db.add(member)
        await db.commit()
        logger.info("user %s joined org %s as %s via invite", current_user.id, org_id, role)
        return {"status": "joined", "org_id": org_id, "role": role}
