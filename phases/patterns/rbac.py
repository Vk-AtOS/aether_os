oauth2_scheme = OAuth2PasswordBearer(tokenUrl="/auth/login")

# Role hierarchy: higher index = more permissions
_ROLE_HIERARCHY = ["viewer", "member", "manager", "admin", "superadmin"]


def _role_level(role: str) -> int:
    try:
        return _ROLE_HIERARCHY.index(role.lower())
    except ValueError:
        return -1


async def get_current_user(token: str = Depends(oauth2_scheme)) -> dict:
    payload = decode_token(token)
    if not payload:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or expired token",
            headers={"WWW-Authenticate": "Bearer"},
        )
    return payload


def require_role(minimum_role: str):
    """Dependency factory that enforces a minimum role level."""
    min_level = _role_level(minimum_role)
    if min_level < 0:
        raise ValueError(f"Unknown role: {minimum_role}")

    async def _check(user: dict = Depends(get_current_user)) -> None:
        user_role = user.get("role", "viewer")
        if _role_level(user_role) < min_level:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail=f"Requires {minimum_role} role or higher (current: {user_role})",
            )

    return _check


def require_any_role(*roles: str):
    """Dependency that accepts any of the specified roles."""
    allowed = set(r.lower() for r in roles)

    async def _check(user: dict = Depends(get_current_user)) -> None:
        user_role = (user.get("role") or "viewer").lower()
        if user_role not in allowed:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail=f"Requires one of: {', '.join(sorted(allowed))} (current: {user_role})",
            )

    return _check


