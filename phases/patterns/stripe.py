from fastapi import APIRouter, HTTPException, Request, Response, status

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/billing", tags=["billing"])

_STRIPE_SECRET_KEY = os.getenv("STRIPE_SECRET_KEY", "")
_WEBHOOK_SECRET = os.getenv("STRIPE_WEBHOOK_SECRET", "")


def _get_stripe():
    if not _STRIPE_SECRET_KEY:
        raise HTTPException(503, "Stripe not configured (STRIPE_SECRET_KEY missing)")
    try:
        import stripe as _stripe
        _stripe.api_key = _STRIPE_SECRET_KEY
        return _stripe
    except ImportError:
        raise HTTPException(503, "stripe package not installed")


@router.post("/checkout", status_code=200)
async def create_checkout(body: dict) -> dict:
    """
    Create a Stripe Checkout Session.
    Body: {price_id: str, success_url: str, cancel_url: str, customer_email?: str}
    """
    stripe = _get_stripe()
    price_id = body.get("price_id")
    success_url = body.get("success_url", "https://example.com/success")
    cancel_url = body.get("cancel_url", "https://example.com/cancel")
    customer_email = body.get("customer_email")

    if not price_id:
        raise HTTPException(422, "price_id is required")

    kwargs = dict(
        payment_method_types=["card"],
        line_items=[{"price": price_id, "quantity": 1}],
        mode="subscription",
        success_url=success_url + "?session_id={CHECKOUT_SESSION_ID}",
        cancel_url=cancel_url,
    )
    if customer_email:
        kwargs["customer_email"] = customer_email

    try:
        session = stripe.checkout.Session.create(**kwargs)
        return {"checkout_url": session.url, "session_id": session.id}
    except Exception as exc:
        logger.error("Stripe checkout error: %s", exc)
        raise HTTPException(502, f"Stripe error: {exc}")


@router.post("/webhook", status_code=200)
async def stripe_webhook(request: Request) -> dict:
    """
    Stripe webhook endpoint — verifies signature and handles events.
    Configure this URL in the Stripe dashboard.
    """
    payload = await request.body()
    sig_header = request.headers.get("stripe-signature", "")

    if not _WEBHOOK_SECRET:
        logger.warning("STRIPE_WEBHOOK_SECRET not set — rejecting unsigned webhook event")
        raise HTTPException(status_code=400, detail="Stripe webhook secret not configured")

    stripe = _get_stripe()
    try:
        event = stripe.Webhook.construct_event(payload, sig_header, _WEBHOOK_SECRET)
    except stripe.error.SignatureVerificationError as exc:
        logger.warning("stripe_webhook: signature verification failed: %s", exc)
        raise HTTPException(status_code=400, detail="Invalid webhook signature")
    except Exception as exc:
        logger.warning("stripe_webhook: failed to construct event: %s", exc)
        raise HTTPException(status_code=400, detail=f"Webhook error: {exc}")

    event_type = event.get("type", "")
    logger.info("Stripe webhook: %s", event_type)

    # Handle key events
    if event_type == "checkout.session.completed":
        session = event["data"]["object"]
        customer_id = session.get("customer")
        subscription_id = session.get("subscription")
        logger.info("Checkout completed: customer=%s subscription=%s", customer_id, subscription_id)
        if customer_id:
            try:
                from src.database import get_db  # type: ignore
                from sqlalchemy import text
                async with get_db() as db:
                    await db.execute(
                        text("UPDATE users SET stripe_customer_id = :cid, plan = 'pro', "
                             "subscription_id = :sid WHERE stripe_customer_id = :cid OR stripe_customer_id IS NULL"),
                        {"cid": customer_id, "sid": subscription_id},
                    )
                    await db.commit()
                logger.info("DB updated: customer %s activated on pro plan", customer_id)
            except Exception as db_exc:
                logger.error("Failed to update subscription in DB: %s", db_exc)

    elif event_type in ("customer.subscription.deleted", "customer.subscription.updated"):
        sub = event["data"]["object"]
        sub_status = sub.get("status", "unknown")
        customer_id = sub.get("customer")
        plan = "free" if sub_status in ("canceled", "unpaid", "incomplete_expired") else "pro"
        logger.info("Subscription %s: status=%s → plan=%s", sub.get("id"), sub_status, plan)
        if customer_id:
            try:
                from src.database import get_db  # type: ignore
                from sqlalchemy import text
                async with get_db() as db:
                    await db.execute(
                        text("UPDATE users SET plan = :plan, subscription_status = :status "
                             "WHERE stripe_customer_id = :cid"),
                        {"plan": plan, "status": sub_status, "cid": customer_id},
                    )
                    await db.commit()
                logger.info("DB updated: customer %s plan=%s", customer_id, plan)
            except Exception as db_exc:
                logger.error("Failed to update plan in DB: %s", db_exc)

    elif event_type == "invoice.payment_failed":
        invoice = event["data"]["object"]
        customer_id = invoice.get("customer")
        attempt_count = invoice.get("attempt_count", 1)
        next_payment_attempt = invoice.get("next_payment_attempt")
        logger.warning("Payment failed: customer=%s attempt=%s", customer_id, attempt_count)
        # Downgrade to free after 3 failed payment attempts
        if customer_id:
            try:
                from src.database import get_db  # type: ignore
                from sqlalchemy import text
                async with get_db() as db:
                    if attempt_count >= 3:
                        await db.execute(
                            text("UPDATE users SET plan = 'free', subscription_status = 'past_due' "
                                 "WHERE stripe_customer_id = :cid"),
                            {"cid": customer_id},
                        )
                        await db.commit()
                        logger.warning("Customer %s downgraded to free after %s failed payments", customer_id, attempt_count)
                    else:
                        # Notify user of failed payment
                        row = await db.execute(
                            text("SELECT email FROM users WHERE stripe_customer_id = :cid LIMIT 1"),
                            {"cid": customer_id},
                        )
                        user_row = row.fetchone()
                        if user_row:
                            import smtplib, email.mime.text as _emt
                            _smtp_host = os.getenv("SMTP_HOST", "")
                            if _smtp_host:
                                try:
                                    msg = _emt.MIMEText(
                                        f"Payment failed for your subscription (attempt {attempt_count})."
                                        f" Please update your payment method to avoid service interruption.",
                                        "plain",
                                    )
                                    msg["Subject"] = "Action required: Payment failed"
                                    msg["From"] = os.getenv("SMTP_FROM", "noreply@example.com")
                                    msg["To"] = user_row[0]
                                    with smtplib.SMTP(os.getenv("SMTP_HOST", "localhost"), int(os.getenv("SMTP_PORT", "587"))) as s:
                                        if os.getenv("SMTP_USER"):
                                            s.starttls()
                                            s.login(os.getenv("SMTP_USER", ""), os.getenv("SMTP_PASSWORD", ""))
                                        s.send_message(msg)
                                    logger.info("Dunning email sent to %s", user_row[0])
                                except Exception as mail_exc:
                                    logger.warning("Dunning email failed: %s", mail_exc)
            except Exception as db_exc:
                logger.error("Failed to handle payment_failed event: %s", db_exc)

    return {"received": True, "event": event_type}


@router.get("/subscription")
async def get_subscription(customer_id: str) -> dict:
    """Get active subscription details for a Stripe customer ID."""
    stripe = _get_stripe()
    try:
        subs = stripe.Subscription.list(customer=customer_id, status="active", limit=1)
        if not subs.data:
            return {"status": "inactive", "plan": "free"}
        sub = subs.data[0]
        return {
            "status": sub.status,
            "plan": sub.items.data[0].price.nickname if sub.items.data else "unknown",
            "current_period_end": sub.current_period_end,
            "cancel_at_period_end": sub.cancel_at_period_end,
        }
    except Exception as exc:
        raise HTTPException(502, f"Stripe error: {exc}")


@router.post("/cancel", status_code=200)
async def cancel_subscription(body: dict) -> dict:
    """Cancel the active subscription for a customer (at period end)."""
    stripe = _get_stripe()
    customer_id = body.get("customer_id")
    if not customer_id:
        raise HTTPException(422, "customer_id required")
    try:
        subs = stripe.Subscription.list(customer=customer_id, status="active", limit=1)
        if not subs.data:
            raise HTTPException(404, "No active subscription found")
        updated = stripe.Subscription.modify(subs.data[0].id, cancel_at_period_end=True)
        return {"status": "cancellation_scheduled", "cancel_at": updated.cancel_at}
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(502, f"Stripe error: {exc}")


@router.get("/invoices")
async def list_invoices(customer_id: str, limit: int = 10) -> dict:
    """List recent invoices for a Stripe customer."""
    stripe = _get_stripe()
    try:
        invoices = stripe.Invoice.list(customer=customer_id, limit=min(limit, 100))
        return {
            "invoices": [
                {
                    "id": inv.id,
                    "number": inv.number,
                    "amount_due": inv.amount_due,
                    "amount_paid": inv.amount_paid,
                    "currency": inv.currency,
                    "status": inv.status,
                    "created": inv.created,
                    "hosted_invoice_url": inv.hosted_invoice_url,
                    "invoice_pdf": inv.invoice_pdf,
                }
                for inv in invoices.data
            ]
        }
    except Exception as exc:
        raise HTTPException(502, f"Stripe error: {exc}")


