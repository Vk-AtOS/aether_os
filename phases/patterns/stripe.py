"""Stripe billing pattern — checkout, webhooks, subscriptions."""
from __future__ import annotations

STRIPE_REQUIREMENTS = ["stripe>=8.0"]

STRIPE_CODE = '''\
"""
Stripe billing router — checkout sessions, webhook handling, subscription status.
Generated by AetherOS pattern library.

Set environment variables:
  STRIPE_SECRET_KEY      — Stripe secret key (sk_live_... or sk_test_...)
  STRIPE_WEBHOOK_SECRET  — Webhook signing secret (whsec_...)

Routes:
  POST /billing/checkout        — create a Stripe Checkout session
  POST /billing/webhook         — Stripe webhook handler (verify signature)
  GET  /billing/subscription    — get current subscription status
  POST /billing/cancel          — cancel active subscription
"""
from __future__ import annotations

import json
import logging
import os

from fastapi import APIRouter, HTTPException, Request, Response, status

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/billing", tags=["billing"])

_STRIPE_SECRET_KEY = os.getenv("STRIPE_SECRET_KEY", "")
_WEBHOOK_SECRET = os.getenv("STRIPE_WEBHOOK_SECRET", "")


def _get_stripe():
    if not _STRIPE_SECRET_KEY:
        raise HTTPException(503, "Stripe not configured (STRIPE_SECRET_KEY missing)")
    try:
        import stripe as _stripe
        _stripe.api_key = _STRIPE_SECRET_KEY
        return _stripe
    except ImportError:
        raise HTTPException(503, "stripe package not installed")


@router.post("/checkout", status_code=200)
async def create_checkout(body: dict) -> dict:
    """
    Create a Stripe Checkout Session.
    Body: {price_id: str, success_url: str, cancel_url: str, customer_email?: str}
    """
    stripe = _get_stripe()
    price_id = body.get("price_id")
    success_url = body.get("success_url", "https://example.com/success")
    cancel_url = body.get("cancel_url", "https://example.com/cancel")
    customer_email = body.get("customer_email")

    if not price_id:
        raise HTTPException(422, "price_id is required")

    kwargs = dict(
        payment_method_types=["card"],
        line_items=[{"price": price_id, "quantity": 1}],
        mode="subscription",
        success_url=success_url + "?session_id={CHECKOUT_SESSION_ID}",
        cancel_url=cancel_url,
    )
    if customer_email:
        kwargs["customer_email"] = customer_email

    try:
        session = stripe.checkout.Session.create(**kwargs)
        return {"checkout_url": session.url, "session_id": session.id}
    except Exception as exc:
        logger.error("Stripe checkout error: %s", exc)
        raise HTTPException(502, f"Stripe error: {exc}")


@router.post("/webhook", status_code=200)
async def stripe_webhook(request: Request) -> dict:
    """
    Stripe webhook endpoint — verifies signature and handles events.
    Configure this URL in the Stripe dashboard.
    """
    payload = await request.body()
    sig_header = request.headers.get("stripe-signature", "")

    if not _WEBHOOK_SECRET:
        logger.warning("STRIPE_WEBHOOK_SECRET not set — skipping signature verification")
        event = json.loads(payload)
    else:
        stripe = _get_stripe()
        try:
            event = stripe.Webhook.construct_event(payload, sig_header, _WEBHOOK_SECRET)
        except Exception as exc:
            raise HTTPException(400, f"Webhook signature invalid: {exc}")

    event_type = event.get("type", "")
    logger.info("Stripe webhook: %s", event_type)

    # Handle key events
    if event_type == "checkout.session.completed":
        session = event["data"]["object"]
        customer_id = session.get("customer")
        logger.info("Checkout completed: customer=%s", customer_id)
        # TODO: update subscription status in DB

    elif event_type in ("customer.subscription.deleted", "customer.subscription.updated"):
        sub = event["data"]["object"]
        logger.info("Subscription %s: status=%s", sub.get("id"), sub.get("status"))
        # TODO: update plan in DB based on sub.status

    elif event_type == "invoice.payment_failed":
        invoice = event["data"]["object"]
        logger.warning("Payment failed: customer=%s", invoice.get("customer"))
        # TODO: send dunning email

    return {"received": True, "event": event_type}


@router.get("/subscription")
async def get_subscription(customer_id: str) -> dict:
    """Get active subscription details for a Stripe customer ID."""
    stripe = _get_stripe()
    try:
        subs = stripe.Subscription.list(customer=customer_id, status="active", limit=1)
        if not subs.data:
            return {"status": "inactive", "plan": "free"}
        sub = subs.data[0]
        return {
            "status": sub.status,
            "plan": sub.items.data[0].price.nickname if sub.items.data else "unknown",
            "current_period_end": sub.current_period_end,
            "cancel_at_period_end": sub.cancel_at_period_end,
        }
    except Exception as exc:
        raise HTTPException(502, f"Stripe error: {exc}")


@router.post("/cancel", status_code=200)
async def cancel_subscription(body: dict) -> dict:
    """Cancel the active subscription for a customer (at period end)."""
    stripe = _get_stripe()
    customer_id = body.get("customer_id")
    if not customer_id:
        raise HTTPException(422, "customer_id required")
    try:
        subs = stripe.Subscription.list(customer=customer_id, status="active", limit=1)
        if not subs.data:
            raise HTTPException(404, "No active subscription found")
        updated = stripe.Subscription.modify(subs.data[0].id, cancel_at_period_end=True)
        return {"status": "cancellation_scheduled", "cancel_at": updated.cancel_at}
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(502, f"Stripe error: {exc}")
'''
