router = APIRouter(prefix="/agent", tags=["agent"])


def _sse(event: dict) -> str:
    return "data: " + json.dumps(event) + "\n\n"


@router.post("/run")
async def run_agent(body: dict, user: dict = Depends(_current_user)):
    """Stream an agent run as SSE.

    Body: {messages: [{role, content}], conversation_id: optional id of a conversation to continue}
    """
    messages = body.get("messages") or []
    if not messages or not all(isinstance(m, dict) and m.get("role") in ("user", "assistant", "system") for m in messages):
        raise HTTPException(422, "messages must be a non-empty list of {role, content}")
    try:
        llm_client = _build_llm_client()
    except RuntimeError as exc:
        raise HTTPException(503, str(exc))

    loop = AgentLoop(llm_client, build_default_registry())
    user_id = int(user["id"])

    async def event_generator():
        reply = ""
        try:
            async for event in loop.run(messages):
                if event["type"] == "response":
                    reply = event["content"]
                if event["type"] == "done":
                    try:
                        event["conversation_id"] = await _save_conversation(
                            user_id, body.get("conversation_id"), messages, reply)
                    except Exception as exc:
                        logger.warning("agent: conversation not saved: %s", exc)
                yield _sse(event)
        except Exception as exc:
            logger.error("agent /run stream error: %s", exc)
            yield _sse({"type": "error", "content": str(exc)})

    return StreamingResponse(event_generator(), media_type="text/event-stream")


async def _own_conversation(db: AsyncSession, conversation_id: str, user: dict) -> AgentConversation:
    conv = await db.get(AgentConversation, conversation_id)
    if conv is None or conv.created_by != int(user["id"]):
        raise HTTPException(404, "conversation not found")     # 404 for another user's too: no existence leak
    return conv


@router.get("/conversations")
async def list_conversations(page: int = 1, page_size: int = 20, user: dict = Depends(_current_user),
                             db: AsyncSession = Depends(get_db)):
    """List the current user's agent conversations (paginated)."""
    page, page_size = max(page, 1), min(max(page_size, 1), 100)
    result = await db.execute(
        select(AgentConversation).where(AgentConversation.created_by == int(user["id"]))
        .order_by(AgentConversation.updated_at.desc()).limit(page_size).offset((page - 1) * page_size)
    )
    return {
        "page": page, "page_size": page_size,
        "items": [{"id": c.id, "title": c.title, "created_at": c.created_at.isoformat(),
                   "updated_at": c.updated_at.isoformat(), "message_count": len(c.messages or [])}
                  for c in result.scalars().all()],
    }


@router.get("/conversations/{conversation_id}")
async def get_conversation(conversation_id: str, user: dict = Depends(_current_user),
                           db: AsyncSession = Depends(get_db)):
    """Get a conversation with all messages."""
    conv = await _own_conversation(db, conversation_id, user)
    return {"id": conv.id, "title": conv.title, "messages": conv.messages,
            "created_at": conv.created_at.isoformat(), "updated_at": conv.updated_at.isoformat()}


@router.delete("/conversations/{conversation_id}", status_code=204)
async def delete_conversation(conversation_id: str, user: dict = Depends(_current_user),
                              db: AsyncSession = Depends(get_db)):
    """Delete a conversation."""
    conv = await _own_conversation(db, conversation_id, user)
