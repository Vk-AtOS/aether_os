def _build_llm_client():
    """Return an LLM client — tries OpenAI first, then Anthropic."""
    model = os.getenv("AGENT_MODEL", "")
    openai_key = os.getenv("OPENAI_API_KEY", "")
    anthropic_key = os.getenv("ANTHROPIC_API_KEY", "")

    if openai_key:
        try:
            import openai as _openai
            client = _openai.AsyncOpenAI(api_key=openai_key)
            effective_model = model or "gpt-4o"
            return ("openai", client, effective_model)
        except ImportError as exc:
            logger.warning("agent: openai package not installed: %s", exc)

    if anthropic_key:
        try:
            import anthropic as _anthropic
            client = _anthropic.AsyncAnthropic(api_key=anthropic_key)
            effective_model = model or "claude-3-5-sonnet-20241022"
            return ("anthropic", client, effective_model)
        except ImportError as exc:
            logger.warning("agent: anthropic package not installed: %s", exc)

    raise RuntimeError(
        "No LLM API key configured. Set OPENAI_API_KEY or ANTHROPIC_API_KEY."
    )


