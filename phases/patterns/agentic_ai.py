@router.post("/run")
async def run_agent(body: dict, request: Request):
    """Stream an agent run as SSE.

    Body: {messages: [{role, content}], tools: [optional override tool names list]}

    Events emitted:
      data: {"type": "thinking",    "content": "..."}
      data: {"type": "tool_call",   "content": "{name, args}"}
      data: {"type": "tool_result", "content": "..."}
      data: {"type": "response",    "content": "..."}
      data: {"type": "done",        "content": ""}
    """
    messages = body.get("messages", [])
    if not messages:
        raise HTTPException(422, "messages list is required")

    try:
        llm_client_tuple = _build_llm_client()
    except RuntimeError as exc:
        raise HTTPException(503, str(exc))

    loop = AgentLoop(llm_client_tuple, _default_registry)

    async def event_generator():
        try:
            async for event in loop.run(messages):
                yield {"data": json.dumps(event)}
        except Exception as exc:
            logger.error("agent /run SSE error: %s", exc)
            yield {"data": json.dumps({"type": "error", "content": str(exc)})}

    return EventSourceResponse(event_generator())


