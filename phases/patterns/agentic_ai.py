class AgentLoop:
    """ReAct-style agent loop: think, call tools, observe, repeat.

    Yields dicts: {"type": "tool_call"|"tool_result"|"response"|"error"|"done", "content": "..."}
    """

    def __init__(self, llm_client: Any, tool_registry: ToolRegistry, max_iterations: int = 10) -> None:
        self._llm_client = llm_client
        self._registry = tool_registry
        self._max_iterations = max_iterations

    async def _call_llm(self, provider: str, client: Any, model: str, history: list, tools: list):
        """One model turn -> (text, [(call_id, name, args)])."""
        if provider == "openai":
            response = await client.chat.completions.create(
                model=model, messages=history, **({"tools": tools, "tool_choice": "auto"} if tools else {}),
            )
            msg = response.choices[0].message
            calls = []
            for tc in msg.tool_calls or []:
                try:
                    args = json.loads(tc.function.arguments or "{}")
                except ValueError as exc:
                    logger.warning("agent: could not parse tool arguments: %s", exc)
                    args = {}
                calls.append((tc.id, tc.function.name, args))
            return msg.content or "", calls
        if provider == "anthropic":
            system = "\n".join(m["content"] for m in history if m["role"] == "system")
            kwargs: dict = {"model": model, "max_tokens": 4096, "messages": [m for m in history if m["role"] != "system"]}
            if system:
                kwargs["system"] = system
            if tools:
                kwargs["tools"] = [
                    {"name": t["function"]["name"], "description": t["function"]["description"],
                     "input_schema": t["function"]["parameters"]} for t in tools
                ]
            response = await client.messages.create(**kwargs)
            text = "".join(b.text for b in response.content if b.type == "text")
            return text, [(b.id, b.name, b.input or {}) for b in response.content if b.type == "tool_use"]
        raise ValueError(f"Unknown provider: {provider}")

    async def _run_tool(self, name: str, args: dict) -> str:
        tool = self._registry.get(name)
        if tool is None:
            return f"Error: tool '{name}' not found"
        try:
            result = tool.handler(**args)
            if asyncio.iscoroutine(result):
                result = await result
            return str(result)
        except Exception as exc:
            logger.warning("agent: tool '%s' raised: %s", name, exc)
            return f"Tool error: {exc}"

    async def run(self, messages: list[dict]) -> AsyncGenerator[dict, None]:
        provider, client, model = self._llm_client
        tools = self._registry.list_tools()
        history = list(messages)

        for _ in range(self._max_iterations):
            try:
                text, calls = await self._call_llm(provider, client, model, history, tools)
            except Exception as exc:
                logger.error("agent: LLM call failed: %s", exc)
                yield {"type": "error", "content": f"LLM error: {exc}"}
                yield {"type": "done", "content": ""}
                return

            if not calls:
                yield {"type": "response", "content": text}
                yield {"type": "done", "content": ""}
                return

            results = []
            for call_id, name, args in calls:
                yield {"type": "tool_call", "content": json.dumps({"name": name, "args": args})}
                output = await self._run_tool(name, args)
                yield {"type": "tool_result", "content": output}
                results.append((call_id, output))

            # One assistant turn carrying every call, then the results (both APIs require this shape).
            if provider == "openai":
                history.append({
                    "role": "assistant", "content": text or None,
                    "tool_calls": [{"id": cid, "type": "function",
                                    "function": {"name": n, "arguments": json.dumps(a)}} for cid, n, a in calls],
                })
                history.extend({"role": "tool", "tool_call_id": cid, "content": out} for cid, out in results)
            else:
                blocks = ([{"type": "text", "text": text}] if text else []) + [
                    {"type": "tool_use", "id": cid, "name": n, "input": a} for cid, n, a in calls
                ]
                history.append({"role": "assistant", "content": blocks})
                history.append({"role": "user", "content": [
                    {"type": "tool_result", "tool_use_id": cid, "content": out} for cid, out in results
                ]})

        logger.warning("agent: reached max_iterations=%d", self._max_iterations)
        yield {"type": "response", "content": "Agent reached maximum iterations without a final answer."}
        yield {"type": "done", "content": ""}


