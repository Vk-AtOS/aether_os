# AgentLoop — ReAct loop with SSE streaming
# ---------------------------------------------------------------------------

class AgentLoop:
    """ReAct-style agent loop: think → call tool → observe → repeat.

    Yields SSE-compatible dicts:
      {"type": "thinking",    "content": "..."}
      {"type": "tool_call",   "content": "{name, args}"}
      {"type": "tool_result", "content": "..."}
      {"type": "response",    "content": "..."}
      {"type": "done",        "content": ""}
    """

    def __init__(
        self,
        llm_client: Any,
        tool_registry: ToolRegistry,
        max_iterations: int = 10,
    ) -> None:
        self._llm_client = llm_client
        self._registry = tool_registry
        self._max_iterations = max_iterations

    async def run(
        self, messages: list[dict], stream: bool = False
    ) -> AsyncGenerator[dict, None]:
        provider, client, model = self._llm_client
        tools = self._registry.list_tools()
        history = list(messages)

        for iteration in range(self._max_iterations):
            logger.debug("AgentLoop iteration %d/%d", iteration + 1, self._max_iterations)

            # ── Call LLM ──────────────────────────────────────────────────────
            try:
                if provider == "openai":
                    response = await client.chat.completions.create(
                        model=model,
                        messages=history,
                        tools=tools or None,
                        tool_choice="auto" if tools else None,
                    )
                    msg = response.choices[0].message
                    tool_calls = msg.tool_calls or []
                    text_content = msg.content or ""
                elif provider == "anthropic":
                    # Convert messages to Anthropic format (system separate)
                    sys_msgs = [m["content"] for m in history if m["role"] == "system"]
                    conv_msgs = [m for m in history if m["role"] != "system"]
                    kwargs: dict = {
                        "model": model,
                        "max_tokens": 4096,
                        "messages": conv_msgs,
                    }
                    if sys_msgs:
                        kwargs["system"] = "\n".join(sys_msgs)
                    if tools:
                        # Anthropic uses "tools" with a different schema key
                        kwargs["tools"] = [
                            {
                                "name": t["function"]["name"],
                                "description": t["function"]["description"],
                                "input_schema": t["function"]["parameters"],
                            }
                            for t in tools
                        ]
                    ant_response = await client.messages.create(**kwargs)
                    # Extract text and tool use blocks
                    tool_calls = []
                    text_content = ""
                    for block in ant_response.content:
                        if block.type == "text":
                            text_content += block.text
                        elif block.type == "tool_use":
                            tool_calls.append(block)
                    msg = ant_response
                else:
                    raise ValueError(f"Unknown provider: {provider}")
            except Exception as llm_exc:
                logger.error("AgentLoop LLM call failed: %s", llm_exc)
                yield {"type": "response", "content": f"LLM error: {llm_exc}"}
                yield {"type": "done", "content": ""}
                return

            # ── No tool call — final answer ───────────────────────────────────
            if not tool_calls:
                if text_content:
                    yield {"type": "thinking", "content": text_content}
                yield {"type": "response", "content": text_content}
                yield {"type": "done", "content": ""}
                return

            # ── Process tool calls ────────────────────────────────────────────
            for tc in tool_calls:
                if provider == "openai":
                    tool_name = tc.function.name
                    try:
                        tool_args = json.loads(tc.function.arguments or "{}")
                    except Exception as json_exc:
                        logger.warning("AgentLoop: could not parse tool args: %s", json_exc)
                        tool_args = {}
                    call_id = tc.id
                else:  # anthropic
                    tool_name = tc.name
                    tool_args = tc.input or {}
                    call_id = tc.id

                yield {
                    "type": "tool_call",
                    "content": json.dumps({"name": tool_name, "args": tool_args}),
                }

                # Execute tool
                tool = self._registry.get(tool_name)
                if tool is None:
                    tool_result_str = f"Error: tool '{tool_name}' not found"
                    logger.warning("AgentLoop: unknown tool '%s'", tool_name)
                else:
                    try:
                        result = tool.handler(**tool_args)
                        if asyncio.iscoroutine(result):
                            result = await result
                        tool_result_str = str(result)
                    except Exception as tool_exc:
                        logger.warning("AgentLoop: tool '%s' raised: %s", tool_name, tool_exc)
                        tool_result_str = f"Tool error: {tool_exc}"

                yield {"type": "tool_result", "content": tool_result_str}

                # Append tool result back into message history
                if provider == "openai":
                    history.append({
                        "role": "assistant",
                        "content": text_content or None,
                        "tool_calls": [tc],
                    })
                    history.append({
                        "role": "tool",
                        "tool_call_id": call_id,
                        "content": tool_result_str,
                    })
                else:
                    history.append({
                        "role": "assistant",
                        "content": [{"type": "tool_use", "id": call_id, "name": tool_name, "input": tool_args}],
                    })
                    history.append({
                        "role": "user",
                        "content": [{"type": "tool_result", "tool_use_id": call_id, "content": tool_result_str}],
                    })

        # Max iterations reached
        logger.warning("AgentLoop: reached max_iterations=%d", self._max_iterations)
        yield {"type": "response", "content": "Agent reached maximum iterations without a final answer."}
        yield {"type": "done", "content": ""}


