def _build_llm_client():
    """Return (provider, client, model). OpenAI-compatible via LLM_BASE_URL/LLM_API_KEY/LLM_MODEL, else Anthropic."""
    model = os.getenv("LLM_MODEL") or os.getenv("AGENT_MODEL", "")
    api_key = os.getenv("LLM_API_KEY") or os.getenv("OPENAI_API_KEY", "")
    base_url = os.getenv("LLM_BASE_URL") or None
    anthropic_key = os.getenv("ANTHROPIC_API_KEY", "")

    if api_key:
        try:
            import openai as _openai
        except ImportError as exc:
            raise RuntimeError("the openai package is not installed") from exc
        return ("openai", _openai.AsyncOpenAI(api_key=api_key, base_url=base_url), model or "gpt-4o-mini")

    if anthropic_key:
        try:
            import anthropic as _anthropic
        except ImportError as exc:
            raise RuntimeError("the anthropic package is not installed") from exc
        return ("anthropic", _anthropic.AsyncAnthropic(api_key=anthropic_key), model or "claude-3-5-sonnet-20241022")

    raise RuntimeError("No LLM configured. Set LLM_API_KEY (and LLM_BASE_URL / LLM_MODEL) or ANTHROPIC_API_KEY.")


