@dataclass
class AgentTool:
    """A callable tool that the agent can invoke."""
    name: str
    description: str
    parameters: dict  # JSON Schema object
    handler: Callable[..., Any]


class ToolRegistry:
    """Registry of agent-callable tools."""

    def __init__(self) -> None:
        self._tools: dict[str, AgentTool] = {}

    def register(self, tool: AgentTool) -> None:
        """Register a tool. Overwrites existing entry with the same name."""
        self._tools[tool.name] = tool
        logger.debug("ToolRegistry: registered tool '%s'", tool.name)

    def get(self, name: str) -> Optional[AgentTool]:
        """Return tool by name, or None if not found."""
        return self._tools.get(name)

    def list_tools(self) -> list[dict]:
        """Return tools in OpenAI function-calling format."""
        return [
            {
                "type": "function",
                "function": {
                    "name": t.name,
                    "description": t.description,
                    "parameters": t.parameters,
                },
            }
            for t in self._tools.values()
        ]


