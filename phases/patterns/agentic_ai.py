class AgentConversation(Base):
    __tablename__ = "agent_conversations"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    title = Column(String(255), nullable=False, default="New conversation")
    created_by = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    messages = Column(JSON, nullable=False, default=list)
    created_at = Column(DateTime(timezone=True), nullable=False, default=lambda: datetime.now(timezone.utc))
    updated_at = Column(DateTime(timezone=True), nullable=False, default=lambda: datetime.now(timezone.utc),
                        onupdate=lambda: datetime.now(timezone.utc))


async def _save_conversation(user_id: int, conversation_id: Optional[str], messages: list, reply: str) -> str:
    """Persist the exchange. Own session: the request's dependency session is closed once streaming starts."""
    async with AsyncSessionLocal() as db:
        conv = await db.get(AgentConversation, conversation_id) if conversation_id else None
        if conv is not None and conv.created_by != user_id:
            conv = None
        full = list(messages) + [{"role": "assistant", "content": reply}]
        if conv is None:
            first = next((m.get("content") for m in messages if m.get("role") == "user"), "") or ""
            conv = AgentConversation(id=str(uuid.uuid4()), title=str(first)[:60] or "New conversation",
                                     created_by=user_id, messages=full)
            db.add(conv)
        else:
            conv.messages = full
        await db.commit()
        return conv.id


