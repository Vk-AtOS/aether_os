async def get_current_time() -> str:
    """Current UTC date and time (a model cannot know it)."""
    return datetime.now(timezone.utc).isoformat()


_BIN_OPS = {
    ast.Add: operator.add, ast.Sub: operator.sub, ast.Mult: operator.mul,
    ast.Div: operator.truediv, ast.FloorDiv: operator.floordiv, ast.Mod: operator.mod, ast.Pow: operator.pow,
}


def _eval_node(node: ast.AST) -> float:
    if isinstance(node, ast.Constant) and isinstance(node.value, (int, float)) and not isinstance(node.value, bool):
        return node.value
    if isinstance(node, ast.BinOp) and type(node.op) in _BIN_OPS:
        left, right = _eval_node(node.left), _eval_node(node.right)
        if isinstance(node.op, ast.Pow) and abs(right) > 100:
            raise ValueError("exponent too large")
        return _BIN_OPS[type(node.op)](left, right)
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.USub, ast.UAdd)):
        value = _eval_node(node.operand)
        return -value if isinstance(node.op, ast.USub) else value
    raise ValueError("only numbers and + - * / // % ** are allowed")


async def calculate(expression: str) -> str:
    """Evaluate an arithmetic expression (numbers and + - * / // % ** only; never exec/eval)."""
    return str(_eval_node(ast.parse(expression.strip(), mode="eval").body))


async def web_search(query: str) -> str:
    """Search the web through Tavily. Registered only when TAVILY_API_KEY is set."""
    import httpx
    async with httpx.AsyncClient(timeout=20.0) as http:
        resp = await http.post(
            "https://api.tavily.com/search",
            headers={"Authorization": "Bearer " + os.environ["TAVILY_API_KEY"]},
            json={"query": query, "max_results": 5},
        )
        resp.raise_for_status()
        results = resp.json().get("results", [])
    if not results:
        return "No results."
    return "\n".join(f"{r.get('title', '')} - {r.get('url', '')}\n{r.get('content', '')}" for r in results)


def build_default_registry() -> ToolRegistry:
    """Tools available to this deployment (web_search only when its provider is configured)."""
    registry = ToolRegistry()
    registry.register(AgentTool(
        name="get_current_time", description="Get the current UTC date and time.",
        parameters={"type": "object", "properties": {}}, handler=get_current_time,
    ))
    registry.register(AgentTool(
        name="calculate", description="Evaluate an arithmetic expression, e.g. '(12.5 * 4) / 3'.",
        parameters={"type": "object", "properties": {"expression": {"type": "string"}}, "required": ["expression"]},
        handler=calculate,
    ))
    if os.getenv("TAVILY_API_KEY"):
        registry.register(AgentTool(
            name="web_search", description="Search the web for up-to-date information.",
            parameters={"type": "object", "properties": {"query": {"type": "string"}}, "required": ["query"]},
            handler=web_search,
        ))
    return registry


