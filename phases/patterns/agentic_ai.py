async def read_file(path: str) -> str:
    """Read a local file (restricted to safe paths only)."""
    import pathlib
    safe_path = pathlib.Path(path).resolve()
    # Safety: only allow reads within the working directory
    cwd = pathlib.Path.cwd()
    try:
        safe_path.relative_to(cwd)
    except ValueError:
        raise PermissionError(f"read_file: path outside working directory: {path!r}")
    if not safe_path.exists():
        raise FileNotFoundError(f"read_file: file not found: {path!r}")
    return safe_path.read_text(encoding="utf-8", errors="replace")


async def write_file(path: str, content: str) -> bool:
    """Write content to a local file (restricted to working directory only)."""
    import pathlib
    safe_path = pathlib.Path(path).resolve()
    cwd = pathlib.Path.cwd()
    try:
        safe_path.relative_to(cwd)
    except ValueError:
        raise PermissionError(f"write_file: path outside working directory: {path!r}")
    safe_path.parent.mkdir(parents=True, exist_ok=True)
    safe_path.write_text(content, encoding="utf-8")
    return True


