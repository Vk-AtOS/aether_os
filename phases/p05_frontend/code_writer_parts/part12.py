def _generate_mobile_first_layout(entities: List[dict], project_name: str) -> str:
    """Generate Layout.tsx with mobile-first sidebar that collapses to bottom tab bar on <768px."""
    icons_needed = {"LayoutDashboard", "LogOut"}
    for ent in entities:
        icons_needed.add(entity_icon(ent["table"]))

    nav_items: List[str] = [
        "  { to: '/' as const, label: 'Dashboard', icon: 'LayoutDashboard' },",
    ]
    for ent in entities[:4]:  # Bottom nav shows max 4 items + more
        table = ent["table"]
        label = to_label(table)
        icon = entity_icon(table)
        route_path = f"/{table.replace('_', '-')}"
        nav_items.append(f"  {{ to: '{route_path}' as const, label: '{label}', icon: '{icon}' }},")

    all_nav_items: List[str] = [
        "  { to: '/' as const, label: 'Dashboard', icon: 'LayoutDashboard' },",
    ]
    for ent in entities:
        table = ent["table"]
        label = to_label(table)
        icon = entity_icon(table)
        route_path = f"/{table.replace('_', '-')}"
        all_nav_items.append(f"  {{ to: '{route_path}' as const, label: '{label}', icon: '{icon}' }},")

    icons_str = ", ".join(sorted(icons_needed | {"Menu", "Moon", "Sun", "X"}))
    nav_str = "\n".join(nav_items)
    all_nav_str = "\n".join(all_nav_items)

    return f"""\
// Auto-generated by AetherOS p05_frontend — mobile-first layout
// Desktop: persistent sidebar. Mobile (<768px): collapsible bottom tab bar.
import {{ useState, useEffect }} from 'react'
import {{ Link, useRouter, Outlet }} from '@tanstack/react-router'
import {{ clearToken }} from '../lib/auth'
import {{ motion, AnimatePresence }} from 'framer-motion'
import {{ {icons_str} }} from 'lucide-react'

const _ICON_MAP: Record<string, React.FC<{{size?: number; className?: string}}>> = {{
  {", ".join(f"'{i}': {i}" for i in sorted(icons_needed))}
}}

// Bottom tab bar: dashboard + first 3 entities
const BOTTOM_NAV = [
{nav_str}
]

// Sidebar: all entities
const SIDEBAR_NAV = [
{all_nav_str}
]

export function Layout() {{
  const router = useRouter()
  const [sidebarOpen, setSidebarOpen] = useState(false)
  const [darkMode, setDarkMode] = useState<boolean>(() => {{
    if (typeof window === 'undefined') return false
    const stored = localStorage.getItem('theme')
    if (stored) return stored === 'dark'
    return window.matchMedia('(prefers-color-scheme: dark)').matches
  }})

  useEffect(() => {{
    if (darkMode) {{
      document.documentElement.classList.add('dark')
      localStorage.setItem('theme', 'dark')
    }} else {{
      document.documentElement.classList.remove('dark')
      localStorage.setItem('theme', 'light')
    }}
  }}, [darkMode])

  const handleLogout = () => {{
    clearToken()
    router.navigate({{ to: '/login' }})
  }}

  return (
    <div className="flex h-screen bg-muted overflow-hidden">
      {{/* ── Desktop sidebar ── */}}
      <aside className="hidden md:flex w-64 bg-foreground text-background flex-col border-r border-border shrink-0">
        <div className="p-6 border-b border-border flex items-center justify-between">
          <h1 className="text-lg font-bold text-white tracking-tight">{project_name}</h1>
          <button
            onClick={{() => setDarkMode(d => !d)}}
            className="p-1.5 rounded-lg text-muted-foreground hover:text-white hover:bg-foreground transition-colors"
            aria-label="Toggle dark mode"
          >
            {{darkMode ? <Sun size={{15}} /> : <Moon size={{15}} />}}
          </button>
        </div>
        <nav className="flex-1 p-3 space-y-0.5 overflow-y-auto">
          {{SIDEBAR_NAV.map(item => {{
            const Icon = _ICON_MAP[item.icon]
            return (
              <Link key={{item.to}} to={{item.to}}
                className="flex items-center gap-3 px-3 py-2.5 rounded-lg text-muted-foreground hover:bg-foreground hover:text-white transition-colors text-sm font-medium [&.active]:bg-brand-600 [&.active]:text-white">
                {{Icon && <Icon size={{16}} />}}
                {{item.label}}
              </Link>
            )
          }})}}
        </nav>
        <div className="p-3 border-t border-border">
          <button onClick={{handleLogout}}
            className="w-full flex items-center gap-3 px-3 py-2.5 rounded-lg text-muted-foreground hover:bg-foreground hover:text-white transition-colors text-sm">
            <LogOut size={{16}} /> Logout
          </button>
        </div>
      </aside>

      {{/* ── Main content ── */}}
      <div className="flex-1 flex flex-col overflow-hidden">
        {{/* Mobile top bar */}}
        <header className="md:hidden sticky top-0 z-40 bg-card border-b border-border px-4 h-14 flex items-center justify-between shadow-sm">
          <span className="text-base font-bold text-foreground dark:text-white tracking-tight">{project_name}</span>
          <button onClick={{() => setSidebarOpen(true)}}
            className="p-2 rounded-lg text-muted-foreground hover:bg-muted transition-colors"
            aria-label="Open menu">
            <Menu size={{20}} />
          </button>
        </header>

        <main className="flex-1 overflow-y-auto pb-20 md:pb-0 bg-muted">
          <Outlet />
        </main>

        {{/* ── Mobile bottom tab bar ── */}}
        <nav className="md:hidden fixed bottom-0 left-0 right-0 z-40 bg-card border-t border-border shadow-[0_-4px_16px_rgba(0,0,0,0.06)]"
          aria-label="Bottom navigation">
          <div className="flex items-stretch h-16">
            {{BOTTOM_NAV.map(item => {{
              const Icon = _ICON_MAP[item.icon]
              return (
                <Link key={{item.to}} to={{item.to}}
                  className="flex-1 flex flex-col items-center justify-center gap-1 text-muted-foreground hover:text-brand-600 [&.active]:text-brand-600 transition-colors py-2">
                  {{Icon && <Icon size={{20}} />}}
                  <span className="text-[10px] font-medium leading-none">{{item.label}}</span>
                </Link>
              )
            }})}}
          </div>
        </nav>
      </div>

      {{/* ── Mobile slide-in menu overlay ── */}}
      <AnimatePresence>
        {{sidebarOpen && (
          <>
            <motion.div
              initial={{{{ opacity: 0 }}}} animate={{{{ opacity: 1 }}}} exit={{{{ opacity: 0 }}}}
              className="fixed inset-0 z-50 bg-black/50 md:hidden"
              onClick={{() => setSidebarOpen(false)}}
            />
            <motion.aside
              initial={{{{ x: -280 }}}} animate={{{{ x: 0 }}}} exit={{{{ x: -280 }}}}
              transition={{{{ type: 'spring', stiffness: 300, damping: 30 }}}}
              className="fixed left-0 top-0 bottom-0 z-50 w-72 bg-foreground text-background flex flex-col md:hidden"
            >
              <div className="p-5 border-b border-border flex items-center justify-between">
                <span className="text-lg font-bold text-white">{project_name}</span>
                <button onClick={{() => setSidebarOpen(false)}}
                  className="p-2 rounded-lg text-muted-foreground hover:bg-foreground" aria-label="Close menu">
                  <X size={{18}} />
                </button>
              </div>
              <nav className="flex-1 p-3 space-y-0.5 overflow-y-auto">
                {{SIDEBAR_NAV.map(item => {{
                  const Icon = _ICON_MAP[item.icon]
                  return (
                    <Link key={{item.to}} to={{item.to}} onClick={{() => setSidebarOpen(false)}}
                      className="flex items-center gap-3 px-3 py-3 rounded-lg text-muted-foreground hover:bg-foreground hover:text-white transition-colors text-sm font-medium [&.active]:bg-brand-600 [&.active]:text-white">
                      {{Icon && <Icon size={{16}} />}} {{item.label}}
                    </Link>
                  )
                }})}}
              </nav>
              <div className="p-3 border-t border-border">
                <button onClick={{handleLogout}}
                  className="w-full flex items-center gap-3 px-3 py-2.5 rounded-lg text-muted-foreground hover:bg-foreground text-sm">
                  <LogOut size={{16}} /> Logout
                </button>
              </div>
            </motion.aside>
          </>
        )}}
      </AnimatePresence>
    </div>
  )
}}
"""


def _generate_page_with_motion(entity_page_code: str) -> str:
    """Wrap a generated entity page component with Framer Motion page transition.

    Inserts a motion.div wrapper around the outermost div in the return statement.
    Falls back to returning the original code unchanged if the pattern isn't found.
    """
    import re as _re
    # Find the return statement's first JSX div and wrap it
    # Pattern: return (\n    <div ...)
    pattern = r'(  return \(\n)(    <div )'
    replacement = (
        r'\1    <motion.div\n'
        r'      initial={{ opacity: 0, y: 8 }}\n'
        r'      animate={{ opacity: 1, y: 0 }}\n'
        r'      transition={{ duration: 0.18, ease: "easeOut" }}\n'
        r'    >\n'
        r'    <div '
    )
    new_code = _re.sub(pattern, replacement, entity_page_code, count=1)
    if new_code == entity_page_code:
        # Pattern didn't match — return unchanged
        return entity_page_code

    # Close the motion.div before the last closing paren
    # Replace the final `  )` with `    </motion.div>\n  )`
    new_code = _re.sub(r'\n  \)\n}$', '\n    </motion.div>\n  )\n}', new_code)

    # Add framer-motion import if not already present
    if 'framer-motion' not in new_code:
        new_code = new_code.replace(
            "// Auto-generated by AetherOS p05_frontend\n",
            "// Auto-generated by AetherOS p05_frontend\nimport { motion } from 'framer-motion'\n",
            1
        )
    return new_code
