"""
Cloud Console App-Shell Generators — AetherOS Layer 7.

Generates the top-level files for the cloud console:
  package.json, index.html, main.jsx, App.jsx, vite.config.js

Page generators (Dashboard, ServiceCatalog, ResourceExplorer, CostDashboard, Settings)
live in cloud_console_pages.py.
"""
from __future__ import annotations

from typing import Dict, List


def _label(name: str) -> str:
    return name.replace("_", " ").title()


def generate_console_package_json(project_name: str) -> str:
    slug = project_name.lower().replace(" ", "-")
    return f"""\
{{
  "name": "{slug}-console",
  "version": "1.0.0",
  "description": "{project_name} Cloud Management Console — generated by AetherOS",
  "scripts": {{
    "dev": "vite",
    "build": "vite build",
    "preview": "vite preview"
  }},
  "dependencies": {{
    "react": "^18.2.0",
    "react-dom": "^18.2.0",
    "react-router-dom": "^6.22.3",
    "@tanstack/react-query": "^5.28.4",
    "recharts": "^2.12.2"
  }},
  "devDependencies": {{
    "@vitejs/plugin-react": "^4.2.1",
    "vite": "^5.1.6"
  }}
}}
"""


def generate_console_index_html(project_name: str) -> str:
    return f"""\
<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>{project_name} Console</title>
    <style>
      *, *::before, *::after {{ box-sizing: border-box; margin: 0; padding: 0; }}
      body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif;
              background: #0f1117; color: #e2e8f0; }}
    </style>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/src/main.jsx"></script>
  </body>
</html>
"""


def generate_console_main_jsx() -> str:
    return """\
import React from 'react';
import ReactDOM from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import App from './App';

const queryClient = new QueryClient({
  defaultOptions: { queries: { staleTime: 30_000, retry: 2 } },
});

ReactDOM.createRoot(document.getElementById('root')).render(
  <React.StrictMode>
    <QueryClientProvider client={queryClient}>
      <BrowserRouter>
        <App />
      </BrowserRouter>
    </QueryClientProvider>
  </React.StrictMode>
);
"""


def generate_console_app_jsx(services: List[Dict]) -> str:
    nav_items = "\n          ".join(
        f'<NavItem key="{s["name"]}" path="/services/{s["name"]}" icon="{s.get("icon", "📦")}" '
        f'label="{_label(s["name"])}" active={{location.pathname.startsWith("/services/{s["name"]}")}}/>'
        for s in services
    )
    return """\
import React, { useState } from 'react';
import { Routes, Route, useLocation, useNavigate } from 'react-router-dom';
import Dashboard from './pages/Dashboard';
import ServiceCatalog from './pages/ServiceCatalog';
import ResourceExplorer from './pages/ResourceExplorer';
import CostDashboard from './pages/CostDashboard';
import Settings from './pages/Settings';

const sidebarStyle = {
  width: 220, minHeight: '100vh', background: '#1a1d27',
  borderRight: '1px solid #2d3748', display: 'flex', flexDirection: 'column',
  padding: '0 0 24px 0', position: 'fixed', top: 0, left: 0, zIndex: 100,
};
const topbarStyle = {
  height: 56, background: '#1a1d27', borderBottom: '1px solid #2d3748',
  display: 'flex', alignItems: 'center', justifyContent: 'space-between',
  padding: '0 24px', position: 'fixed', top: 0, left: 220, right: 0, zIndex: 99,
};
const mainStyle = {
  marginLeft: 220, marginTop: 56, padding: 28, minHeight: 'calc(100vh - 56px)',
};

function NavItem({ path, icon, label, active }) {
  const navigate = useNavigate();
  return (
    <div
      onClick={() => navigate(path)}
      style={{
        padding: '10px 20px', cursor: 'pointer', display: 'flex', alignItems: 'center',
        gap: 10, borderRadius: 6, margin: '2px 8px',
        background: active ? '#2d3748' : 'transparent',
        color: active ? '#63b3ed' : '#a0aec0',
        transition: 'all 0.15s',
      }}
    >
      <span style={{ fontSize: 18 }}>{icon}</span>
      <span style={{ fontSize: 14, fontWeight: active ? 600 : 400 }}>{label}</span>
    </div>
  );
}

export default function App() {
  const location = useLocation();
  const [region, setRegion] = useState('us-east-1');
  const tenant = localStorage.getItem('project_name') || 'My Platform';

  return (
    <div>
      <nav style={sidebarStyle}>
        <div style={{ padding: '20px 20px 16px', borderBottom: '1px solid #2d3748' }}>
          <div style={{ fontSize: 18, fontWeight: 700, color: '#63b3ed' }}>☁ Console</div>
          <div style={{ fontSize: 12, color: '#718096', marginTop: 4 }}>{tenant}</div>
        </div>
        <div style={{ marginTop: 16, flex: 1 }}>
          <NavItem path="/" icon="📊" label="Dashboard" active={location.pathname === '/'} />
          <NavItem path="/catalog" icon="🗂" label="Service Catalog" active={location.pathname === '/catalog'} />
          <NavItem path="/resources" icon="🔍" label="Resources" active={location.pathname === '/resources'} />
          <NavItem path="/billing" icon="💰" label="Billing" active={location.pathname === '/billing'} />
          <div style={{ padding: '12px 20px 4px', fontSize: 11, color: '#4a5568', textTransform: 'uppercase', letterSpacing: 1 }}>
            Services
          </div>
          """ + nav_items + """
        </div>
        <NavItem path="/settings" icon="⚙️" label="Settings" active={location.pathname === '/settings'} />
      </nav>

      <div style={topbarStyle}>
        <div style={{ fontSize: 14, color: '#a0aec0' }}>
          {location.pathname === '/' ? 'Dashboard' : location.pathname.slice(1).replace('/', ' › ')}
        </div>
        <div style={{ display: 'flex', alignItems: 'center', gap: 16 }}>
          <select
            value={region}
            onChange={e => setRegion(e.target.value)}
            style={{ background: '#2d3748', border: 'none', color: '#e2e8f0', padding: '6px 12px', borderRadius: 6, fontSize: 13 }}
          >
            {['us-east-1','us-west-2','eu-west-1','ap-southeast-1'].map(r => (
              <option key={r} value={r}>{r}</option>
            ))}
          </select>
          <div
            style={{ width: 32, height: 32, borderRadius: '50%', background: '#4a5568', display: 'flex',
                     alignItems: 'center', justifyContent: 'center', cursor: 'pointer', fontSize: 14 }}
            onClick={() => { localStorage.clear(); window.location.href = '/login'; }}
            title="Logout"
          >
            👤
          </div>
        </div>
      </div>

      <main style={mainStyle}>
        <Routes>
          <Route path="/" element={<Dashboard />} />
          <Route path="/catalog" element={<ServiceCatalog />} />
          <Route path="/resources" element={<ResourceExplorer />} />
          <Route path="/billing" element={<CostDashboard />} />
          <Route path="/settings" element={<Settings />} />
        </Routes>
      </main>
    </div>
  );
}
"""


def generate_console_vite_config() -> str:
    return """\
import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig({
  plugins: [react()],
  server: {
    proxy: {
      '/api': { target: 'http://localhost:8000', changeOrigin: true },
      '/ws': { target: 'ws://localhost:8000', ws: true },
    },
  },
  build: { outDir: 'dist' },
});
"""
