"""
Aether-One macOS packaging utilities.

This module builds a relocatable macOS bundle for local distribution:

    dist/macos/aether-one/
        run-aether-one.command
        README.txt

The bundle is intentionally simple and local-first:

- It does NOT require PyInstaller, Homebrew, or Xcode.
- It bootstraps a local virtualenv inside the bundle on first run.
- It installs dependencies from the project's requirements.txt if present.
- It uses PYTHONPATH to point at the Aether-One project directory.
- It launches the Aether-One CLI via `python -m aetherone.cli`.

You can:

- Ship the `dist/macos/aether-one` directory as a zip, or
- Wrap it with an external .dmg/.pkg builder later if needed.
"""

from __future__ import annotations

import argparse
import logging
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)


@dataclass
class MacOSBundleResult:
    """
    Result of creating a macOS bundle.

    Attributes:
        bundle_dir: Root directory of the bundle.
        run_script: Path to the run-aether-one.command launcher.
        readme_path: Path to the bundle's README file.
    """

    bundle_dir: Path
    run_script: Path
    readme_path: Path


def _ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def create_macos_bundle(
    project_path: str,
    *,
    output_dir: Optional[str] = None,
    app_dir_name: str = "aether-one",
) -> MacOSBundleResult:
    """
    Create a macOS bundle for Aether-One.

    Arguments:
        project_path:
            Root of the Aether-One project (where `aetherone/` lives).
        output_dir:
            Base output directory for bundles. If None, uses:
                <project_path>/dist/macos
        app_dir_name:
            Name of the app directory under output_dir (default: "aether-one").

    Returns:
        MacOSBundleResult describing the bundle layout.
    """
    project_root = Path(project_path).expanduser().resolve()
    if not project_root.exists():
        raise FileNotFoundError(f"Project path does not exist: {project_root}")

    if output_dir is None:
        output_root = project_root / "dist" / "macos"
    else:
        output_root = Path(output_dir).expanduser().resolve()

    bundle_dir = output_root / app_dir_name
    _ensure_dir(bundle_dir)

    run_script = bundle_dir / "run-aether-one.command"
    readme_path = bundle_dir / "README.txt"

    project_root_str = str(project_root)

    script_contents = f"""#!/usr/bin/env bash
set -euo pipefail

# Resolve bundle directory (where this script lives)
APP_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
PROJECT_DIR="{project_root_str}"
VENV_DIR="$APP_DIR/.venv"
PYTHON_BIN="$VENV_DIR/bin/python"

echo "[Aether-One] macOS bundle launcher"
echo "  APP_DIR:      $APP_DIR"
echo "  PROJECT_DIR:  $PROJECT_DIR"
echo "  VENV_DIR:     $VENV_DIR"

if [ ! -d "$VENV_DIR" ]; then
  echo "[Aether-One] Creating virtualenv..."
  python3 -m venv "$VENV_DIR"
  "$PYTHON_BIN" -m pip install --upgrade pip
  if [ -f "$PROJECT_DIR/requirements.txt" ]; then
    echo "[Aether-One] Installing dependencies from requirements.txt..."
    "$PYTHON_BIN" -m pip install -r "$PROJECT_DIR/requirements.txt"
  else
    echo "[Aether-One] WARNING: requirements.txt not found in $PROJECT_DIR"
  fi
fi

# Ensure Python can import the project-local aetherone package
export PYTHONPATH="$PROJECT_DIR${{PYTHONPATH:+:$PYTHONPATH}}"

cd "$PROJECT_DIR"
echo "[Aether-One] Launching orchestrator CLI..."
exec "$PYTHON_BIN" -m aetherone.cli "$@"
"""

    run_script.write_text(script_contents, encoding="utf-8")
    os.chmod(run_script, 0o755)

    readme_contents = f"""Aether-One macOS Bundle
=========================

This directory was generated by aetherone.packaging_macos.

Contents
--------

- run-aether-one.command
    Double-click this file in Finder to launch Aether-One.
    On first run it will:

    - Create a private virtual environment inside this folder (.venv)
    - Install dependencies from the project's requirements.txt (if present)
    - Set PYTHONPATH to the Aether-One project directory
    - Launch the Aether-One CLI via: python -m aetherone.cli

Usage (Developer)
-----------------

From Terminal:

    cd "{bundle_dir}"
    ./run-aether-one.command --help

From Finder:

    - Right-click run-aether-one.command
    - Click "Open" (you may need to confirm Gatekeeper prompts)

Assumptions
-----------

- The original project root is:
    {project_root}
- The 'aetherone/' package directory lives under that root.
- Python 3 is available as 'python3' on this system.

To rebuild this bundle:
-----------------------

From the project root:

    python -m aetherone.packaging_macos \\
      --project "{project_root}" \\
      --output-dir "{output_root}"

Distribution
------------

You can zip or tar.gz the entire "{bundle_dir}" directory and
ship it alongside the same project tree. They do not need global
Python packages; everything is local to this bundle and the project.
"""

    readme_path.write_text(readme_contents, encoding="utf-8")

    logger.info("macOS bundle created at %s", bundle_dir)

    return MacOSBundleResult(
        bundle_dir=bundle_dir,
        run_script=run_script,
        readme_path=readme_path,
    )


def main(argv: Optional[list[str]] = None) -> int:
    """
    CLI entrypoint for `python -m aetherone.packaging_macos`.

    Example:

        python -m aetherone.packaging_macos --project . --output-dir dist/macos
    """
    parser = argparse.ArgumentParser(
        description="Build a macOS bundle for Aether-One."
    )
    parser.add_argument(
        "--project",
        "-p",
        dest="project",
        default=".",
        help="Path to the Aether-One project root (default: current directory).",
    )
    parser.add_argument(
        "--output-dir",
        "-o",
        dest="output_dir",
        default=None,
        help="Output directory for the macOS bundle (default: <project>/dist/macos).",
    )
    parser.add_argument(
        "--app-dir-name",
        dest="app_dir_name",
        default="aether-one",
        help="Name of the app directory inside the output dir (default: aether-one).",
    )

    args = parser.parse_args(argv)

    try:
        result = create_macos_bundle(
            project_path=args.project,
            output_dir=args.output_dir,
            app_dir_name=args.app_dir_name,
        )
    except Exception as exc:  # pragma: no cover - defensive
        logger.error("Failed to create macOS bundle: %s", exc)
        raise SystemExit(1) from exc

    print("Aether-One macOS bundle created:")
    print(f"  Bundle dir : {result.bundle_dir}")
    print(f"  Launcher   : {result.run_script}")
    print(f"  README     : {result.readme_path}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())

