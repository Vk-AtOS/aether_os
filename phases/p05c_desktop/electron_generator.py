"""
Electron desktop app generator for AetherOS P05c phase.

Called when build_profile.frontend_framework == "electron".
Generates a complete Electron + React desktop app that embeds the FastAPI
backend as a managed child process started from the Electron main process.

Output layout (under output_dir/desktop/):
  main.js                   — Electron main process
  preload.js                — Secure IPC bridge (contextBridge)
  package.json              — Electron + Vite + React deps
  electron-builder.yml      — Cross-platform packaging config
  vite.config.js            — Vite config for renderer bundle
  src/
    index.html
    main.jsx                — React entry point
    App.jsx                 — Root component with entity nav
    components/
      <Entity>View.jsx      — List + create/edit form per entity
  .env.example
"""
from __future__ import annotations

import logging
from pathlib import Path
from typing import Any, Dict, List

logger = logging.getLogger(__name__)


def _pascal(name: str) -> str:
    return "".join(w.capitalize() for w in name.replace("-", "_").split("_"))


def _label(name: str) -> str:
    return name.replace("_", " ").title()


def generate_main_js(project_name: str, api_port: int = 8000) -> str:
    slug = project_name.lower().replace(" ", "-")
    return f"""\
const {{ app, BrowserWindow, ipcMain }} = require('electron');
const path = require('path');
const {{ spawn }} = require('child_process');

let mainWindow;
let backendProcess;
const API_PORT = {api_port};

function startBackend() {{
  const backendPath = path.join(process.resourcesPath, 'backend');
  const python = process.platform === 'win32' ? 'python' : 'python3';
  backendProcess = spawn(python, ['-m', 'uvicorn', 'main:app', '--port', API_PORT], {{
    cwd: backendPath,
    stdio: 'pipe',
  }});
  backendProcess.stdout.on('data', (d) => console.log('[backend]', d.toString()));
  backendProcess.stderr.on('data', (d) => console.error('[backend]', d.toString()));
}}

function createWindow() {{
  mainWindow = new BrowserWindow({{
    width: 1280,
    height: 800,
    webPreferences: {{
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
    }},
  }});

  const isDev = !app.isPackaged;
  if (isDev) {{
    mainWindow.loadURL('http://localhost:5173');
    mainWindow.webContents.openDevTools();
  }} else {{
    mainWindow.loadFile(path.join(__dirname, 'dist', 'index.html'));
  }}

  mainWindow.on('closed', () => {{ mainWindow = null; }});
}}

app.whenReady().then(() => {{
  if (app.isPackaged) startBackend();
  // Wait briefly for backend startup before opening window
  setTimeout(createWindow, app.isPackaged ? 2000 : 0);
}});

app.on('window-all-closed', () => {{
  if (backendProcess) backendProcess.kill();
  if (process.platform !== 'darwin') app.quit();
}});

ipcMain.handle('get-api-base', () => `http://localhost:${{API_PORT}}`);
"""


def generate_preload_js() -> str:
    return """\
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electron', {
  getApiBase: () => ipcRenderer.invoke('get-api-base'),
});
"""


