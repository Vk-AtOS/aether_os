"""P11c Task Agent — wire PostHog analytics SDK."""
from __future__ import annotations
import json, logging
from pathlib import Path
from typing import Any, Dict, List
from aether_os.phases.base import TaskResult
from aether_os.core.llm.client import get_llm_client
logger = logging.getLogger(__name__)

async def run(phase_input: Any, memory_ctx: List[Dict], output_dir: Path) -> TaskResult:
    output_dir.mkdir(parents=True, exist_ok=True)
    data = phase_input.input_data
    project_dir = Path(data.get("project_dir", str(output_dir)))
    components_json_path = data.get("components_json_path", "")
    llm = get_llm_client()

    journeys = []
    if components_json_path and Path(components_json_path).exists():
        try:
            comp = json.loads(Path(components_json_path).read_text())
            journeys = comp.get("user_journeys", comp.get("pages", []))
        except Exception:
            pass

    # docker-compose.posthog.yml
    posthog_compose = """version: '3.8'
services:
  posthog:
    image: posthog/posthog:latest
    environment:
      - DATABASE_URL=postgres://posthog:posthog@posthog-db/posthog
      - REDIS_URL=redis://posthog-redis:6379
      - SECRET_KEY=${POSTHOG_SECRET_KEY:-posthog-secret}
    ports: ["8001:8000"]
    depends_on: [posthog-db, posthog-redis]
  posthog-db:
    image: postgres:15-alpine
    environment:
      POSTGRES_USER: posthog
      POSTGRES_PASSWORD: posthog
      POSTGRES_DB: posthog
  posthog-redis:
    image: redis:7-alpine
"""
    (project_dir / "docker-compose.posthog.yml").write_text(posthog_compose)

    # Backend analytics (Python PostHog)
    backend_analytics = """
import posthog
import os

posthog.project_api_key = os.getenv("POSTHOG_KEY", "")
posthog.host = os.getenv("POSTHOG_HOST", "https://app.posthog.com")

def track(user_id: str, event: str, properties: dict = None):
    if posthog.project_api_key:
        posthog.capture(user_id, event, properties or {})

def identify_user(user_id: str, properties: dict):
    if posthog.project_api_key:
        posthog.identify(user_id, properties)

def group_user(user_id: str, group_type: str, group_id: str):
    if posthog.project_api_key:
        posthog.group_identify(group_type, group_id, {"user": user_id})
"""
    analytics_file = project_dir / "src" / "analytics.py"
    analytics_file.parent.mkdir(parents=True, exist_ok=True)
    analytics_file.write_text(backend_analytics)

    # Generate tracking events for user journeys
    events = set()
    for journey in journeys[:5]:
        name = journey.get("name", journey.get("purpose", "action")) if isinstance(journey, dict) else str(journey)
        events.add(f"page_viewed_{name.lower().replace(' ','_')}")
        steps = journey.get("steps", []) if isinstance(journey, dict) else []
        for step in steps[:3]:
            events.add(f"step_{step.lower().replace(' ','_')[:30]}")

    # Default events if none found
    if not events:
        events = {"user_signed_up", "user_logged_in", "page_viewed_dashboard",
                  "feature_used_main", "user_completed_onboarding"}

    events_list = sorted(list(events))
    events_doc = project_dir / "src" / "tracked_events.py"
    events_doc.write_text(
        "# PostHog tracked events — generated by AetherOS\n\n" +
        "EVENTS = {\n" +
        "\n".join(f'    "{e}": "{e.replace("_"," ").title()}",' for e in events_list) +
        "\n}\n"
    )

    # Frontend analytics snippet (JS)
    frontend_snippet = f"""
// PostHog frontend analytics — add to your main JS file
import posthog from 'posthog-js';

posthog.init(process.env.POSTHOG_KEY || window.POSTHOG_KEY, {{
  api_host: process.env.POSTHOG_HOST || 'https://app.posthog.com',
  autocapture: true,
  capture_pageview: true,
}});

// Track events
export const track = (event, properties = {{}}) => posthog.capture(event, properties);
export const identifyUser = (userId, traits) => posthog.identify(userId, traits);

// Tracked events:
{chr(10).join(f"// track('{e}');" for e in events_list[:8])}
"""
    frontend_dir = project_dir / "frontend"
    if frontend_dir.exists():
        (frontend_dir / "analytics.js").write_text(frontend_snippet)

    # Update .env.example
    env_example = project_dir / ".env.example"
    if env_example.exists():
        content = env_example.read_text()
        if "POSTHOG_KEY" not in content:
            env_example.write_text(content + "\n# PostHog\nPOSTHOG_KEY=\nPOSTHOG_HOST=https://app.posthog.com\n")

    issues = []
    if not analytics_file.exists():
        issues.append("analytics.py not written")
    if len(events_list) < 5:
        issues.append(f"Only {len(events_list)} tracked events (need >= 5)")

    return TaskResult(
        output_path=str(analytics_file),
        confidence=0.9 if not issues else 0.5,
        metadata={"event_count": len(events_list), "events": events_list},
        issues=issues,
        success=len(events_list) >= 5,
    )
