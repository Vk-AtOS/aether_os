async def log_action(
    db,
    user_id: Optional[str],
    action: str,
    resource_type: str,
    resource_id: Optional[str] = None,
    old_value: Optional[Any] = None,
    new_value: Optional[Any] = None,
    request: Optional[Request] = None,
) -> None:
    """Insert an immutable audit record.  Never raises — failure is logged only."""
    try:
        ip = _audit_ip.get() or (request.client.host if request and request.client else None)
        ua = _audit_ua.get() or (request.headers.get("user-agent", "") if request else None)
        session = _audit_session.get() or (request.headers.get("x-session-id", "") if request else None)

        entry = AuditLog(
            user_id=str(user_id) if user_id else None,
            action=action,
            resource_type=resource_type,
            resource_id=str(resource_id) if resource_id else None,
            old_value=json.dumps(old_value, default=str) if old_value is not None else None,
            new_value=json.dumps(new_value, default=str) if new_value is not None else None,
            ip_address=ip,
            user_agent=ua,
            session_id=session,
        )
        db.add(entry)
        # flush within the caller\'s transaction; commit is the caller\'s responsibility
        await db.flush()
    except Exception as exc:
        logger.warning("audit log_action failed (non-fatal): %s", exc)


