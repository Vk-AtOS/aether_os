# ── FK-aware seed entity ordering ─────────────────────────────────────────────

def topological_sort_entities(entities: list[dict]) -> list[dict]:
    """Sort entities so FK parent tables are inserted before child tables.

    Accepts a list of entity dicts with optional 'fields' key containing
    field dicts that may have 'fk_ref' or 'ref_entity' keys indicating the
    parent entity name.  Returns a new list sorted so parents come first.

    Cycles are detected and logged as a warning — the function never crashes,
    it returns the best ordering possible given the cycle.

    Args:
        entities: List of entity dicts. Each dict may have:
            - 'name': str — entity class name
            - 'fields': list of field dicts, each optionally with 'ref_entity' or 'fk_ref'
    Returns:
        A new list of entity dicts in dependency-safe insertion order.
    """
    sorted_out: list[dict] = []
    visited: set[str] = set()
    in_progress: set[str] = set()

    entity_map: dict[str, dict] = {}
    for ent in entities:
        name = ent.get("name", "")
        if name:
            entity_map[name] = ent

    def _visit(name: str) -> None:
        if name in visited:
            return
        if name in in_progress:
            logger.warning(
                "[p04a] topological_sort_entities: cycle detected at entity %r — skipping to avoid infinite loop",
                name,
            )
            return
        in_progress.add(name)
        ent = entity_map.get(name)
        if ent:
            for field in ent.get("fields", []):
                if not isinstance(field, dict):
                    continue
                ref = field.get("ref_entity") or field.get("fk_ref") or field.get("references")
                if ref and ref != name and ref in entity_map:
                    _visit(ref)
        in_progress.discard(name)
        visited.add(name)
        if ent:
            sorted_out.append(ent)

    for ent in entities:
        _visit(ent.get("name", ""))

    return sorted_out
