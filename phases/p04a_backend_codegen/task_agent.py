"""P04a Backend Codegen — generates a complete FastAPI backend from the architecture spec."""
from __future__ import annotations
import json
import logging
import re
import textwrap
from pathlib import Path
from typing import Any, Dict, List

from aether_os.phases.base import TaskResult

logger = logging.getLogger(__name__)


def _build_fallback_main(project_name: str, entities: list, endpoints: list) -> str:
    """Generate a minimal but working FastAPI app when LLM fails."""
    model_blocks = []
    router_blocks = []
    for ent in entities[:8]:
        name = ent.get("name", "Item")
        table = ent.get("table", name.lower() + "s")
        fields = ent.get("fields", ["id", "name", "created_at"])
        col_lines = []
        for f in fields:
            if f in ("id",):
                col_lines.append(f"    {f}: int = None")
            elif f in ("created_at", "updated_at"):
                col_lines.append(f"    {f}: str = None")
            else:
                col_lines.append(f"    {f}: str = None")
        col_str = "\n".join(col_lines) or "    name: str = None"
        model_blocks.append(textwrap.dedent(f"""\
            class {name}(BaseModel):
            {col_str}
        """))
        router_blocks.append(textwrap.dedent(f"""\
            @app.get("/api/{table}", tags=["{name}"])
            async def list_{table}(current_user: dict = Depends(get_current_user)):
                return {{"items": [], "total": 0}}

            @app.post("/api/{table}", tags=["{name}"])
            async def create_{table}(item: {name}, current_user: dict = Depends(get_current_user)):
                return {{"id": 1, **item.dict()}}

            @app.get("/api/{table}/{{item_id}}", tags=["{name}"])
            async def get_{table}(item_id: int, current_user: dict = Depends(get_current_user)):
                return {{"id": item_id}}

            @app.put("/api/{table}/{{item_id}}", tags=["{name}"])
            async def update_{table}(item_id: int, item: {name}, current_user: dict = Depends(get_current_user)):
                return {{"id": item_id, **item.dict()}}

            @app.delete("/api/{table}/{{item_id}}", tags=["{name}"])
            async def delete_{table}(item_id: int, current_user: dict = Depends(get_current_user)):
                return {{"deleted": True}}
        """))

    models = "\n".join(model_blocks)
    routes = "\n".join(router_blocks)
    return textwrap.dedent(f"""\
        \"\"\"
        {project_name} — Auto-generated FastAPI backend
        Generated by AetherOS p04a_backend_codegen
        \"\"\"
        import os
        from fastapi import FastAPI, HTTPException, Depends, Security
        from fastapi.middleware.cors import CORSMiddleware
        from fastapi.security import HTTPBearer, HTTPAuthorizationCredentials
        from pydantic import BaseModel

        app = FastAPI(
            title="{project_name} API",
            version="1.0.0",
            description="Auto-generated backend for {project_name}",
        )

        app.add_middleware(
            CORSMiddleware,
            allow_origins=os.environ.get("CORS_ORIGINS", "*").split(","),
            allow_credentials=True,
            allow_methods=["*"],
            allow_headers=["*"],
        )

        _bearer = HTTPBearer(auto_error=False)

        def get_current_user(credentials: HTTPAuthorizationCredentials = Security(_bearer)):
            \"\"\"Validate Bearer token. Raises 401 if missing or invalid.\"\"\"
            if not credentials or not credentials.credentials:
                raise HTTPException(status_code=401, detail="Not authenticated")
            return {{"token": credentials.credentials}}

        # ── Models ────────────────────────────────────────────────────────────
        {models}

        # ── Health ────────────────────────────────────────────────────────────
        @app.get("/health")
        async def health():
            return {{"status": "ok", "service": "{project_name}"}}

        # ── Routes ───────────────────────────────────────────────────────────
        {routes}
    """)


def _extract_code_block(text: str) -> str:
    """Pull the first ```python ... ``` block, or return the whole text."""
    m = re.search(r"```(?:python)?\s*\n(.*?)```", text, re.DOTALL)
    return m.group(1).strip() if m else text.strip()


async def run(phase_input: Any, memory_ctx: List[Dict], output_dir: Path) -> TaskResult:
    output_dir.mkdir(parents=True, exist_ok=True)
    src_dir = output_dir / "src"
    src_dir.mkdir(parents=True, exist_ok=True)

    data = phase_input.input_data if hasattr(phase_input, "input_data") else {}
    raw_input: str = data.get("raw_input", "") or data.get("requirements", "") or ""
    project_name: str = data.get("project_name", "App")
    domain: str = data.get("domain", "general")
    entities: list = data.get("entities", [])
    api_endpoints: list = data.get("api_endpoints", [])

    # Load architecture doc if available
    arch_doc: dict = {}
    arch_path = data.get("architecture_path", "") or data.get("json_path", "")
    if arch_path:
        try:
            arch_doc = json.loads(Path(arch_path).read_text())
            if not entities:
                entities = arch_doc.get("entities", [])
            if not api_endpoints:
                api_endpoints = arch_doc.get("api_endpoints", [])
        except Exception as exc:
            logger.warning("[p04a] could not load architecture doc: %s", exc)

    main_py_path = src_dir / "main.py"
    generated_via = "llm"

    # ── LLM-based codegen ────────────────────────────────────────────────────
    try:
        from aether_os.core.llm.client import get_llm_client
        llm = get_llm_client()

        entities_json = json.dumps(entities[:10], indent=2) if entities else "[]"
        endpoints_json = json.dumps(api_endpoints[:20], indent=2) if api_endpoints else "[]"
        arch_summary = json.dumps({
            "tech_stack": arch_doc.get("tech_stack", {}),
            "security_considerations": arch_doc.get("security_considerations", []),
        }, indent=2) if arch_doc else "{}"

        prompt = f"""\
You are a senior backend engineer. Generate a complete, production-ready FastAPI backend \
for the following project.

Project Name: {project_name}
Domain: {domain}
Requirements:
{raw_input[:2000]}

Architecture:
{arch_summary}

Entities:
{entities_json}

Desired API Endpoints:
{endpoints_json}

REQUIREMENTS FOR THE CODE:
1. Use FastAPI with SQLAlchemy (async) and Pydantic v2 models
2. Use DATABASE_URL env var (default: sqlite+aiosqlite:///./app.db)
3. Include CORS middleware reading CORS_ORIGINS env var (default "*")
4. Every entity gets full CRUD endpoints: GET list, POST create, GET by id, PUT update, DELETE
5. Include JWT auth: POST /auth/login returns token, GET /auth/me returns current user
6. Include /health endpoint returning {{"status": "ok"}}
7. Use SQLAlchemy async engine with create_all on startup
8. Include realistic field validation with Pydantic
9. Include pagination (skip/limit) on list endpoints
10. Role-based access control: admin vs regular user where appropriate

Return ONLY the complete Python file content. No explanation, no markdown fences.
The file must be importable without errors."""

        result = await llm.call(prompt, task_type="code_generation", max_tokens=6000)
        if result and len(result.strip()) > 200:
            code = _extract_code_block(result)
            if len(code) > 100:
                main_py_path.write_text(code)
                logger.info("[p04a] LLM generated main.py (%d chars)", len(code))
            else:
                raise ValueError("LLM returned too-short code block")
        else:
            raise ValueError("LLM returned empty/short response")
    except Exception as exc:
        logger.warning("[p04a] LLM codegen failed (%s), using fallback", exc)
        generated_via = "fallback"
        main_py_path.write_text(_build_fallback_main(project_name, entities, api_endpoints))

    # ── requirements.txt ─────────────────────────────────────────────────────
    requirements_txt = textwrap.dedent("""\
        fastapi>=0.111.0
        uvicorn[standard]>=0.29.0
        sqlalchemy[asyncio]>=2.0.0
        aiosqlite>=0.20.0
        pydantic>=2.0.0
        python-jose[cryptography]>=3.3.0
        passlib[bcrypt]>=1.7.4
        python-multipart>=0.0.9
        httpx>=0.27.0
        python-dotenv>=1.0.0
    """)
    (src_dir / "requirements.txt").write_text(requirements_txt)

    # ── Dockerfile ────────────────────────────────────────────────────────────
    dockerfile = textwrap.dedent(f"""\
        FROM python:3.11-slim
        WORKDIR /app
        COPY requirements.txt .
        RUN pip install --no-cache-dir -r requirements.txt
        COPY . .
        EXPOSE 8000
        CMD ["uvicorn", "src.main:app", "--host", "0.0.0.0", "--port", "8000"]
    """)
    (src_dir / "Dockerfile").write_text(dockerfile)

    # ── .env.example ─────────────────────────────────────────────────────────
    import secrets as _sec
    _gen_secret = _sec.token_hex(32)
    env_example = textwrap.dedent(f"""\
        DATABASE_URL=sqlite+aiosqlite:///./app.db
        SECRET_KEY={_gen_secret}
        CORS_ORIGINS=http://localhost:3000,http://localhost:5173
        ENVIRONMENT=development
    """)
    (src_dir / ".env.example").write_text(env_example)

    # ── docker-compose.yml ────────────────────────────────────────────────────
    dc = textwrap.dedent(f"""\
        version: '3.8'
        services:
          api:
            build: ./src
            ports:
              - "8000:8000"
            environment:
              - DATABASE_URL=sqlite+aiosqlite:///./app.db
              - SECRET_KEY=${{SECRET_KEY:-{_gen_secret}}}
            volumes:
              - ./data:/app/data
            restart: unless-stopped
        volumes:
          data:
    """)
    (output_dir / "docker-compose.yml").write_text(dc)

    code_size = main_py_path.stat().st_size if main_py_path.exists() else 0
    logger.info("[p04a] backend codegen complete: %d bytes via %s", code_size, generated_via)

    return TaskResult(
        output_path=str(output_dir),
        confidence=0.88 if generated_via == "llm" else 0.65,
        metadata={
            "backend_src_dir": str(src_dir),
            "main_py": str(main_py_path),
            "generated_via": generated_via,
            "code_size_bytes": code_size,
            "entities_count": len(entities),
            "endpoints_count": len(api_endpoints),
            "project_name": project_name,
        },
        success=True,
        issues=[],
    )
