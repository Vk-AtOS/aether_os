class AuditContextMiddleware(BaseHTTPMiddleware):
    """Store request IP + User-Agent + session in context vars for async access."""

    async def dispatch(self, request: Request, call_next):
        _audit_ip.set(request.client.host if request.client else "")
        _audit_ua.set(request.headers.get("user-agent", "")[:512])
        _audit_session.set(request.headers.get("x-session-id", ""))
        return await call_next(request)


