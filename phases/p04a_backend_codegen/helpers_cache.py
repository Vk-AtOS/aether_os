"""Cache service generator — split from helpers.py to keep it under 600 lines.

Provides _generate_cache_service() which writes services/cache.py into the
generated app.  The generated file contains:
  - An async Redis client (redis.asyncio) with graceful no-op fallback
  - cache_get / cache_set / cache_delete / cache_invalidate_prefix helpers
  - RedisCacheMiddleware (Starlette BaseHTTPMiddleware) for 30-s GET response caching
"""
from __future__ import annotations

import logging
from pathlib import Path

logger = logging.getLogger(__name__)


def _generate_cache_service(src_dir: Path) -> None:
    """Write services/cache.py into the generated app's src/ directory."""
    services_dir = src_dir / "services"
    services_dir.mkdir(parents=True, exist_ok=True)

    cache_service_py = '''\
"""Redis cache service — generated by AetherOS.

Provides async cache helpers that fall back gracefully to no-op when Redis is
unavailable or REDIS_URL is not set.  Import freely — no crash risk.

Usage:
    from services.cache import cache_get, cache_set, cache_delete
    from services.cache import RedisCacheMiddleware

    # In main.py lifespan / middleware setup:
    app.add_middleware(RedisCacheMiddleware)
"""
from __future__ import annotations

import hashlib
import json
import logging
import os
import re
from typing import Any, Optional
from urllib.parse import urlsplit

from starlette.middleware.base import BaseHTTPMiddleware
from starlette.requests import Request
from starlette.responses import JSONResponse, Response

logger = logging.getLogger(__name__)

_redis_client = None
_redis_unavailable = False  # latched True after first failed connect


async def _get_redis():
    """Return a live aioredis client, or None if Redis is down / not configured."""
    global _redis_client, _redis_unavailable
    if _redis_client is not None:
        return _redis_client
    if _redis_unavailable:
        return None
    url = os.environ.get("REDIS_URL", "")
    if not url:
        _redis_unavailable = True
        return None
    try:
        import redis.asyncio as aioredis  # type: ignore[import]
        client = aioredis.from_url(url, encoding="utf-8", decode_responses=True)
        await client.ping()
        _redis_client = client
        logger.info("[cache] Redis connected: %s", urlsplit(url).hostname)   # never the URL: it carries the password
        return _redis_client
    except Exception as exc:
        logger.warning("[cache] Redis unavailable — running without cache: %s", exc)
        _redis_unavailable = True
        return None


async def cache_get(key: str) -> Optional[Any]:
    """Return cached value or None on miss / Redis down."""
    try:
        r = await _get_redis()
        if r is None:
            return None
        raw = await r.get(key)
        return json.loads(raw) if raw is not None else None
    except Exception as exc:
        logger.warning("[cache] cache_get failed (non-fatal): %s", exc)
        return None


async def cache_set(key: str, value: Any, ttl: int = 30) -> None:
    """Store *value* in Redis with *ttl* seconds expiry.  Silently skips if Redis is down."""
    try:
        r = await _get_redis()
        if r is None:
            return
        await r.set(key, json.dumps(value, default=str), ex=ttl)
    except Exception as exc:
        logger.warning("[cache] cache_set failed (non-fatal): %s", exc)


async def cache_delete(key: str) -> None:
    """Invalidate a single cached key.  Silently skips if Redis is down."""
    try:
        r = await _get_redis()
        if r is None:
            return
        await r.delete(key)
    except Exception as exc:
        logger.warning("[cache] cache_delete failed (non-fatal): %s", exc)


async def cache_invalidate_prefix(prefix: str) -> None:
    """Delete all keys starting with *prefix* (SCAN, never the blocking KEYS).  Silently skips if Redis is down."""
    try:
        r = await _get_redis()
        if r is None:
            return
        async for key in r.scan_iter(match=f"{prefix}*", count=200):
            await r.delete(key)
    except Exception as exc:
        logger.warning("[cache] cache_invalidate_prefix failed (non-fatal): %s", exc)


_CACHE_TTL = int(os.environ.get("CACHE_TTL", "30"))

# Paths that should never be cached (mutations, auth tokens, user-specific state)
_NEVER_CACHE_PATHS = ("/api/auth/", "/api/health", "/docs", "/redoc", "/openapi")


class RedisCacheMiddleware(BaseHTTPMiddleware):
    """Cache successful GET /api/* responses for CACHE_TTL seconds (default 30 s).

    Cache key: ``resp:{path}:{query}:{auth_hash}`` where *auth_hash* is the full SHA-256 of the Authorization
    header, so each user gets their own cache slot (a short hash can collide and show one user another's data).
    A successful write (POST/PUT/PATCH/DELETE) to /api/<entity> drops every cached response of that entity.
    No-ops silently if Redis is unavailable.
    """

    async def dispatch(self, request: Request, call_next):
        path = request.url.path
        if not path.startswith("/api/") or any(path.startswith(p) for p in _NEVER_CACHE_PATHS):
            return await call_next(request)
        if request.method != "GET":
            response = await call_next(request)
            entity = re.match(r"/api/([A-Za-z0-9_-]+)", path)
            if entity and request.method in ("POST", "PUT", "PATCH", "DELETE") and response.status_code < 400:
                await cache_invalidate_prefix(f"resp:/api/{entity.group(1)}")
            return response

        auth_hash = hashlib.sha256(request.headers.get("authorization", "").encode()).hexdigest()
        cache_key = f"resp:{path}:{request.url.query}:{auth_hash}"

        cached = await cache_get(cache_key)
        if cached is not None:
            return JSONResponse(content=cached, headers={"X-Cache": "HIT"})

        response = await call_next(request)
        if response.status_code != 200:
            return response

        body = b""
        async for chunk in response.body_iterator:
            body += chunk

        try:
            data = json.loads(body)
            await cache_set(cache_key, data, ttl=_CACHE_TTL)
        except ValueError as exc:      # not JSON: served uncached
            logger.warning("[cache] response not cached: %s", exc)

        return Response(
            content=body,
            status_code=response.status_code,
            headers=dict(response.headers),
            media_type=response.media_type,
        )
'''

    (services_dir / "cache.py").write_text(cache_service_py)
    init_py = services_dir / "__init__.py"
    if not init_py.exists():
        init_py.write_text("")
    logger.info("[p04a] cache service written to %s", services_dir / "cache.py")
