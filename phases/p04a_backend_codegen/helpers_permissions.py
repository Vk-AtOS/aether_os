"""Permissions service generator — split from helpers.py to keep it under 600 lines.

Provides _generate_permissions_service for writing ABAC permissions code to generated apps.
"""
from __future__ import annotations

import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)


def _generate_permissions_service(src_dir: Path, permission_model: dict) -> None:
    """Generate services/permissions.py from the p02c permission model.

    Produces:
      - ROLES enum
      - PERMISSIONS dict
      - require_permission(resource, action) FastAPI dependency decorator
      - roles + user_roles table definitions appended to models note
    """
    services_dir = src_dir / "services"
    services_dir.mkdir(parents=True, exist_ok=True)

    roles = permission_model.get("roles", ["SuperAdmin", "Admin", "Staff", "ReadOnly"])
    permissions = permission_model.get("permissions", {})
    row_filters = permission_model.get("row_filters", {})
    field_masks = permission_model.get("field_masks", {})

    roles_enum_members = "\n".join(f'    {r.upper().replace(" ", "_")} = "{r}"' for r in roles)
    permissions_repr = json.dumps(permissions, indent=4)
    row_filters_repr = json.dumps(row_filters, indent=4)
    field_masks_repr = json.dumps(field_masks, indent=4)

    permissions_py = f'''\
"""ABAC permission service — generated by AetherOS from p02c_permission_modeling."""
from __future__ import annotations
import enum
import logging
from typing import Any, Dict, List, Optional

from fastapi import Depends, HTTPException, status

logger = logging.getLogger(__name__)


class Role(str, enum.Enum):
    """Application roles — derived from the permission model."""
{roles_enum_members}


PERMISSIONS: Dict[str, Dict[str, List[str]]] = {permissions_repr}

ROW_FILTERS: Dict[str, str] = {row_filters_repr}

FIELD_MASKS: Dict[str, Dict[str, List[str]]] = {field_masks_repr}


def _has_permission(role: str, resource: str, action: str) -> bool:
    """Return True if the given role may perform action on resource."""
    role_perms = PERMISSIONS.get(role, {{}})
    # SuperAdmin wildcard
    if "*" in role_perms and ("*" in role_perms["*"] or action in role_perms["*"]):
        return True
    resource_perms = role_perms.get(resource, role_perms.get("*", []))
    return "*" in resource_perms or action in resource_perms


def require_permission(resource: str, action: str):
    """FastAPI dependency that enforces ABAC on the current user."""
    try:
        from auth import get_current_user  # absolute import inside generated app
    except ImportError:
        async def _dep(current_user: dict = Depends(lambda: {{}})):
            return current_user
        return _dep

    async def _dep(current_user: dict = Depends(get_current_user)):
        role = current_user.get("role", "ReadOnly")
        if not _has_permission(role, resource, action):
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail=f"Role {{role!r}} cannot perform {{action!r}} on {{resource!r}}",
            )
        return current_user

    return _dep


def mask_fields(data: dict, role: str, resource: str) -> dict:
    """Remove field-masked fields from a dict based on the role\'s field masks."""
    masked_fields = FIELD_MASKS.get(role, {{}}).get(resource, [])
    return {{k: v for k, v in data.items() if k not in masked_fields}}
'''

    (services_dir / "permissions.py").write_text(permissions_py)
    init_py = services_dir / "__init__.py"
    if not init_py.exists():
        init_py.write_text("")
    logger.info("[p04a] permissions.py written with %d roles", len(roles))
