def write_alembic_scaffold(output_dir: Path) -> None:
    """Write alembic.ini, env.py, script.py.mako and versions/ into *output_dir*."""
    alembic_dir = output_dir / "alembic"
    alembic_versions = alembic_dir / "versions"
    alembic_versions.mkdir(parents=True, exist_ok=True)
    (output_dir / "alembic.ini").write_text(_ALEMBIC_INI)
    (alembic_dir / "env.py").write_text(_ALEMBIC_ENV_PY)
    (alembic_dir / "script.py.mako").write_text(_ALEMBIC_SCRIPT_PY_MAKO)
    (alembic_dir / "README").write_text(
        "Generate a migration: alembic revision --autogenerate -m 'description'\n"
        "Apply migrations:    alembic upgrade head\n"
        "Rollback one step:   alembic downgrade -1\n"
    )


def patch_main_py(
    main_py: str,
    inject_pipeline: bool = False,
    inject_realtime: bool = False,
    inject_websocket: bool = False,
    inject_stripe: bool = False,
    inject_marketplace: bool = False,
    inject_erp_approval: bool = False,
) -> str:
    """Apply all optional router injections to the generated main.py string."""
    main_py = main_py.replace(
        "app.include_router(auth_router, prefix=\"/api\")",
        (
            "try:\n"
            "    from services.audit_service import AuditContextMiddleware\n"
            "    app.add_middleware(AuditContextMiddleware)\n"
            "except Exception:\n"
            "    pass\n\n"
            "try:\n"
            "    from services.cache import RedisCacheMiddleware\n"
            "    app.add_middleware(RedisCacheMiddleware)\n"
            "except Exception:\n"
            "    pass\n\n"
            "app.include_router(auth_router, prefix=\"/api\")"
        ),
    )
    _HEALTH_ANCHOR = "@app.get(\"/health\""
    if inject_pipeline:
        main_py = main_py.replace(_HEALTH_ANCHOR, (
            "\ntry:\n"
            "    from routers.pipeline_events import router as _pipeline_events_router\n"
            "    app.include_router(_pipeline_events_router, prefix=\"/api\")\n"
            "except Exception:\n    pass\n"
        ) + _HEALTH_ANCHOR, 1)
    if inject_realtime:
        main_py = main_py.replace(_HEALTH_ANCHOR, (
            "\ntry:\n"
            "    from routers.realtime_router import realtime_router as _realtime_router\n"
            "    app.include_router(_realtime_router, prefix=\"/api\")\n"
            "except Exception as _rt_exc:\n"
            "    import logging as _l; _l.getLogger(__name__).warning('SSE router unavailable: %s', _rt_exc)\n"
        ) + _HEALTH_ANCHOR, 1)
    if inject_websocket:
        main_py = main_py.replace(_HEALTH_ANCHOR, (
            "\ntry:\n"
            "    from websocket_router import router as _ws_router\n"
            "    app.include_router(_ws_router, prefix=\"/api\")\n"
            "except Exception as _ws_exc:\n"
            "    import logging as _l; _l.getLogger(__name__).warning('WS router unavailable: %s', _ws_exc)\n"
        ) + _HEALTH_ANCHOR, 1)
    if inject_stripe:
        main_py = main_py.replace(_HEALTH_ANCHOR, (
            "\ntry:\n"
            "    from billing_router import router as _billing_router\n"
            "    app.include_router(_billing_router, prefix=\"/api\")\n"
            "except Exception as _bill_exc:\n"
            "    import logging as _l; _l.getLogger(__name__).warning('billing router unavailable: %s', _bill_exc)\n"
        ) + _HEALTH_ANCHOR, 1)
    if inject_marketplace:
        main_py = main_py.replace(_HEALTH_ANCHOR, (
            "\ntry:\n"
            "    from marketplace_router import router as _marketplace_router\n"
            "    app.include_router(_marketplace_router, prefix=\"/api\")\n"
            "except Exception as _mkt_exc:\n"
            "    import logging as _l; _l.getLogger(__name__).warning('marketplace router unavailable: %s', _mkt_exc)\n"
        ) + _HEALTH_ANCHOR, 1)
    if inject_erp_approval:
        main_py = main_py.replace(_HEALTH_ANCHOR, (
            "\ntry:\n"
            "    from approval_router import router as _approval_router\n"
            "    app.include_router(_approval_router, prefix=\"/api\")\n"
            "except Exception as _erp_exc:\n"
            "    import logging as _l; _l.getLogger(__name__).warning('approval router unavailable: %s', _erp_exc)\n"
        ) + _HEALTH_ANCHOR, 1)
    return main_py
