def gen_mimir_docker_compose(project_name: str) -> str:
    """
    Generate docker-compose.mimir.yml for local development.

    Uses Mimir in single-binary mode (--target=all) — simplest possible
    setup that still exercises the distributed code paths.
    MinIO provides S3-compatible storage.
    Grafana is pre-wired to use Mimir instead of Prometheus.
    """
    slug = project_name.lower().replace(" ", "-")
    return textwrap.dedent(f"""\
        # docker-compose.mimir.yml — Grafana Mimir local dev stack
        # Generated by AetherOS for {project_name}
        # Usage:
        #   docker compose -f docker-compose.mimir.yml up -d
        #   Mimir  → http://localhost:9009
        #   MinIO  → http://localhost:9001  (minioadmin / minioadmin)
        #   Grafana → http://localhost:3001  (admin / admin)

        version: "3.8"

        services:
          mimir:
            image: grafana/mimir:latest
            command:
              - --config.file=/etc/mimir/mimir.yaml
            volumes:
              - ./mimir.yaml:/etc/mimir/mimir.yaml:ro
              - mimir_data:/data
            ports:
              - "9009:9009"
            depends_on:
              - minio
            environment:
              - AWS_ACCESS_KEY_ID=minioadmin
              - AWS_SECRET_ACCESS_KEY=minioadmin
            restart: unless-stopped

          minio:
            image: minio/minio:latest
            command: server /data --console-address ":9001"
            environment:
              - MINIO_ROOT_USER=minioadmin
              - MINIO_ROOT_PASSWORD=minioadmin
            volumes:
              - minio_data:/data
            ports:
              - "9000:9000"
              - "9001:9001"
            healthcheck:
              test: ["CMD", "curl", "-f", "http://localhost:9000/minio/health/live"]
              interval: 30s
              timeout: 10s
              retries: 3
            restart: unless-stopped

          # Create the bucket on first start
          minio_init:
            image: minio/mc:latest
            depends_on:
              minio:
                condition: service_healthy
            entrypoint: >
              /bin/sh -c "
              mc alias set local http://minio:9000 minioadmin minioadmin;
              mc mb --ignore-existing local/{slug}-metrics;
              exit 0;
              "

          grafana:
            image: grafana/grafana:latest
            environment:
              - GF_SECURITY_ADMIN_PASSWORD=admin
              - GF_USERS_ALLOW_SIGN_UP=false
            volumes:
              - grafana_data:/var/lib/grafana
              - ./grafana/provisioning:/etc/grafana/provisioning:ro
            ports:
              - "3001:3000"
            depends_on:
              - mimir
            restart: unless-stopped

        volumes:
          mimir_data:
          minio_data:
          grafana_data:
    """)


def gen_mimir_config_yaml(project_name: str) -> str:
    """
    Generate mimir.yaml — the Mimir single-binary config for local dev.

    All six core components are configured in one file:
      distributor, ingester, querier, store-gateway, compactor, ruler.
    Object storage points at the local MinIO container.
    """
    slug = project_name.lower().replace(" ", "-")
    return textwrap.dedent(f"""\
        # mimir.yaml — Grafana Mimir configuration
        # Generated by AetherOS for {project_name}
        # Used by: docker compose -f docker-compose.mimir.yml

        target: all          # single-binary mode for local dev
        multitenancy_enabled: false

        common:
          storage:
            backend: s3
            s3:
              endpoint: minio:9000
              bucket_name: {slug}-metrics
              access_key_id: minioadmin
              secret_access_key: minioadmin
              insecure: true

        server:
          http_listen_port: 9009
          grpc_listen_port: 9095
          log_level: info

        distributor:
          ring:
            instance_addr: 127.0.0.1
            kvstore:
              store: inmemory

        ingester:
          ring:
            instance_addr: 127.0.0.1
            kvstore:
              store: inmemory
            replication_factor: 1   # single-binary — no replication needed locally

        blocks_storage:
          backend: s3
          s3:
            endpoint: minio:9000
            bucket_name: {slug}-metrics
            access_key_id: minioadmin
            secret_access_key: minioadmin
            insecure: true
          tsdb:
            dir: /data/tsdb

        compactor:
          data_dir: /data/compactor
          sharding_ring:
            kvstore:
              store: inmemory

        store_gateway:
          sharding_ring:
            kvstore:
              store: inmemory
            replication_factor: 1

        querier:
          store_gateway_addresses: 127.0.0.1:9095

        frontend:
          log_queries_longer_than: 10s
          query_sharding_target_series_per_shard: 2500

        ruler:
          enable_api: true
          rule_path: /data/rules

        ruler_storage:
          backend: local
          local:
            directory: /data/ruler

        limits:
          ingestion_rate: 10000
          ingestion_burst_size: 200000
          max_global_series_per_user: 5000000
          out_of_order_time_window: 10m
          compactor_blocks_retention_period: 90d
    """)


def gen_cortex_migration_guide(project_name: str) -> str:
    """
    Generate a Markdown migration guide from Prometheus to Grafana Mimir.

    Covers: why Mimir, remote_write config change, Grafana datasource swap,
    alerting rules migration, and rollback procedure.
    """
    slug = project_name.lower().replace(" ", "-")
    return textwrap.dedent(f"""\
        # Migrating {project_name} from Prometheus to Grafana Mimir

        ## Why Mimir?

        Single-node Prometheus bottlenecks at ~10K req/sec and ~5M active series.
        Grafana Mimir provides:
        - Horizontally scalable ingest (distributor + ingester ring)
        - Long-term storage in S3-compatible object storage
        - Multi-tenancy support
        - Drop-in Prometheus-compatible API

        ## Prerequisites

        - Helm >= 3.10
        - Kubernetes >= 1.25 (or Docker Compose for local dev)
        - S3 bucket: `{slug}-metrics`
        - Grafana >= 10.0

        ## Step 1: Deploy Mimir

        ### Local (Docker Compose)
        ```bash
        docker compose -f docker-compose.mimir.yml up -d
        # Mimir UI: http://localhost:9009
        # Grafana:  http://localhost:3001
        ```

        ### Kubernetes (Helm)
        ```bash
        helm repo add grafana https://grafana.github.io/helm-charts
        helm repo update

        # Create S3 secret first
        kubectl create secret generic mimir-s3-credentials \\
          --namespace monitoring \\
          --from-literal=AWS_ACCESS_KEY_ID=<your-key> \\
          --from-literal=AWS_SECRET_ACCESS_KEY=<your-secret>

        helm upgrade --install mimir grafana/mimir-distributed \\
          --namespace monitoring --create-namespace \\
          -f mimir-values.yaml
        ```

        ## Step 2: Configure remote_write in Prometheus

        Add to your existing `prometheus.yml` (keeps Prometheus as scraper):

        ```yaml
        remote_write:
          - url: http://mimir-nginx.monitoring.svc/api/v1/push
            # For local dev:
            # url: http://localhost:9009/api/v1/push
            queue_config:
              max_samples_per_send: 10000
              capacity: 20000
              max_shards: 30
        ```

        After this change, Prometheus continues scraping but forwards all metrics
        to Mimir for long-term storage and querying.

        ## Step 3: Update Grafana datasource

        1. In Grafana → Settings → Data Sources → Add data source
        2. Choose **Prometheus**
        3. URL: `http://mimir-nginx.monitoring.svc/prometheus`
           (or `http://localhost:9009/prometheus` for local dev)
        4. Set as Default, save
        5. Remove the old `http://prometheus:9090` datasource

        All existing dashboards will work unchanged — Mimir exposes the same
        PromQL-compatible API as Prometheus.

        ## Step 4: Migrate alert rules

        Mimir ruler reads rules from object storage. Upload your existing rules:

        ```bash
        # Install mimirtool
        brew install grafana/tap/mimirtool  # macOS
        # or: go install github.com/grafana/mimir/pkg/mimirtool@latest

        # Upload rules (replace localhost:9009 for k8s)
        mimirtool rules load alert_rules.yml \\
          --address=http://localhost:9009 \\
          --id=anonymous
        ```

        ## Step 5: Verify

        ```bash
        # Check ingester ring health
        curl http://localhost:9009/ring

        # Query a metric via Mimir (same PromQL API)
        curl 'http://localhost:9009/prometheus/api/v1/query?query=up'

        # Check active series count
        curl http://localhost:9009/api/v1/cardinality/label_names
        ```

        ## Rollback

        If issues arise, revert `prometheus.yml` to remove `remote_write`,
        then restore Grafana datasource to `http://prometheus:9090`.
        Historical data already ingested into Mimir is preserved in S3.

        ## Resource Sizing for 500K users

        | Component      | Replicas | CPU Request | Memory Request |
        |----------------|----------|-------------|----------------|
        | Distributor    | 2        | 250m        | 512Mi          |
        | Ingester       | 3        | 500m        | 2Gi            |
        | Querier        | 2        | 500m        | 1Gi            |
        | Store-Gateway  | 2        | 250m        | 1Gi            |
        | Compactor      | 1        | 250m        | 512Mi          |

        Estimated throughput: **~500K active series, ~1M samples/sec**.
    """)
