"""
OPA (Open Policy Agent) policy and Keycloak realm configuration generator
for AetherOS p16_iam phase.

Generates:
  - Rego policy file (OPA authorization)
  - OPA Helm values (standalone, policy bundle from ConfigMap)
  - Keycloak realm JSON (clients, roles, token settings)
"""
from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Dict, List

logger = logging.getLogger(__name__)

_DEFAULT_ROLES = ["admin", "user", "viewer"]
_DEFAULT_RESOURCES = ["*"]

_DEFAULT_RULES = [
    {"role": "admin",  "resource": "*",    "actions": ["create", "read", "update", "delete"]},
    {"role": "user",   "resource": "*",    "actions": ["create", "read", "update"]},
    {"role": "viewer", "resource": "*",    "actions": ["read"]},
]


def _build_role_permissions(permission_model: Dict) -> Dict[str, Dict[str, List[str]]]:
    """
    Convert permission_model to a nested dict: {role: {resource: [actions]}}.

    Falls back to sane defaults when permission_model is empty.
    """
    rules = permission_model.get("rules") or _DEFAULT_RULES
    result: Dict[str, Dict[str, List[str]]] = {}
    for rule in rules:
        role = rule.get("role", "user")
        resource = rule.get("resource", "*")
        actions = rule.get("actions") or []
        if role not in result:
            result[role] = {}
        result[role][resource] = list(actions)
    return result


def generate_opa_policy(permission_model: Dict, slug: str) -> str:
    """
    Rego policy file.

    Package: authz.{slug}
    allow rule: checks JWT claims (role in token) against resource/action pairs.
    Roles and permissions derived from permission_model dict.
    Fallback: if permission_model empty, generates admin/user/viewer roles.
    """
    role_perms = _build_role_permissions(permission_model)
    roles = list(role_perms.keys()) or _DEFAULT_ROLES

    # Build per-role permission blocks
    role_blocks = ""
    for role, resources in role_perms.items():
        for resource, actions in resources.items():
            actions_set = "{" + ", ".join(f'"{a}"' for a in actions) + "}"
            if resource == "*":
                role_blocks += f"""\
allow {{
    claims.role == "{role}"
    {actions_set}[input.action]
}}

"""
            else:
                role_blocks += f"""\
allow {{
    claims.role == "{role}"
    input.resource == "{resource}"
    {actions_set}[input.action]
}}

"""

    roles_comment = ", ".join(roles)

    return f"""\
# OPA Rego policy — generated by AetherOS for {slug}
# Roles: {roles_comment}
# Input: {{ "token": "<JWT>", "resource": "<name>", "action": "<verb>" }}
# Returns: {{ "allow": true/false }}

package authz.{slug}

import future.keywords.if
import future.keywords.in

default allow := false

# Decode JWT claims from input.token
claims := payload if {{
    # token format: header.payload.signature
    parts := split(input.token, ".")
    count(parts) == 3
    payload := json.unmarshal(base64url.decode(parts[1]))
}}

# Superblock: deny all if claims cannot be parsed
allow if {{
    _ = claims  # ensure claims resolved
    false       # keep as gate; actual rules below
}}

{role_blocks}
# Explicit deny: log unknown roles (unreachable default, but documents intent)
deny if {{
    not claims.role in {{{", ".join(f'"{r}"' for r in roles)}}}
}}
"""


def generate_opa_helm_values(slug: str) -> str:
    """
    OPA Helm values: standalone (gatekeeper disabled), policy bundle from ConfigMap,
    REST API exposed at /v1/data/authz/{slug}/allow.
    """
    return f"""\
## OPA Helm values — generated by AetherOS for {slug}
## Standalone OPA (not gatekeeper mode)
opa:
  enabled: true

replicaCount: 2

args:
  - "run"
  - "--server"
  - "--addr=0.0.0.0:8181"
  - "--log-level=info"
  - "--set=decision_logs.console=true"
  - "/policies"

volumes:
  - name: opa-policy
    configMap:
      name: {slug}-opa-policy

volumeMounts:
  - name: opa-policy
    mountPath: /policies

service:
  type: ClusterIP
  port: 8181

# REST API endpoint used by the app:
# POST http://opa:8181/v1/data/authz/{slug}/allow
# Body: {{"input": {{"token": "<jwt>", "resource": "<name>", "action": "<verb>"}}}}

resources:
  requests:
    cpu: "100m"
    memory: "128Mi"
  limits:
    cpu: "500m"
    memory: "256Mi"

readinessProbe:
  httpGet:
    path: /health?plugins
    port: 8181
  initialDelaySeconds: 5
  periodSeconds: 10

livenessProbe:
  httpGet:
    path: /health
    port: 8181
  initialDelaySeconds: 10
  periodSeconds: 30
"""


def generate_keycloak_realm(slug: str, roles: List[str]) -> str:
    """
    Keycloak realm JSON.

    realm: slug
    clients: one confidential client "api-client" with secret placeholder
    roles: one per role in roles list
    defaultRoles: ["user"]
    Token settings: access token 15min, refresh token 7 days
    """
    if not roles:
        roles = _DEFAULT_ROLES

    realm_roles = [{"name": r, "composite": False, "clientRole": False} for r in roles]
    default_roles = ["user"] if "user" in roles else [roles[0]]

    realm = {
        "realm": slug,
        "enabled": True,
        "displayName": slug.replace("-", " ").title(),
        "registrationAllowed": False,
        "loginWithEmailAllowed": True,
        "duplicateEmailsAllowed": False,
        "resetPasswordAllowed": True,
        "editUsernameAllowed": False,
        "bruteForceProtected": True,
        "permanentLockout": False,
        "maxFailureWaitSeconds": 900,
        "minimumQuickLoginWaitSeconds": 60,
        "waitIncrementSeconds": 60,
        "quickLoginCheckMilliSeconds": 1000,
        "maxDeltaTimeSeconds": 43200,
        "failureFactor": 5,
        "accessTokenLifespan": 900,
        "refreshTokenMaxReuse": 0,
        "ssoSessionMaxLifespan": 604800,
        "offlineSessionMaxLifespan": 5184000,
        "roles": {
            "realm": realm_roles,
        },
        "defaultRoles": default_roles,
        "clients": [
            {
                "clientId": "api-client",
                "name": f"{slug} API Client",
                "enabled": True,
                "publicClient": False,
                "secret": "CHANGE_ME_IN_PRODUCTION",
                "standardFlowEnabled": True,
                "implicitFlowEnabled": False,
                "directAccessGrantsEnabled": True,
                "serviceAccountsEnabled": True,
                "redirectUris": [f"https://{slug}.internal/*"],
                "webOrigins": [f"https://{slug}.internal"],
                "protocol": "openid-connect",
                "defaultClientScopes": ["openid", "profile", "email", "roles"],
            }
        ],
        "smtpServer": {
            "host": "${env.SMTP_HOST}",
            "port": "${env.SMTP_PORT}",
            "from": f"noreply@{slug}.internal",
            "ssl": False,
            "starttls": True,
        },
    }
    return json.dumps(realm, indent=2)


def generate_iam_package(
    permission_model: Dict,
    slug: str,
    output_dir: Path,
) -> Path:
    """
    Writes IAM files to output_dir/iam/ and returns the directory.

    Files written:
      - output_dir/iam/policy.rego
      - output_dir/iam/opa-values.yaml
      - output_dir/iam/keycloak-realm.json
    """
    iam_dir = output_dir / "iam"
    iam_dir.mkdir(parents=True, exist_ok=True)

    roles = list(permission_model.get("roles") or _DEFAULT_ROLES)

    (iam_dir / "policy.rego").write_text(generate_opa_policy(permission_model, slug))
    (iam_dir / "opa-values.yaml").write_text(generate_opa_helm_values(slug))
    (iam_dir / "keycloak-realm.json").write_text(generate_keycloak_realm(slug, roles))

    logger.info(
        "p16_iam: generated OPA policy + Keycloak realm at %s (roles=%s)",
        iam_dir,
        roles,
    )
    return iam_dir
