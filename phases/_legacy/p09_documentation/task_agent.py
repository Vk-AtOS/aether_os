def _generate_diagram_code(project_name: str, stack: Dict, output_dir: str) -> str:
    backend = stack.get("backend", "FastAPI")
    database = stack.get("database", "PostgreSQL")
    cache = stack.get("cache", "Redis")
    return f'''
from diagrams import Diagram, Cluster, Edge
from diagrams.onprem.client import Users
try:
    from diagrams.programming.framework import FastAPI as BackendNode
except ImportError:
    from diagrams.generic.compute import Rack as BackendNode
try:
    from diagrams.onprem.database import PostgreSQL as DBNode
except ImportError:
    from diagrams.generic.database import SQL as DBNode
try:
    from diagrams.onprem.inmemory import Redis as CacheNode
except ImportError:
    from diagrams.generic.storage import Storage as CacheNode

with Diagram("{project_name} Architecture", filename="{output_dir}/architecture",
             outformat="png", show=False):
    users = Users("Clients")
    with Cluster("Application"):
        api = BackendNode("{backend}")
        db = DBNode("{database}")
        cache = CacheNode("{cache}")
    users >> api >> db
    api >> cache
'''


def _strip_fences(code: str) -> str:
    lines = code.strip().splitlines()
    if lines and lines[0].startswith("```"):
        lines = lines[1:]
    if lines and lines[-1].strip() == "```":
        lines = lines[:-1]
    return "\n".join(lines)
