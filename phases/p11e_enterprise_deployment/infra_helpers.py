"""P11e Enterprise Deployment — Layer 4 infrastructure helpers.

Adds:
  - Kafka + Zookeeper Helm values for event-driven / microservices builds
  - GitHub Actions CI/CD pipeline for multi-service repos
  - Terraform AWS EKS module (VPC + EKS + RDS + ElastiCache)

Called from task_agent.py when build_profile indicates microservices
or a message_queue is configured.
"""
from __future__ import annotations

import logging
from pathlib import Path

logger = logging.getLogger(__name__)


def write_kafka_helm_values(output_dir: Path, slug: str) -> None:
    """Write Kafka + Zookeeper Helm chart values alongside the main app chart."""
    kafka_dir = output_dir / "helm" / "kafka"
    kafka_dir.mkdir(parents=True, exist_ok=True)

    (kafka_dir / "values.yaml").write_text(f"""\
# Kafka + Zookeeper values — generated by AetherOS for {slug}
kafka:
  replicaCount: 3
  heapOpts: "-Xmx1g -Xms1g"
  persistence:
    enabled: true
    size: 20Gi
  resources:
    requests:
      cpu: 500m
      memory: 1Gi
    limits:
      cpu: 2000m
      memory: 2Gi
  # Topic auto-creation for each service domain
  provisioning:
    topics:
      - name: {slug}-events
        partitions: 12
        replicationFactor: 3
        config:
          retention.ms: "604800000"   # 7 days
          cleanup.policy: delete
      - name: {slug}-commands
        partitions: 6
        replicationFactor: 3
      - name: {slug}-dead-letter
        partitions: 3
        replicationFactor: 3

zookeeper:
  replicaCount: 3
  persistence:
    enabled: true
    size: 8Gi
  resources:
    requests:
      cpu: 250m
      memory: 512Mi

# Schema Registry for Avro/Protobuf schemas
schemaRegistry:
  enabled: true
  replicaCount: 2

# Kafka UI for observability (disable in air-gapped environments)
kafkaUi:
  enabled: true
  image:
    tag: latest
""")

    (kafka_dir / "Chart.yaml").write_text(f"""\
apiVersion: v2
name: {slug}-kafka
description: Kafka + Zookeeper for {slug} — generated by AetherOS
type: application
version: 0.1.0
dependencies:
  - name: kafka
    version: "26.x.x"
    repository: https://charts.bitnami.com/bitnami
""")

    logger.info("p11e: Kafka Helm values written to %s", kafka_dir)


def write_github_actions(
    output_dir: Path,
    slug: str,
    backend_lang: str = "python",
    is_microservices: bool = False,
) -> None:
    """Write GitHub Actions CI/CD workflows."""
    gha_dir = output_dir / ".github" / "workflows"
    gha_dir.mkdir(parents=True, exist_ok=True)

    # Language-specific test step
    test_step = _test_step(backend_lang)
    build_args = f"--build-arg BUILD_DATE=$(date -u +%Y-%m-%dT%H:%M:%SZ)"

    multi_service_matrix = ""
    if is_microservices:
        multi_service_matrix = """\
    strategy:
      matrix:
        service: [api-gateway, auth-service, core-service]
"""

    (gha_dir / "ci.yml").write_text(f"""\
name: CI

on:
  push:
    branches: [main, develop]
  pull_request:
    branches: [main]

env:
  REGISTRY: ghcr.io
  IMAGE_NAME: ${{{{ github.repository }}}}

jobs:
  test:
    runs-on: ubuntu-latest
{multi_service_matrix}    steps:
      - uses: actions/checkout@v4

      - name: Set up environment
{_setup_step(backend_lang)}

      - name: Install dependencies
{_install_step(backend_lang)}

      - name: Run tests
        run: |
{test_step}

      - name: Lint
{_lint_step(backend_lang)}

  build-and-push:
    needs: test
    runs-on: ubuntu-latest
    if: github.ref == 'refs/heads/main'
    permissions:
      contents: read
      packages: write
    steps:
      - uses: actions/checkout@v4

      - name: Log in to Container Registry
        uses: docker/login-action@v3
        with:
          registry: ${{{{ env.REGISTRY }}}}
          username: ${{{{ github.actor }}}}
          password: ${{{{ secrets.GITHUB_TOKEN }}}}

      - name: Build and push Docker image
        uses: docker/build-push-action@v5
        with:
          context: .
          push: true
          tags: |
            ${{{{ env.REGISTRY }}}}/${{{{ env.IMAGE_NAME }}}}:latest
            ${{{{ env.REGISTRY }}}}/${{{{ env.IMAGE_NAME }}}}:${{{{ github.sha }}}}
          build-args: |
            {build_args}
          cache-from: type=gha
          cache-to: type=gha,mode=max
""")

    (gha_dir / "deploy.yml").write_text(f"""\
name: Deploy to Production

on:
  workflow_run:
    workflows: [CI]
    types: [completed]
    branches: [main]

jobs:
  deploy:
    if: ${{{{ github.event.workflow_run.conclusion == 'success' }}}}
    runs-on: ubuntu-latest
    environment: production
    steps:
      - uses: actions/checkout@v4

      - name: Configure kubectl
        uses: azure/k8s-set-context@v3
        with:
          method: kubeconfig
          kubeconfig: ${{{{ secrets.KUBE_CONFIG }}}}

      - name: Deploy with Helm
        run: |
          helm upgrade --install {slug} ./helm/{slug} \\
            --namespace {slug} \\
            --create-namespace \\
            --set image.tag=${{{{ github.sha }}}} \\
            --set image.repository=ghcr.io/${{{{ github.repository }}}} \\
            --values helm/{slug}/values.prod.yaml \\
            --wait --timeout 10m

      - name: Verify rollout
        run: kubectl rollout status deployment/{slug} -n {slug} --timeout=5m

      - name: Smoke test
        run: |
          APP_URL=$(kubectl get ingress -n {slug} -o jsonpath='{{.items[0].status.loadBalancer.ingress[0].hostname}}')
          curl -f "https://$APP_URL/health" || exit 1
""")

    (gha_dir / "security.yml").write_text("""\
name: Security Scan

on:
  schedule:
    - cron: "0 6 * * 1"   # Weekly Monday 06:00 UTC
  push:
    branches: [main]

jobs:
  trivy:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Run Trivy vulnerability scanner
        uses: aquasecurity/trivy-action@master
        with:
          scan-type: fs
          scan-ref: .
          format: sarif
          output: trivy-results.sarif
          severity: CRITICAL,HIGH
      - name: Upload Trivy SARIF
        uses: github/codeql-action/upload-sarif@v3
        with:
          sarif_file: trivy-results.sarif
""")

    logger.info("p11e: GitHub Actions workflows written to %s", gha_dir)


def write_terraform_eks(output_dir: Path, slug: str) -> None:
    """Write a complete Terraform AWS EKS module (VPC + EKS + RDS + ElastiCache)."""
    eks_dir = output_dir / "terraform" / "aws-eks"
    eks_dir.mkdir(parents=True, exist_ok=True)

    (eks_dir / "main.tf").write_text(f"""\
# Terraform — AWS EKS + VPC + RDS + ElastiCache
# Generated by AetherOS for {slug}

terraform {{
  required_version = ">= 1.6"
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
    kubernetes = {{
      source  = "hashicorp/kubernetes"
      version = "~> 2.24"
    }}
  }}
  backend "s3" {{
    bucket = "{slug}-terraform-state"
    key    = "eks/terraform.tfstate"
    region = "us-east-1"
  }}
}}

provider "aws" {{
  region = var.aws_region
  default_tags {{ tags = local.common_tags }}
}}

locals {{
  common_tags = {{
    Project     = "{slug}"
    ManagedBy   = "terraform"
    Environment = var.environment
  }}
}}

# ── VPC ──────────────────────────────────────────────────────────────────────
module "vpc" {{
  source  = "terraform-aws-modules/vpc/aws"
  version = "~> 5.0"

  name = "{slug}-vpc"
  cidr = "10.0.0.0/16"

  azs             = ["${{var.aws_region}}a", "${{var.aws_region}}b", "${{var.aws_region}}c"]
  private_subnets = ["10.0.1.0/24", "10.0.2.0/24", "10.0.3.0/24"]
  public_subnets  = ["10.0.101.0/24", "10.0.102.0/24", "10.0.103.0/24"]

  enable_nat_gateway   = true
  single_nat_gateway   = var.environment != "production"
  enable_dns_hostnames = true

  public_subnet_tags  = {{ "kubernetes.io/role/elb" = "1" }}
  private_subnet_tags = {{ "kubernetes.io/role/internal-elb" = "1" }}
}}

# ── EKS ──────────────────────────────────────────────────────────────────────
module "eks" {{
  source  = "terraform-aws-modules/eks/aws"
  version = "~> 20.0"

  cluster_name    = "{slug}-${{var.environment}}"
  cluster_version = "1.29"

  vpc_id     = module.vpc.vpc_id
  subnet_ids = module.vpc.private_subnets

  cluster_endpoint_public_access = true

  eks_managed_node_groups = {{
    main = {{
      instance_types = [var.node_instance_type]
      min_size       = var.environment == "production" ? 3 : 1
      max_size       = var.environment == "production" ? 10 : 3
      desired_size   = var.environment == "production" ? 3 : 1

      block_device_mappings = {{
        xvda = {{
          device_name = "/dev/xvda"
          ebs = {{
            volume_size = 50
            volume_type = "gp3"
            encrypted   = true
          }}
        }}
      }}
    }}
  }}

  access_entries = {{
    admin = {{
      kubernetes_groups = []
      principal_arn     = var.admin_role_arn
      policy_associations = {{
        admin = {{
          policy_arn = "arn:aws:eks::aws:cluster-access-policy/AmazonEKSClusterAdminPolicy"
          access_scope = {{ type = "cluster" }}
        }}
      }}
    }}
  }}
}}

# ── RDS PostgreSQL ───────────────────────────────────────────────────────────
module "rds" {{
  source  = "terraform-aws-modules/rds/aws"
  version = "~> 6.0"

  identifier = "{slug}-${{var.environment}}"

  engine               = "postgres"
  engine_version       = "16.1"
  family               = "postgres16"
  major_engine_version = "16"
  instance_class       = var.db_instance_class

  allocated_storage     = 20
  max_allocated_storage = 200
  storage_encrypted     = true

  db_name  = replace("{slug}", "-", "_")
  username = "{slug}_admin"
  port     = 5432

  multi_az               = var.environment == "production"
  db_subnet_group_name   = module.vpc.database_subnet_group
  vpc_security_group_ids = [aws_security_group.rds.id]

  backup_retention_period = 7
  skip_final_snapshot     = var.environment != "production"
  deletion_protection     = var.environment == "production"

  performance_insights_enabled = true
}}

# ── ElastiCache Redis ─────────────────────────────────────────────────────────
resource "aws_elasticache_replication_group" "redis" {{
  replication_group_id = "{slug}-redis"
  description          = "Redis for {slug}"

  node_type               = var.redis_node_type
  num_cache_clusters      = var.environment == "production" ? 3 : 1
  engine_version          = "7.1"
  port                    = 6379
  parameter_group_name    = "default.redis7"

  subnet_group_name  = aws_elasticache_subnet_group.main.name
  security_group_ids = [aws_security_group.redis.id]

  at_rest_encryption_enabled = true
  transit_encryption_enabled = true

  automatic_failover_enabled = var.environment == "production"
}}

resource "aws_elasticache_subnet_group" "main" {{
  name       = "{slug}-redis-subnets"
  subnet_ids = module.vpc.private_subnets
}}

# ── Security Groups ───────────────────────────────────────────────────────────
resource "aws_security_group" "rds" {{
  name_prefix = "{slug}-rds-"
  vpc_id      = module.vpc.vpc_id

  ingress {{
    from_port       = 5432
    to_port         = 5432
    protocol        = "tcp"
    security_groups = [module.eks.node_security_group_id]
  }}
}}

resource "aws_security_group" "redis" {{
  name_prefix = "{slug}-redis-"
  vpc_id      = module.vpc.vpc_id

  ingress {{
    from_port       = 6379
    to_port         = 6379
    protocol        = "tcp"
    security_groups = [module.eks.node_security_group_id]
  }}
}}
""")

    (eks_dir / "variables.tf").write_text(f"""\
variable "aws_region" {{
  description = "AWS region"
  default     = "us-east-1"
}}

variable "environment" {{
  description = "Deployment environment (staging | production)"
  default     = "staging"
}}

variable "node_instance_type" {{
  description = "EKS worker node EC2 instance type"
  default     = "t3.medium"
}}

variable "db_instance_class" {{
  description = "RDS instance class"
  default     = "db.t3.medium"
}}

variable "redis_node_type" {{
  description = "ElastiCache node type"
  default     = "cache.t3.micro"
}}

variable "admin_role_arn" {{
  description = "ARN of the IAM role granted cluster admin access"
}}
""")

    (eks_dir / "outputs.tf").write_text(f"""\
output "cluster_endpoint" {{
  value = module.eks.cluster_endpoint
}}

output "rds_endpoint" {{
  value = module.rds.db_instance_endpoint
}}

output "redis_endpoint" {{
  value = aws_elasticache_replication_group.redis.primary_endpoint_address
}}

output "vpc_id" {{
  value = module.vpc.vpc_id
}}
""")

    (eks_dir / "README.md").write_text(f"""\
# Terraform — AWS EKS for {slug}

Generated by AetherOS.

## Prerequisites
- AWS CLI configured with sufficient permissions
- Terraform >= 1.6
- An S3 bucket named `{slug}-terraform-state` in us-east-1

## Deploy

```bash
terraform init
terraform plan -var="environment=staging" -var="admin_role_arn=arn:aws:iam::ACCOUNT:role/ROLE"
terraform apply
```

## After deploy
Update `helm/{slug}/values.prod.yaml` with the Terraform outputs:
```bash
terraform output rds_endpoint
terraform output redis_endpoint
```
""")

    logger.info("p11e: AWS EKS Terraform module written to %s", eks_dir)


# ── Private helpers ───────────────────────────────────────────────────────────

def _setup_step(lang: str) -> str:
    if lang == "go":
        return """\
        uses: actions/setup-go@v5
        with:
          go-version: "1.21"
          cache: true"""
    if lang == "typescript":
        return """\
        uses: actions/setup-node@v4
        with:
          node-version: "20"
          cache: npm"""
    return """\
        uses: actions/setup-python@v5
        with:
          python-version: "3.12"
          cache: pip"""


def _install_step(lang: str) -> str:
    if lang == "go":
        return "        run: go mod download"
    if lang == "typescript":
        return "        run: npm ci"
    return "        run: pip install -r requirements.txt"


def _test_step(lang: str) -> str:
    if lang == "go":
        return "          go test ./... -race -coverprofile=coverage.out"
    if lang == "typescript":
        return "          npm test"
    return "          pytest --tb=short -q"


def _lint_step(lang: str) -> str:
    if lang == "go":
        return """\
        uses: golangci/golangci-lint-action@v4
        with:
          version: latest"""
    if lang == "typescript":
        return "        run: npm run lint"
    return """\
        run: |
          pip install ruff
          ruff check ."""
