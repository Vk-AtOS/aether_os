"""P11e Enterprise Deployment — prompt strings and templates.

Contains: the LLM prompt for AWS Terraform generation and the
fallback AWS Terraform template string.
"""
from __future__ import annotations
import json


def build_aws_terraform_prompt(
    project_name: str,
    domain: str,
    tech_stack: dict,
    raw_input: str,
) -> str:
    """Build the LLM prompt for generating production-ready AWS Terraform (main.tf)."""
    return (
        f'Generate production-ready AWS Terraform (main.tf) for "{project_name}" ({domain} domain).\n\n'
        f"Tech stack: {json.dumps(tech_stack)}\n"
        f"Description: {raw_input[:1500]}\n\n"
        f"Infrastructure to create:\n"
        f"1. VPC with public/private subnets across 2 AZs\n"
        f"2. ECS Fargate cluster + task definition + service (3 desired count)\n"
        f"   - Container port: 8000, CPU: 512, Memory: 1024\n"
        f"   - Environment variables from AWS Secrets Manager\n"
        f"3. Application Load Balancer (port 443 with ACM cert, port 80 redirect)\n"
        f"4. RDS PostgreSQL 15 (db.t3.medium, Multi-AZ, encrypted, 7-day backup retention)\n"
        f"5. ElastiCache Redis (cache.t3.micro, single node)\n"
        f"6. Security groups with least-privilege rules\n"
        f"7. IAM role for ECS task execution\n"
        f"8. CloudWatch log group\n\n"
        f"Use variables: var.app_name, var.aws_region, var.environment, var.db_password, var.container_image\n\n"
        f"Return ONLY valid HCL Terraform code. No markdown, no explanation."
    )


def aws_terraform_template(slug: str, app_name: str, domain: str) -> str:
    """Fallback AWS Terraform template used when the LLM call fails."""
    return f"""\
# AWS infrastructure for {app_name} — generated by AetherOS p11e_enterprise_deployment
# Apply: terraform init && terraform apply -var="db_password=SecurePass123"

terraform {{
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

provider "aws" {{
  region = var.aws_region
}}

# ── VPC ──────────────────────────────────────────────────────────────────────
resource "aws_vpc" "main" {{
  cidr_block           = "10.0.0.0/16"
  enable_dns_hostnames = true
  tags = {{ Name = "${{var.app_name}}-vpc", Environment = var.environment }}
}}

resource "aws_subnet" "public" {{
  count             = 2
  vpc_id            = aws_vpc.main.id
  cidr_block        = cidrsubnet("10.0.0.0/16", 8, count.index)
  availability_zone = data.aws_availability_zones.available.names[count.index]
  map_public_ip_on_launch = true
  tags = {{ Name = "${{var.app_name}}-public-${{count.index}}" }}
}}

resource "aws_subnet" "private" {{
  count             = 2
  vpc_id            = aws_vpc.main.id
  cidr_block        = cidrsubnet("10.0.0.0/16", 8, count.index + 10)
  availability_zone = data.aws_availability_zones.available.names[count.index]
  tags = {{ Name = "${{var.app_name}}-private-${{count.index}}" }}
}}

data "aws_availability_zones" "available" {{ state = "available" }}

resource "aws_internet_gateway" "main" {{
  vpc_id = aws_vpc.main.id
}}

# ── ECS Fargate ───────────────────────────────────────────────────────────────
resource "aws_ecs_cluster" "main" {{
  name = "${{var.app_name}}-cluster"
}}

resource "aws_cloudwatch_log_group" "main" {{
  name              = "/ecs/${{var.app_name}}"
  retention_in_days = 30
}}

resource "aws_ecs_task_definition" "main" {{
  family                   = var.app_name
  network_mode             = "awsvpc"
  requires_compatibilities = ["FARGATE"]
  cpu                      = "512"
  memory                   = "1024"
  execution_role_arn       = aws_iam_role.ecs_execution.arn

  container_definitions = jsonencode([{{
    name      = var.app_name
    image     = var.container_image
    portMappings = [{{ containerPort = 8000 }}]
    environment = [
      {{ name = "ENVIRONMENT", value = var.environment }},
    ]
    secrets = [
      {{ name = "DATABASE_URL", valueFrom = aws_secretsmanager_secret.db_url.arn }},
      {{ name = "SECRET_KEY",   valueFrom = aws_secretsmanager_secret.secret_key.arn }},
    ]
    logConfiguration = {{
      logDriver = "awslogs"
      options = {{
        "awslogs-group"  = aws_cloudwatch_log_group.main.name
        "awslogs-region" = var.aws_region
        "awslogs-stream-prefix" = "ecs"
      }}
    }}
  }}])
}}

resource "aws_ecs_service" "main" {{
  name            = var.app_name
  cluster         = aws_ecs_cluster.main.id
  task_definition = aws_ecs_task_definition.main.arn
  desired_count   = 3
  launch_type     = "FARGATE"

  network_configuration {{
    subnets          = aws_subnet.private[*].id
    security_groups  = [aws_security_group.app.id]
  }}

  load_balancer {{
    target_group_arn = aws_lb_target_group.main.arn
    container_name   = var.app_name
    container_port   = 8000
  }}
}}

# ── RDS PostgreSQL ────────────────────────────────────────────────────────────
resource "aws_db_instance" "main" {{
  identifier        = "${{var.app_name}}-db"
  engine            = "postgres"
  engine_version    = "15"
  instance_class    = "db.t3.medium"
  allocated_storage = 20
  storage_encrypted = true
  db_name           = "appdb"
  username          = "appuser"
  password          = var.db_password
  multi_az          = true
  backup_retention_period = 7
  vpc_security_group_ids  = [aws_security_group.db.id]
  db_subnet_group_name    = aws_db_subnet_group.main.name
  skip_final_snapshot     = false
  final_snapshot_identifier = "${{var.app_name}}-final-snapshot"
}}

resource "aws_db_subnet_group" "main" {{
  name       = "${{var.app_name}}-db-subnet"
  subnet_ids = aws_subnet.private[*].id
}}

# ── ElastiCache Redis ─────────────────────────────────────────────────────────
resource "aws_elasticache_cluster" "main" {{
  cluster_id           = "${{var.app_name}}-redis"
  engine               = "redis"
  node_type            = "cache.t3.micro"
  num_cache_nodes      = 1
  parameter_group_name = "default.redis7"
  port                 = 6379
  subnet_group_name    = aws_elasticache_subnet_group.main.name
  security_group_ids   = [aws_security_group.redis.id]
}}

resource "aws_elasticache_subnet_group" "main" {{
  name       = "${{var.app_name}}-redis-subnet"
  subnet_ids = aws_subnet.private[*].id
}}

# ── ALB ───────────────────────────────────────────────────────────────────────
resource "aws_lb" "main" {{
  name               = "${{var.app_name}}-alb"
  internal           = false
  load_balancer_type = "application"
  security_groups    = [aws_security_group.alb.id]
  subnets            = aws_subnet.public[*].id
}}

resource "aws_lb_target_group" "main" {{
  name        = "${{var.app_name}}-tg"
  port        = 8000
  protocol    = "HTTP"
  vpc_id      = aws_vpc.main.id
  target_type = "ip"
  health_check {{ path = "/health" }}
}}

# ── IAM ───────────────────────────────────────────────────────────────────────
resource "aws_iam_role" "ecs_execution" {{
  name = "${{var.app_name}}-ecs-execution"
  assume_role_policy = jsonencode({{
    Version   = "2012-10-17"
    Statement = [{{ Action = "sts:AssumeRole", Effect = "Allow", Principal = {{ Service = "ecs-tasks.amazonaws.com" }} }}]
  }})
}}

resource "aws_iam_role_policy_attachment" "ecs_execution" {{
  role       = aws_iam_role.ecs_execution.name
  policy_arn = "arn:aws:iam::aws:policy/service-role/AmazonECSTaskExecutionRolePolicy"
}}

# ── Security Groups ───────────────────────────────────────────────────────────
resource "aws_security_group" "alb"  {{ vpc_id = aws_vpc.main.id name = "${{var.app_name}}-alb" }}
resource "aws_security_group" "app"  {{ vpc_id = aws_vpc.main.id name = "${{var.app_name}}-app" }}
resource "aws_security_group" "db"   {{ vpc_id = aws_vpc.main.id name = "${{var.app_name}}-db" }}
resource "aws_security_group" "redis" {{ vpc_id = aws_vpc.main.id name = "${{var.app_name}}-redis" }}

# ── Secrets Manager ───────────────────────────────────────────────────────────
resource "aws_secretsmanager_secret" "db_url" {{ name = "${{var.app_name}}/DATABASE_URL" }}
resource "aws_secretsmanager_secret" "secret_key" {{ name = "${{var.app_name}}/SECRET_KEY" }}
"""
