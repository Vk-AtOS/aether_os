"""P11e Enterprise Deployment — helper utilities.

Contains: Helm chart writer, Azure Terraform writer, and operational script writers.
All functions generate files from deterministic templates (no LLM calls).
"""
from __future__ import annotations
import logging
import os
from pathlib import Path

logger = logging.getLogger(__name__)


def write_helm_chart(output_dir: Path, app_name: str, slug: str) -> None:
    """Write a production-grade Helm chart."""
    helm_dir = output_dir / "helm" / slug
    templates_dir = helm_dir / "templates"
    templates_dir.mkdir(parents=True, exist_ok=True)

    # Chart.yaml
    (helm_dir / "Chart.yaml").write_text(f"""\
apiVersion: v2
name: {slug}
description: Helm chart for {app_name} — generated by AetherOS
type: application
version: 0.1.0
appVersion: "1.0.0"
""")

    # values.yaml
    (helm_dir / "values.yaml").write_text(f"""\
# Default values for {slug}
replicaCount: 3

image:
  repository: {slug}
  pullPolicy: IfNotPresent
  tag: "latest"

service:
  type: ClusterIP
  port: 80
  targetPort: 8000

ingress:
  enabled: true
  className: nginx
  annotations:
    cert-manager.io/cluster-issuer: letsencrypt-prod
  hosts:
    - host: app.yourdomain.com
      paths:
        - path: /
          pathType: Prefix
  tls:
    - secretName: {slug}-tls
      hosts:
        - app.yourdomain.com

resources:
  requests:
    cpu: 500m
    memory: 512Mi
  limits:
    cpu: 2000m
    memory: 2Gi

autoscaling:
  enabled: true
  minReplicas: 3
  maxReplicas: 20
  targetCPUUtilizationPercentage: 70
  targetMemoryUtilizationPercentage: 80

env:
  DATABASE_URL: ""
  SECRET_KEY: ""
  REDIS_URL: "redis://redis:6379"
  CORS_ORIGINS: "https://yourdomain.com"

postgresql:
  enabled: true
  auth:
    database: appdb
    username: appuser
    existingSecret: {slug}-db-secret

redis:
  enabled: true
  architecture: standalone
""")

    # values.prod.yaml
    (helm_dir / "values.prod.yaml").write_text(f"""\
# Production overrides — set these before deploying to production
replicaCount: 5

image:
  pullPolicy: Always

autoscaling:
  minReplicas: 5
  maxReplicas: 50

resources:
  requests:
    cpu: 1000m
    memory: 1Gi
  limits:
    cpu: 4000m
    memory: 4Gi
""")

    # templates/deployment.yaml
    (templates_dir / "deployment.yaml").write_text(f"""\
apiVersion: apps/v1
kind: Deployment
metadata:
  name {{{{ include "{slug}.fullname" . }}}}
  labels:
    {{{{- include "{slug}.labels" . | nindent 4 }}}}
spec:
  {{{{- if not .Values.autoscaling.enabled }}}}
  replicas: {{{{ .Values.replicaCount }}}}
  {{{{- end }}}}
  selector:
    matchLabels:
      {{{{- include "{slug}.selectorLabels" . | nindent 6 }}}}
  template:
    metadata:
      labels:
        {{{{- include "{slug}.selectorLabels" . | nindent 8 }}}}
    spec:
      containers:
        - name: {{{{ .Chart.Name }}}}
          image: "{{{{ .Values.image.repository }}}}:{{{{ .Values.image.tag }}}}"
          imagePullPolicy: {{{{ .Values.image.pullPolicy }}}}
          ports:
            - containerPort: {{{{ .Values.service.targetPort }}}}
          envFrom:
            - secretRef:
                name: {{{{ include "{slug}.fullname" . }}}}-secrets
          resources:
            {{{{- toYaml .Values.resources | nindent 12 }}}}
          livenessProbe:
            httpGet:
              path: /health
              port: {{{{ .Values.service.targetPort }}}}
            initialDelaySeconds: 15
            periodSeconds: 10
          readinessProbe:
            httpGet:
              path: /ready
              port: {{{{ .Values.service.targetPort }}}}
            initialDelaySeconds: 5
            periodSeconds: 5
""")

    # templates/service.yaml
    (templates_dir / "service.yaml").write_text(f"""\
apiVersion: v1
kind: Service
metadata:
  name: {{{{ include "{slug}.fullname" . }}}}
  labels:
    {{{{- include "{slug}.labels" . | nindent 4 }}}}
spec:
  type: {{{{ .Values.service.type }}}}
  ports:
    - port: {{{{ .Values.service.port }}}}
      targetPort: {{{{ .Values.service.targetPort }}}}
      protocol: TCP
  selector:
    {{{{- include "{slug}.selectorLabels" . | nindent 4 }}}}
""")

    # templates/ingress.yaml
    (templates_dir / "ingress.yaml").write_text(f"""\
{{{{- if .Values.ingress.enabled -}}}}
apiVersion: networking.k8s.io/v1
kind: Ingress
metadata:
  name: {{{{ include "{slug}.fullname" . }}}}
  labels:
    {{{{- include "{slug}.labels" . | nindent 4 }}}}
  {{{{- with .Values.ingress.annotations }}}}
  annotations:
    {{{{- toYaml . | nindent 4 }}}}
  {{{{- end }}}}
spec:
  {{{{- with .Values.ingress.tls }}}}
  tls:
    {{{{- toYaml . | nindent 4 }}}}
  {{{{- end }}}}
  rules:
    {{{{- range .Values.ingress.hosts }}}}
    - host: {{{{ .host | quote }}}}
      http:
        paths:
          {{{{- range .paths }}}}
          - path: {{{{ .path }}}}
            pathType: {{{{ .pathType }}}}
            backend:
              service:
                name: {{{{ include "{slug}.fullname" $ }}}}
                port:
                  number: {{{{ $.Values.service.port }}}}
          {{{{- end }}}}
    {{{{- end }}}}
{{{{- end }}}}
""")

    # templates/hpa.yaml
    (templates_dir / "hpa.yaml").write_text(f"""\
{{{{- if .Values.autoscaling.enabled }}}}
apiVersion: autoscaling/v2
kind: HorizontalPodAutoscaler
metadata:
  name: {{{{ include "{slug}.fullname" . }}}}
spec:
  scaleTargetRef:
    apiVersion: apps/v1
    kind: Deployment
    name: {{{{ include "{slug}.fullname" . }}}}
  minReplicas: {{{{ .Values.autoscaling.minReplicas }}}}
  maxReplicas: {{{{ .Values.autoscaling.maxReplicas }}}}
  metrics:
    - type: Resource
      resource:
        name: cpu
        target:
          type: Utilization
          averageUtilization: {{{{ .Values.autoscaling.targetCPUUtilizationPercentage }}}}
{{{{- end }}}}
""")

    # templates/configmap.yaml
    (templates_dir / "configmap.yaml").write_text(f"""\
apiVersion: v1
kind: ConfigMap
metadata:
  name: {{{{ include "{slug}.fullname" . }}}}-config
data:
  ENVIRONMENT: production
  REDIS_URL: "{{{{ .Values.env.REDIS_URL }}}}"
  CORS_ORIGINS: "{{{{ .Values.env.CORS_ORIGINS }}}}"
""")

    # templates/secret.yaml (template — placeholders only)
    (templates_dir / "secret.yaml").write_text(f"""\
# DO NOT commit real values. Use external-secrets or sealed-secrets in production.
apiVersion: v1
kind: Secret
metadata:
  name: {{{{ include "{slug}.fullname" . }}}}-secrets
type: Opaque
stringData:
  DATABASE_URL: "{{{{ .Values.env.DATABASE_URL }}}}"
  SECRET_KEY: "{{{{ .Values.env.SECRET_KEY }}}}"
""")

    # templates/pvc.yaml
    (templates_dir / "pvc.yaml").write_text(f"""\
apiVersion: v1
kind: PersistentVolumeClaim
metadata:
  name: {{{{ include "{slug}.fullname" . }}}}-data
spec:
  accessModes:
    - ReadWriteOnce
  resources:
    requests:
      storage: 10Gi
""")

    # _helpers.tpl
    (templates_dir / "_helpers.tpl").write_text(f"""\
{{{{/*
Expand the name of the chart.
*/}}}}
{{{{- define "{slug}.name" -}}}}
{{{{- .Chart.Name }}}}
{{{{- end }}}}

{{{{- define "{slug}.fullname" -}}}}
{{{{- .Release.Name }}}}-{slug}
{{{{- end }}}}

{{{{- define "{slug}.labels" -}}}}
helm.sh/chart: {{{{ .Chart.Name }}}}-{{{{ .Chart.Version }}}}
app.kubernetes.io/name: {{{{ include "{slug}.name" . }}}}
app.kubernetes.io/instance: {{{{ .Release.Name }}}}
app.kubernetes.io/version: {{{{ .Chart.AppVersion | quote }}}}
app.kubernetes.io/managed-by: {{{{ .Release.Service }}}}
{{{{- end }}}}

{{{{- define "{slug}.selectorLabels" -}}}}
app.kubernetes.io/name: {{{{ include "{slug}.name" . }}}}
app.kubernetes.io/instance: {{{{ .Release.Name }}}}
{{{{- end }}}}
""")

    logger.info("p11e: Helm chart written to %s", helm_dir)


def write_terraform_azure(output_dir: Path, app_name: str, slug: str) -> None:
    """Write Azure Terraform (AKS + Azure Database for PostgreSQL + Azure Cache for Redis)."""
    tf_dir = output_dir / "terraform" / "azure"
    tf_dir.mkdir(parents=True, exist_ok=True)

    (tf_dir / "variables.tf").write_text(f"""\
variable "resource_group_name" {{
  description = "Azure resource group name"
  default     = "{slug}-rg"
}}

variable "location" {{
  description = "Azure region"
  default     = "East US"
}}

variable "app_name" {{
  description = "Application name"
  default     = "{slug}"
}}

variable "db_admin_password" {{
  description = "PostgreSQL admin password"
  sensitive   = true
}}
""")

    (tf_dir / "main.tf").write_text(f"""\
# Azure infrastructure for {app_name}
# Generated by AetherOS p11e_enterprise_deployment

terraform {{
  required_providers {{
    azurerm = {{
      source  = "hashicorp/azurerm"
      version = "~> 3.0"
    }}
  }}
}}

provider "azurerm" {{
  features {{}}
}}

resource "azurerm_resource_group" "main" {{
  name     = var.resource_group_name
  location = var.location
}}

# AKS Cluster
resource "azurerm_kubernetes_cluster" "main" {{
  name                = "${{var.app_name}}-aks"
  location            = azurerm_resource_group.main.location
  resource_group_name = azurerm_resource_group.main.name
  dns_prefix          = var.app_name

  default_node_pool {{
    name       = "default"
    node_count = 3
    vm_size    = "Standard_D2_v2"
  }}

  identity {{
    type = "SystemAssigned"
  }}
}}

# Azure Database for PostgreSQL
resource "azurerm_postgresql_flexible_server" "main" {{
  name                = "${{var.app_name}}-psql"
  resource_group_name = azurerm_resource_group.main.name
  location            = azurerm_resource_group.main.location
  version             = "15"
  administrator_login = "appuser"
  administrator_password = var.db_admin_password
  storage_mb          = 32768
  sku_name            = "GP_Standard_D2s_v3"
}}

# Azure Cache for Redis
resource "azurerm_redis_cache" "main" {{
  name                = "${{var.app_name}}-redis"
  location            = azurerm_resource_group.main.location
  resource_group_name = azurerm_resource_group.main.name
  capacity            = 1
  family              = "C"
  sku_name            = "Standard"
}}
""")

    (tf_dir / "outputs.tf").write_text(f"""\
output "aks_kube_config" {{
  value     = azurerm_kubernetes_cluster.main.kube_config_raw
  sensitive = true
}}

output "db_fqdn" {{
  value = azurerm_postgresql_flexible_server.main.fqdn
}}

output "redis_hostname" {{
  value = azurerm_redis_cache.main.hostname
}}
""")

    logger.info("p11e: Azure Terraform written to %s", tf_dir)


def write_operational_scripts(output_dir: Path, app_name: str, slug: str) -> None:
    """Write operational scripts: backup, restore, upgrade, healthcheck, bundle."""
    scripts_dir = output_dir / "scripts"
    scripts_dir.mkdir(parents=True, exist_ok=True)

    # backup.sh
    backup_sh = scripts_dir / "backup.sh"
    backup_sh.write_text(f"""\
#!/usr/bin/env bash
# Backup {app_name} PostgreSQL database to S3
# Usage: ./scripts/backup.sh [--dry-run]
set -euo pipefail

APP_NAME="{slug}"
BACKUP_BUCKET="${{BACKUP_S3_BUCKET:-s3://your-backups-bucket}}"
TIMESTAMP=$(date +%Y%m%d_%H%M%S)
BACKUP_FILE="/tmp/${{APP_NAME}}_backup_${{TIMESTAMP}}.sql.gz"
RETENTION_DAYS="${{BACKUP_RETENTION_DAYS:-30}}"

echo "[${{TIMESTAMP}}] Starting backup of ${{APP_NAME}}..."

# Dump and compress
pg_dump "${{DATABASE_URL}}" | gzip > "${{BACKUP_FILE}}"
echo "Backup created: ${{BACKUP_FILE}} ($(du -h "${{BACKUP_FILE}}" | cut -f1))"

if [ "${{1:-}}" != "--dry-run" ]; then
    # Upload to S3
    aws s3 cp "${{BACKUP_FILE}}" "${{BACKUP_BUCKET}}/${{APP_NAME}}/" --storage-class STANDARD_IA
    echo "Uploaded to ${{BACKUP_BUCKET}}/${{APP_NAME}}/"

    # Apply retention policy
    aws s3 ls "${{BACKUP_BUCKET}}/${{APP_NAME}}/" | awk '{{print $4}}' | sort | head -n -${{RETENTION_DAYS}} | xargs -I {{}} aws s3 rm "${{BACKUP_BUCKET}}/${{APP_NAME}}/{{}}"
    echo "Retention policy applied (keep ${{RETENTION_DAYS}} most recent)"
fi

rm -f "${{BACKUP_FILE}}"
echo "Backup complete."
""")
    os.chmod(backup_sh, 0o755)

    # restore.sh
    restore_sh = scripts_dir / "restore.sh"
    restore_sh.write_text(f"""\
#!/usr/bin/env bash
# Restore {app_name} from S3 backup
# Usage: ./scripts/restore.sh <s3://bucket/path/backup.sql.gz>
set -euo pipefail

if [ -z "${{1:-}}" ]; then
    echo "Usage: $0 <s3://bucket/path/backup.sql.gz>"
    exit 1
fi

S3_PATH="$1"
LOCAL_FILE="/tmp/restore_$(basename $S3_PATH)"

echo "Downloading ${{S3_PATH}}..."
aws s3 cp "${{S3_PATH}}" "${{LOCAL_FILE}}"

echo "Restoring to database..."
gunzip -c "${{LOCAL_FILE}}" | psql "${{DATABASE_URL}}"

rm -f "${{LOCAL_FILE}}"
echo "Restore complete."
""")
    os.chmod(restore_sh, 0o755)

    # upgrade.sh
    upgrade_sh = scripts_dir / "upgrade.sh"
    upgrade_sh.write_text(f"""\
#!/usr/bin/env bash
# Rolling upgrade: pull new Docker image, run migrations, rolling restart
# Usage: ./scripts/upgrade.sh <new-image-tag>
set -euo pipefail

IMAGE_TAG="${{1:-latest}}"
NAMESPACE="${{KUBE_NAMESPACE:-default}}"
DEPLOYMENT="{slug}"

echo "Upgrading ${{DEPLOYMENT}} to image tag: ${{IMAGE_TAG}}"

# Pull new image
docker pull "${{DEPLOYMENT}}:${{IMAGE_TAG}}"

# Run Alembic migrations in a one-off pod
kubectl run migrations-${{IMAGE_TAG//./}} \\
    --image="${{DEPLOYMENT}}:${{IMAGE_TAG}}" \\
    --env="DATABASE_URL=${{DATABASE_URL}}" \\
    --restart=Never --rm -i --wait \\
    --namespace="${{NAMESPACE}}" \\
    -- alembic upgrade head

# Rolling restart
kubectl set image deployment/${{DEPLOYMENT}} \\
    ${{DEPLOYMENT}}="${{DEPLOYMENT}}:${{IMAGE_TAG}}" \\
    --namespace="${{NAMESPACE}}"

kubectl rollout status deployment/${{DEPLOYMENT}} --namespace="${{NAMESPACE}}"
echo "Upgrade complete."
""")
    os.chmod(upgrade_sh, 0o755)

    # healthcheck.sh
    healthcheck_sh = scripts_dir / "healthcheck.sh"
    healthcheck_sh.write_text(f"""\
#!/usr/bin/env bash
# Check health of all {app_name} services, output JSON status
set -euo pipefail

API_URL="${{APP_URL:-http://localhost:8000}}"
TIMESTAMP=$(date -u +%Y-%m-%dT%H:%M:%SZ)

check_service() {{
    local name="$1"
    local url="$2"
    local status
    local http_code
    http_code=$(curl -s -o /dev/null -w "%{{http_code}}" --max-time 5 "${{url}}" || echo "000")
    if [ "${{http_code}}" = "200" ]; then
        status="healthy"
    else
        status="unhealthy (HTTP ${{http_code}})"
    fi
    echo "{{\\"service\\": \\"${{name}}\\", \\"status\\": \\"${{status}}\\", \\"url\\": \\"${{url}}\\"}}"
}}

echo "{{"
echo "  \\"timestamp\\": \\"${{TIMESTAMP}}\\","
echo "  \\"app\\": \\"{app_name}\\","
echo "  \\"checks\\": ["
check_service "api" "${{API_URL}}/health"
check_service "api_ready" "${{API_URL}}/ready"
echo "  ]"
echo "}}"
""")
    os.chmod(healthcheck_sh, 0o755)

    # bundle.sh
    bundle_sh = scripts_dir / "bundle.sh"
    bundle_sh.write_text(f"""\
#!/usr/bin/env bash
# Air-gap bundle: package Docker images + Helm chart into a single tarball
# Usage: ./scripts/bundle.sh [output-dir]
set -euo pipefail

APP_NAME="{slug}"
VERSION="${{1:-$(date +%Y%m%d)}}"
OUTPUT_DIR="${{2:-./dist}}"
BUNDLE_NAME="${{APP_NAME}}-bundle-${{VERSION}}.tar.gz"

mkdir -p "${{OUTPUT_DIR}}"
WORK_DIR=$(mktemp -d)
trap 'rm -rf "${{WORK_DIR}}"' EXIT

echo "Building bundle ${{BUNDLE_NAME}}..."

# Save Docker images
docker save "${{APP_NAME}}:latest" | gzip > "${{WORK_DIR}}/${{APP_NAME}}.tar.gz"

# Copy Helm chart
cp -r helm/"${{APP_NAME}}" "${{WORK_DIR}}/helm"

# Copy scripts and docs
cp -r scripts/ "${{WORK_DIR}}/"
[ -d docs/ ] && cp -r docs/ "${{WORK_DIR}}/"

# Create bundle
tar -czf "${{OUTPUT_DIR}}/${{BUNDLE_NAME}}" -C "${{WORK_DIR}}" .
echo "Bundle created: ${{OUTPUT_DIR}}/${{BUNDLE_NAME}} ($(du -h "${{OUTPUT_DIR}}/${{BUNDLE_NAME}}" | cut -f1))"
""")
    os.chmod(bundle_sh, 0o755)

    logger.info("p11e: operational scripts written to %s", scripts_dir)
