"""AetherOS Layer 8 — Multi-Region Generator.

Generates active-active multi-region Terraform configuration:
  - AWS Global Accelerator (anycast entry point with per-region endpoint groups)
  - Route53 latency-based routing with health checks
  - Cross-region VPC peering mesh
  - Terraform variables + outputs
  - Markdown deployment guide

All output is deterministic template-based generation — no LLM calls.
"""
from __future__ import annotations

import logging
from itertools import combinations
from pathlib import Path
from typing import List

logger = logging.getLogger(__name__)

DEFAULT_REGIONS = ["us-east-1", "eu-west-1", "ap-southeast-1"]


def generate_global_accelerator_tf(slug: str, regions: List[str]) -> str:
    """Return Terraform for AWS Global Accelerator with one endpoint group per region.

    Primary region receives weight=100; all others receive weight=50.
    DUAL_STACK address type enables IPv4+IPv6 anycast.
    """
    primary = regions[0]

    endpoint_groups = ""
    for region in regions:
        weight = 100 if region == primary else 50
        endpoint_groups += f"""\
resource "aws_globalaccelerator_endpoint_group" "{slug}_{region.replace("-", "_")}" {{
  listener_arn          = aws_globalaccelerator_listener.{slug}.id
  endpoint_group_region = "{region}"
  traffic_dial_percentage = {weight}

  endpoint_configuration {{
    endpoint_id = var.alb_arns["{region}"]
    weight      = {weight}
    client_ip_preservation_enabled = true
  }}

  health_check_path             = "/health"
  health_check_protocol         = "HTTP"
  health_check_interval_seconds = 10
  threshold_count               = 2
}}

"""

    return f"""\
# AWS Global Accelerator — {slug}
# Provides anycast entry point with automatic failover between regions.
# Generated by AetherOS p20_multiregion

resource "aws_globalaccelerator_accelerator" "{slug}" {{
  name            = "{slug}-global"
  ip_address_type = "DUAL_STACK"
  enabled         = true

  attributes {{
    flow_logs_enabled   = true
    flow_logs_s3_bucket = var.flow_logs_bucket
    flow_logs_s3_prefix = "{slug}/"
  }}
}}

resource "aws_globalaccelerator_listener" "{slug}" {{
  accelerator_arn = aws_globalaccelerator_accelerator.{slug}.id
  protocol        = "TCP"

  port_range {{
    from_port = 80
    to_port   = 80
  }}

  port_range {{
    from_port = 443
    to_port   = 443
  }}
}}

{endpoint_groups}
"""


def generate_route53_latency_routing(
    slug: str, regions: List[str], hosted_zone_id: str
) -> str:
    """Return Terraform for Route53 latency-based routing with per-region health checks.

    Each record uses a distinct set_identifier so Route53 knows they are
    alternatives rather than equal-weight round-robin entries.
    failure_threshold=2 means two consecutive health check failures trigger
    Route53 to stop routing traffic to that region (fast failover).
    """
    records = ""
    for region in regions:
        records += f"""\
resource "aws_route53_health_check" "{slug}_{region.replace("-", "_")}" {{
  fqdn              = var.alb_dns["{region}"]
  port              = 443
  type              = "HTTPS"
  resource_path     = "/health"
  failure_threshold = 2
  request_interval  = 10

  tags = {{
    Name   = "{slug}-{region}-health"
    Region = "{region}"
  }}
}}

resource "aws_route53_record" "{slug}_{region.replace("-", "_")}" {{
  zone_id        = var.hosted_zone_id
  name           = var.domain_name
  type           = "A"
  set_identifier = "{slug}-{region}"

  latency_routing_policy {{
    region = "{region}"
  }}

  alias {{
    name                   = var.alb_dns["{region}"]
    zone_id                = var.alb_zone_ids["{region}"]
    evaluate_target_health = true
  }}

  health_check_id = aws_route53_health_check.{slug}_{region.replace("-", "_")}.id
}}

"""

    return f"""\
# Route53 latency-based routing — {slug}
# Routes each user to the region with the lowest measured latency.
# Health check failure removes the region from DNS within ~30 s.

{records}
"""


def generate_vpc_peering_tf(slug: str, regions: List[str]) -> str:
    """Return Terraform for a full-mesh cross-region VPC peering topology.

    Creates one peering connection per unique region pair (n*(n-1)/2 total).
    Route table entries and security group rules allow cross-cell service
    discovery on port 8000 (the AetherOS default app port).
    """
    peering_blocks = ""
    for r1, r2 in combinations(regions, 2):
        r1_id = r1.replace("-", "_")
        r2_id = r2.replace("-", "_")
        peering_blocks += f"""\
# Peering: {r1} ↔ {r2}
resource "aws_vpc_peering_connection" "{slug}_{r1_id}_{r2_id}" {{
  provider    = aws.{r1_id}
  vpc_id      = var.vpc_ids["{r1}"]
  peer_vpc_id = var.vpc_ids["{r2}"]
  peer_region = "{r2}"
  auto_accept = false

  tags = {{
    Name = "{slug}-peer-{r1}-{r2}"
  }}
}}

resource "aws_vpc_peering_connection_accepter" "{slug}_{r1_id}_{r2_id}" {{
  provider                  = aws.{r2_id}
  vpc_peering_connection_id = aws_vpc_peering_connection.{slug}_{r1_id}_{r2_id}.id
  auto_accept               = true

  tags = {{
    Name = "{slug}-peer-{r2}-accept-{r1}"
  }}
}}

# Route table entries for {r1} → {r2}
resource "aws_route" "{slug}_{r1_id}_to_{r2_id}" {{
  provider                  = aws.{r1_id}
  route_table_id            = var.route_table_ids["{r1}"]
  destination_cidr_block    = var.vpc_cidrs["{r2}"]
  vpc_peering_connection_id = aws_vpc_peering_connection.{slug}_{r1_id}_{r2_id}.id
}}

# Route table entries for {r2} → {r1}
resource "aws_route" "{slug}_{r2_id}_to_{r1_id}" {{
  provider                  = aws.{r2_id}
  route_table_id            = var.route_table_ids["{r2}"]
  destination_cidr_block    = var.vpc_cidrs["{r1}"]
  vpc_peering_connection_id = aws_vpc_peering_connection.{slug}_{r1_id}_{r2_id}.id
}}

"""

    provider_aliases = "\n".join(
        f'  alias = "{r.replace("-", "_")}"' for r in regions
    )

    return f"""\
# Cross-region VPC peering mesh — {slug}
# Full mesh: every region can reach every other region for service discovery.
# Port 8000 is the AetherOS default app port.

terraform {{
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

{chr(10).join(
    f'provider "aws" {{\n  region = "{r}"\n  alias  = "{r.replace("-","_")}"\n}}\n'
    for r in regions
)}

{peering_blocks}
# Security group rule — allow cross-region service discovery on port 8000
resource "aws_security_group_rule" "{slug}_cross_region_ingress" {{
  for_each          = var.vpc_cidrs
  type              = "ingress"
  from_port         = 8000
  to_port           = 8000
  protocol          = "tcp"
  cidr_blocks       = [each.value]
  security_group_id = var.app_security_group_ids[each.key]
  description       = "Allow cross-region service discovery from ${{each.key}}"
}}
"""


def generate_multiregion_variables_tf(slug: str, regions: List[str]) -> str:
    """Return Terraform variables for the multi-region topology."""
    secondary = [r for r in regions[1:]]
    secondary_default = "\n".join(f'    "{r}",' for r in secondary)

    return f"""\
variable "primary_region" {{
  description = "Primary AWS region — receives 100% of Global Accelerator weight"
  type        = string
  default     = "{regions[0]}"
}}

variable "secondary_regions" {{
  description = "Secondary AWS regions — each receives 50% weight (failover only)"
  type        = list(string)
  default     = [
{secondary_default}
  ]
}}

variable "hosted_zone_id" {{
  description = "Route53 hosted zone ID for latency-based routing"
  type        = string
}}

variable "domain_name" {{
  description = "Application domain name (e.g. app.example.com)"
  type        = string
}}

variable "alb_arns" {{
  description = "Map of region -> ALB ARN for Global Accelerator endpoint groups"
  type        = map(string)
}}

variable "alb_dns" {{
  description = "Map of region -> ALB DNS name for Route53 alias records"
  type        = map(string)
}}

variable "alb_zone_ids" {{
  description = "Map of region -> ALB hosted zone ID for Route53 alias records"
  type        = map(string)
}}

variable "vpc_ids" {{
  description = "Map of region -> VPC ID for peering connections"
  type        = map(string)
}}

variable "vpc_cidrs" {{
  description = "Map of region -> VPC CIDR block for route table entries"
  type        = map(string)
}}

variable "route_table_ids" {{
  description = "Map of region -> main route table ID for cross-region routes"
  type        = map(string)
}}

variable "app_security_group_ids" {{
  description = "Map of region -> app security group ID for cross-region ingress rules"
  type        = map(string)
}}

variable "flow_logs_bucket" {{
  description = "S3 bucket name for Global Accelerator flow logs"
  type        = string
  default     = "{slug}-flow-logs"
}}
"""


def generate_multiregion_outputs_tf(slug: str, regions: List[str]) -> str:
    """Return Terraform outputs for the multi-region topology."""
    route53_outputs = "\n".join(
        f"""\
output "route53_record_{r.replace("-", "_")}" {{
  description = "Route53 latency record for {r}"
  value       = aws_route53_record.{slug}_{r.replace("-", "_")}.fqdn
}}
"""
        for r in regions
    )

    peering_outputs = "\n".join(
        f'    "{r1}-{r2}" = aws_vpc_peering_connection.{slug}_{r1.replace("-", "_")}_{r2.replace("-", "_")}.id,'
        for r1, r2 in combinations(regions, 2)
    )

    return f"""\
output "global_accelerator_dns" {{
  description = "Global Accelerator anycast DNS name (use this as your CDN origin)"
  value       = aws_globalaccelerator_accelerator.{slug}.dns_name
}}

output "global_accelerator_ips" {{
  description = "Global Accelerator static anycast IP addresses"
  value       = aws_globalaccelerator_accelerator.{slug}.ip_sets[*].ip_addresses
}}

{route53_outputs}

output "vpc_peering_ids" {{
  description = "Map of region pair -> VPC peering connection ID"
  value = {{
{peering_outputs}
  }}
}}
"""


def generate_deployment_guide(slug: str, regions: List[str]) -> str:
    """Return a Markdown multi-region deployment guide."""
    region_list = "\n".join(f"- `{r}`" for r in regions)
    helm_steps = "\n".join(
        f"  ```bash\n  kubectl config use-context {r}\n"
        f"  helm upgrade --install {slug} ./helm/{slug} -n {slug} -f helm/{slug}/values.prod.yaml\n"
        f"  ```"
        for r in regions
    )

    return f"""\
# Multi-Region Deployment Guide — {slug}

Generated by AetherOS p20_multiregion.

## Regions

{region_list}

## Prerequisites

Before running this Terraform, you must have:

1. An EKS cluster running in each region (deploy via `terraform/aws-eks/` from p11e).
2. An ALB in each region with a valid SSL certificate and `/health` returning HTTP 200.
3. A Route53 hosted zone for your domain.
4. The following Terraform variables populated in `terraform.tfvars`:
   - `hosted_zone_id`
   - `domain_name`
   - `alb_arns` (map of region → ALB ARN)
   - `alb_dns` (map of region → ALB DNS name)
   - `alb_zone_ids` (map of region → ALB hosted zone ID)
   - `vpc_ids`, `vpc_cidrs`, `route_table_ids`, `app_security_group_ids`

## Step 1 — Deploy the application to each region

{helm_steps}

## Step 2 — Apply multi-region Terraform

```bash
cd multiregion/
terraform init
terraform plan -out=tfplan
terraform apply tfplan
```

## Step 3 — Verify health checks in Route53

```bash
# Wait 60 s for health checks to stabilise, then:
aws route53 list-health-checks --query \
  "HealthChecks[?starts_with(CallerReference, '{slug}')].{{Id:Id,Status:HealthCheckConfig.FullyQualifiedDomainName}}"
```

All health checks should show `Healthy` status.

## Step 4 — Update DNS TTL for fast failover

Reduce the Route53 record TTL to 60 s so clients pick up failover DNS changes quickly:

```bash
# Edit variables.tf: TTL is hardcoded to 60 s in the aws_route53_record resources.
# No action needed — TTL is already set to 60 s in the generated Terraform.
```

## Failover Procedure

If a region becomes unhealthy:

1. Route53 health checks detect the failure within ~30 s and stop routing traffic.
2. Global Accelerator detects the unhealthy endpoint within ~10 s and redirects traffic.

To manually remove a region from the rotation:

```bash
# Set endpoint weight to 0 in Global Accelerator
aws globalaccelerator update-endpoint-group \\
  --endpoint-group-arn <ARN> \\
  --endpoint-configurations EndpointId=<ALB-ARN>,Weight=0

# Or: disable the Route53 health check to force DNS failover
aws route53 update-health-check \\
  --health-check-id <ID> \\
  --disabled
```

To restore the region:

```bash
# Re-apply Terraform to restore weights to their configured values
terraform apply
```

## Monitoring

- Global Accelerator flow logs → S3 bucket `{slug}-flow-logs`
- Route53 health check metrics → CloudWatch namespace `AWS/Route53`
- Cross-region latency → CloudWatch `AWS/GlobalAccelerator`
"""


def generate_multiregion_package(
    entities: List[dict],
    slug: str,
    output_dir: Path,
    regions: List[str] | None = None,
) -> Path:
    """Write a complete multi-region Terraform package to output_dir/multiregion/.

    Creates:
      main.tf        — Global Accelerator + Route53 + VPC peering
      variables.tf
      outputs.tf
      DEPLOYMENT_GUIDE.md

    Returns the multiregion/ directory path.
    """
    if not regions:
        regions = list(DEFAULT_REGIONS)

    mr_dir = output_dir / "multiregion"
    mr_dir.mkdir(parents=True, exist_ok=True)

    # Default hosted_zone_id placeholder — operator fills in terraform.tfvars
    hosted_zone_id = "REPLACE_WITH_YOUR_HOSTED_ZONE_ID"

    main_tf_parts = [
        f"# Multi-region Terraform — {slug}\n"
        f"# Generated by AetherOS p20_multiregion\n"
        f"# Regions: {', '.join(regions)}\n\n",
        generate_global_accelerator_tf(slug, regions),
        generate_route53_latency_routing(slug, regions, hosted_zone_id),
        generate_vpc_peering_tf(slug, regions),
    ]

    try:
        (mr_dir / "main.tf").write_text("\n".join(main_tf_parts))
        logger.info("multiregion: wrote main.tf (%d regions)", len(regions))
    except Exception as e:
        logger.warning("multiregion: main.tf write failed: %s", e)

    try:
        (mr_dir / "variables.tf").write_text(generate_multiregion_variables_tf(slug, regions))
        logger.info("multiregion: wrote variables.tf")
    except Exception as e:
        logger.warning("multiregion: variables.tf write failed: %s", e)

    try:
        (mr_dir / "outputs.tf").write_text(generate_multiregion_outputs_tf(slug, regions))
        logger.info("multiregion: wrote outputs.tf")
    except Exception as e:
        logger.warning("multiregion: outputs.tf write failed: %s", e)

    try:
        (mr_dir / "DEPLOYMENT_GUIDE.md").write_text(generate_deployment_guide(slug, regions))
        logger.info("multiregion: wrote DEPLOYMENT_GUIDE.md")
    except Exception as e:
        logger.warning("multiregion: DEPLOYMENT_GUIDE.md write failed: %s", e)

    return mr_dir
