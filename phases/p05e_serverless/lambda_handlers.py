"""Generated Lambda code for p05e: the per-entity CRUD handler and the JWT authorizer.

Entity and field names come from the domain model (ultimately from a user's spec and a model),
so they are reduced to plain identifiers before they reach generated code or SQL. Update only
touches columns the entity declares; column names never come from the request.
"""
from __future__ import annotations

import re
import textwrap


def safe_ident(raw: object, default: str = "item") -> str:
    """lower_snake identifier: letters, digits, underscore; never empty, never leading digit."""
    s = re.sub(r"[^a-z0-9_]+", "_", str(raw or "").lower()).strip("_")
    if not s:
        return default
    return s if s[0].isalpha() else f"e_{s}"


def gen_authorizer() -> str:
    """src/authorizer.py: API Gateway TOKEN authorizer that verifies the JWT signature.

    RS256 with JWT_PUBLIC_KEY when set (what the generated backend issues), else HS256 with
    SECRET_KEY. Anything that does not verify is a 401: the function raises "Unauthorized".
    """
    return textwrap.dedent('''\
        """API Gateway Lambda authorizer: allow only requests with a verified access token."""
        import os

        from jose import JWTError, jwt

        _PUBLIC_KEY = os.environ.get("JWT_PUBLIC_KEY", "")


        def _claims(token: str) -> dict:
            if _PUBLIC_KEY:
                return jwt.decode(token, _PUBLIC_KEY, algorithms=["RS256"])
            return jwt.decode(token, os.environ["SECRET_KEY"], algorithms=["HS256"])


        def lambda_handler(event, context):
            header = event.get("authorizationToken") or ""
            scheme, _, token = header.partition(" ")
            if scheme.lower() != "bearer" or not token:
                raise Exception("Unauthorized")
            try:
                claims = _claims(token)
            except (JWTError, KeyError) as exc:
                raise Exception("Unauthorized") from exc
            if claims.get("type", "access") != "access" or not claims.get("sub"):
                raise Exception("Unauthorized")
            # One policy for the whole API: API Gateway caches it per token.
            arn = event["methodArn"].split("/")[0] + "/*"
            return {
                "principalId": str(claims["sub"]),
                "policyDocument": {
                    "Version": "2012-10-17",
                    "Statement": [{"Action": "execute-api:Invoke", "Effect": "Allow", "Resource": arn}],
                },
                "context": {"role": str(claims.get("role", "")), "org_id": str(claims.get("org_id") or "")},
            }
    ''')


def gen_entity_lambda_handler(entity: dict) -> str:
    """Per-entity Lambda handler with list/create/get/update/delete (SQLAlchemy Core).

    Runs behind the JWT authorizer. Statements are fixed at generation time: the column lists
    come from the entity's own fields, and update ignores any other key in the request body.
    """
    name = safe_ident(entity.get("name", entity.get("table", "item")))
    fields = entity.get("fields") or []
    cols = [c for c in (safe_ident(f.get("name"), "") for f in fields if isinstance(f, dict)) if c and c != "id"]
    cols = list(dict.fromkeys(cols)) or ["name", "description"]

    col_list = ", ".join(cols)
    val_list = ", ".join(f":{c}" for c in cols)
    insert_params = ", ".join(f'"{c}": body.get("{c}")' for c in cols)

    return textwrap.dedent(f"""\
        \"\"\"
        Lambda handler for {name} CRUD operations.
        Generated by AetherOS — uses SQLAlchemy Core against RDS PostgreSQL.
        The API Gateway authorizer has already verified the caller's token.
        \"\"\"
        from __future__ import annotations

        import json
        import logging
        import os
        from typing import Any, Dict

        import sqlalchemy as sa

        logger = logging.getLogger(__name__)
        logger.setLevel(os.environ.get("LOG_LEVEL", "INFO"))

        _engine: sa.engine.Engine | None = None
        _COLUMNS = {cols!r}


        def _get_engine() -> sa.engine.Engine:
            \"\"\"Lazy-init DB engine; reused across warm Lambda invocations.\"\"\"
            global _engine
            if _engine is None:
                db_url = os.environ["DATABASE_URL"]
                _engine = sa.create_engine(db_url, pool_pre_ping=True, pool_size=2)
            return _engine


        def _resp(status: int, body: Any) -> Dict:
            return {{
                "statusCode": status,
                "headers": {{"Content-Type": "application/json"}},
                "body": json.dumps(body, default=str),
            }}


        def _list_{name}s() -> Dict:
            with _get_engine().connect() as conn:
                rows = conn.execute(
                    sa.text("SELECT * FROM {name}s ORDER BY id LIMIT 100")
                ).mappings().all()
            return _resp(200, [dict(r) for r in rows])


        def _create_{name}(body: Dict) -> Dict:
            with _get_engine().begin() as conn:
                result = conn.execute(
                    sa.text(
                        "INSERT INTO {name}s ({col_list}) VALUES ({val_list}) RETURNING *"
                    ),
                    {{{insert_params}}},
                )
                row = result.mappings().first()
            return _resp(201, dict(row) if row else {{}})


        def _get_{name}(item_id: str) -> Dict:
            with _get_engine().connect() as conn:
                row = conn.execute(
                    sa.text("SELECT * FROM {name}s WHERE id = :id"),
                    {{"id": item_id}},
                ).mappings().first()
            if row is None:
                return _resp(404, {{"detail": "{name} not found"}})
            return _resp(200, dict(row))


        def _update_{name}(item_id: str, body: Dict) -> Dict:
            # Only declared columns, never keys taken from the request: a key was a SQL fragment.
            changed = [c for c in _COLUMNS if c in body]
            if not changed:
                return _resp(400, {{"detail": "No fields to update"}})
            assignments = {{c: f"{{c}} = :{{c}}" for c in _COLUMNS}}
            set_clause = ", ".join(assignments[c] for c in changed)
            params = {{c: body[c] for c in changed}}
            params["id"] = item_id
            with _get_engine().begin() as conn:
                result = conn.execute(
                    sa.text(f"UPDATE {name}s SET {{set_clause}} WHERE id = :id RETURNING *"),
                    params,
                )
                row = result.mappings().first()
            if row is None:
                return _resp(404, {{"detail": "{name} not found"}})
            return _resp(200, dict(row))


        def _delete_{name}(item_id: str) -> Dict:
            with _get_engine().begin() as conn:
                conn.execute(
                    sa.text("DELETE FROM {name}s WHERE id = :id"),
                    {{"id": item_id}},
                )
            return _resp(204, {{}})


        def lambda_handler(event: Dict, context: Any) -> Dict:
            \"\"\"Main Lambda handler — dispatches CRUD by HTTP method.\"\"\"
            method = (event.get("httpMethod") or "GET").upper()
            path_params = event.get("pathParameters") or {{}}
            item_id = path_params.get("id", "")

            try:
                raw_body = event.get("body") or "{{}}"
                body = json.loads(raw_body) if raw_body else {{}}
                if not isinstance(body, dict):
                    raise TypeError("body must be a JSON object")
            except (json.JSONDecodeError, TypeError) as exc:
                logger.warning("{name} handler: invalid JSON body: %s", exc)
                return _resp(400, {{"detail": "Invalid JSON body"}})

            try:
                if method == "GET" and not item_id:
                    return _list_{name}s()
                elif method == "GET":
                    return _get_{name}(item_id)
                elif method == "POST":
                    return _create_{name}(body)
                elif method == "PUT":
                    return _update_{name}(item_id, body)
                elif method == "DELETE":
                    return _delete_{name}(item_id)
                else:
                    return _resp(405, {{"detail": "Method not allowed"}})
            except Exception as exc:
                logger.warning("{name} handler: unhandled error method=%s: %s", method, exc)
                return _resp(500, {{"detail": "Internal server error"}})
    """)
