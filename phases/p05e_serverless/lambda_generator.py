"""
AWS Lambda + API Gateway serverless scaffolding generator.

Generates SAM (Serverless Application Model) templates, Lambda function
handlers (using Mangum adapter for FastAPI), and API Gateway config.

Output layout (under output_dir/serverless/aws/):
  template.yaml          — SAM template (API Gateway + Lambda functions)
  requirements.txt       — Lambda layer dependencies
  src/
    handler.py           — Mangum adapter entry point (wraps FastAPI app)
    <entity>_handler.py  — Per-entity Lambda function with CRUD operations
  layers/
    requirements.txt     — Dependencies for Lambda layer
  Makefile               — Build, deploy, test commands
  samconfig.toml         — SAM CLI config
  README.md              — Deployment instructions
"""
from __future__ import annotations

import re
import textwrap
from typing import List

from aether_os.phases.p05e_serverless.lambda_handlers import (  # noqa: F401  (re-exported)
    gen_authorizer,
    gen_entity_lambda_handler,
    safe_ident,
)


def gen_sam_template(
    project_name: str,
    entities: List[dict],
    region: str = "us-east-1",
) -> str:
    """
    Generate SAM template.yaml for the project.

    Includes:
      - AWS::Serverless::Api (API Gateway REST API)
      - AWS::Serverless::Function for the main Mangum-wrapped FastAPI app
      - AWS::Serverless::LayerVersion for Python dependencies
      - Environment variables: DATABASE_URL, SECRET_KEY, ENVIRONMENT
    RDS is omitted by default — DATABASE_URL points to an external PG endpoint
    or can be swapped for DynamoDB by setting USE_DYNAMODB=true.
    """
    project_name = " ".join(project_name.replace('"', "'").split())  # it sits inside YAML double quotes
    slug = re.sub(r"[^a-z0-9-]+", "-", project_name.lower()).strip("-") or "app"
    safe_name = re.sub(r"[^A-Za-z0-9]", "", project_name) or "App"  # CloudFormation logical ids are alphanumeric

    # Build one function resource block per entity (max 8 enforced by caller)
    entity_functions = ""
    for ent in entities[:8]:
        name = safe_ident(ent.get("name", ent.get("table", "item")))
        title = name.title().replace("_", "")
        entity_functions += textwrap.dedent(f"""\

          {title}Function:
            Type: AWS::Serverless::Function
            Properties:
              FunctionName: !Sub "{slug}-{name}-${{Environment}}"
              CodeUri: src/
              Handler: {name}_handler.lambda_handler
              Runtime: python3.12
              Layers:
                - !Ref DependenciesLayer
              Environment:
                Variables:
                  DATABASE_URL: !Ref DatabaseUrl
                  SECRET_KEY: !Ref SecretKey
                  ENVIRONMENT: !Ref Environment
                  ENTITY_NAME: "{name}"
              Events:
                List{title}:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{name}s
                    Method: GET
                    Auth:
                      Authorizer: JwtAuthorizer
                Create{title}:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{name}s
                    Method: POST
                    Auth:
                      Authorizer: JwtAuthorizer
                Get{title}:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{name}s/{{id}}
                    Method: GET
                    Auth:
                      Authorizer: JwtAuthorizer
                Update{title}:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{name}s/{{id}}
                    Method: PUT
                    Auth:
                      Authorizer: JwtAuthorizer
                Delete{title}:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{name}s/{{id}}
                    Method: DELETE
                    Auth:
                      Authorizer: JwtAuthorizer
        """)

    template = textwrap.dedent(f"""\
        # SAM template — {project_name}
        # Generated by AetherOS
        # Deploy: sam build && sam deploy --guided
        AWSTemplateFormatVersion: "2010-09-09"
        Transform: AWS::Serverless-2016-10-31
        Description: "{project_name} — AWS Lambda + API Gateway (AetherOS)"

        Globals:
          Function:
            Timeout: 30
            MemorySize: 512
            Runtime: python3.12
            Architectures:
              - x86_64
            Tracing: Active
            Environment:
              Variables:
                LOG_LEVEL: INFO

        Parameters:
          Environment:
            Type: String
            Default: prod
            AllowedValues: [dev, staging, prod]
          DatabaseUrl:
            Type: String
            NoEcho: true
            Description: PostgreSQL connection string (e.g. postgresql://user:pass@host/db)
          SecretKey:
            Type: String
            NoEcho: true
            Description: JWT / app secret key
          JwtPublicKey:
            Type: String
            Default: ""
            Description: PEM public key when tokens are RS256 (the generated backend default); empty = HS256 with SecretKey

        Resources:

          {safe_name}Api:
            Type: AWS::Serverless::Api
            Properties:
              Name: !Sub "{slug}-api-${{Environment}}"
              StageName: !Ref Environment
              Cors:
                AllowMethods: "'GET,POST,PUT,DELETE,OPTIONS'"
                AllowHeaders: "'Content-Type,Authorization'"
                AllowOrigin: "'*'"
              Auth:
                # Entity routes need a verified JWT. The proxy function below opts out: the
                # FastAPI app behind it enforces its own auth (and serves /auth/login).
                DefaultAuthorizer: JwtAuthorizer
                Authorizers:
                  JwtAuthorizer:
                    FunctionArn: !GetAtt AuthorizerFunction.Arn
                    Identity:
                      Header: Authorization
                      ReauthorizeEvery: 300

          AuthorizerFunction:
            Type: AWS::Serverless::Function
            Properties:
              FunctionName: !Sub "{slug}-authorizer-${{Environment}}"
              CodeUri: src/
              Handler: authorizer.lambda_handler
              Runtime: python3.12
              Layers:
                - !Ref DependenciesLayer
              Environment:
                Variables:
                  SECRET_KEY: !Ref SecretKey
                  JWT_PUBLIC_KEY: !Ref JwtPublicKey

          MainAppFunction:
            Type: AWS::Serverless::Function
            Properties:
              FunctionName: !Sub "{slug}-main-${{Environment}}"
              CodeUri: src/
              Handler: handler.handler
              Runtime: python3.12
              Layers:
                - !Ref DependenciesLayer
              Environment:
                Variables:
                  DATABASE_URL: !Ref DatabaseUrl
                  SECRET_KEY: !Ref SecretKey
                  ENVIRONMENT: !Ref Environment
              Events:
                ProxyRoot:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /
                    Method: ANY
                    Auth:
                      Authorizer: NONE
                ProxyAll:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{{proxy+}}
                    Method: ANY
                    Auth:
                      Authorizer: NONE
          __ENTITY_FUNCTIONS__
          DependenciesLayer:
            Type: AWS::Serverless::LayerVersion
            Properties:
              LayerName: !Sub "{slug}-deps-${{Environment}}"
              Description: "Python dependencies for {project_name}"
              ContentUri: layers/
              CompatibleRuntimes:
                - python3.12
              RetentionPolicy: Retain

        Outputs:
          ApiUrl:
            Description: "API Gateway endpoint URL"
            Value: !Sub "https://${{ServerlessRestApi}}.execute-api.${{AWS::Region}}.amazonaws.com/${{Environment}}/"
          MainFunctionArn:
            Description: "Main Lambda function ARN"
            Value: !GetAtt MainAppFunction.Arn
    """)
    # Substituted after dedent: the entity block carries its own indentation (it used to be
    # pasted inside the dedent and produced invalid YAML).
    return template.replace("__ENTITY_FUNCTIONS__", textwrap.indent(entity_functions, "  ").strip("\n").lstrip(" "))


def gen_mangum_handler(project_name: str) -> str:
    """
    Generate src/handler.py — Mangum adapter wrapping the FastAPI app.

    Mangum translates API Gateway events to ASGI (FastAPI/Starlette) calls.
    lifespan="off" avoids startup/shutdown lifecycle issues in Lambda cold starts.
    """
    return textwrap.dedent(f"""\
        \"\"\"
        AWS Lambda entry point for {project_name}.
        Mangum wraps the FastAPI ASGI app for API Gateway proxy integration.
        \"\"\"
        from __future__ import annotations

        import logging
        import os

        logger = logging.getLogger(__name__)
        logger.setLevel(os.environ.get("LOG_LEVEL", "INFO"))

        try:
            from mangum import Mangum
            from main import app  # generated FastAPI application

            # lifespan="off" prevents Lambda cold-start timeouts on app startup events
            handler = Mangum(app, lifespan="off")
            logger.info("Mangum handler initialized for {project_name}")
        except ImportError as e:
            logger.error("Failed to import Mangum or FastAPI app: %s", e)
            raise
    """)


def gen_lambda_requirements() -> str:
    """Generate requirements.txt for Lambda function package.

    Pins must stay >= the versions in requirements.lock (the audited set); tests/test_lambda_requirements_pins.py enforces it.
    sqlalchemy[asyncio] because newer SQLAlchemy no longer pulls greenlet in by default.
    """
    return textwrap.dedent("""\
        # AWS Lambda requirements — generated by AetherOS
        mangum==0.19.0
        fastapi==0.120.4
        uvicorn==0.32.0
        sqlalchemy[asyncio]==2.0.35
        psycopg2-binary==2.9.13
        pydantic==2.9.0
        pydantic-settings==2.5.2
        PyJWT[crypto]==2.15.1
        passlib[bcrypt]==1.7.4
        python-multipart==0.0.34
        httpx==0.28.1
        structlog==26.1.0
    """)


def gen_sam_config(project_name: str, region: str = "us-east-1") -> str:
    """
    Generate samconfig.toml — SAM CLI configuration file.

    Stores default deploy parameters so `sam deploy` works without
    re-prompting every time.
    """
    slug = project_name.lower().replace(" ", "-")
    return textwrap.dedent(f"""\
        # samconfig.toml — SAM CLI config for {project_name}
        # Generated by AetherOS
        version = 0.1

        [default.global.parameters]
        stack_name = "{slug}"

        [default.build.parameters]
        cached = true
        parallel = true

        [default.deploy.parameters]
        stack_name = "{slug}"
        s3_bucket = "{slug}-sam-artifacts"
        s3_prefix = "{slug}"
        region = "{region}"
        confirm_changeset = true
        capabilities = "CAPABILITY_IAM"
        parameter_overrides = "Environment=prod"

        [default.local_start_api.parameters]
        port = 3000
        warm_containers = "EAGER"
    """)


def gen_lambda_makefile(project_name: str) -> str:
    """
    Generate Makefile with build, deploy, local, test, and logs targets.

    Uses SAM CLI for build/deploy/local and pytest for tests.
    """
    slug = project_name.lower().replace(" ", "-")
    return textwrap.dedent(f"""\
        # Makefile — {project_name} AWS Lambda
        # Generated by AetherOS
        .PHONY: build deploy local test logs clean validate

        STACK_NAME ?= {slug}
        REGION     ?= us-east-1

        build:
        \tsam build --parallel --cached

        deploy: build
        \tsam deploy --guided

        deploy-fast: build
        \tsam deploy --no-confirm-changeset

        local: build
        \tsam local start-api --port 3000 --warm-containers EAGER

        local-invoke:
        \tsam local invoke MainAppFunction --event events/sample.json

        test:
        \tpip install pytest pytest-asyncio httpx --quiet
        \tpytest tests/ -v --tb=short

        logs:
        \tsam logs --stack-name $(STACK_NAME) --region $(REGION) --tail

        validate:
        \tsam validate --region $(REGION)

        clean:
        \trm -rf .aws-sam/

        package:
        \tsam package \\
        \t\t--s3-bucket $(STACK_NAME)-sam-artifacts \\
        \t\t--output-template-file packaged.yaml

        delete:
        \taws cloudformation delete-stack --stack-name $(STACK_NAME) --region $(REGION)
    """)


def gen_lambda_readme(project_name: str, entities: List[dict]) -> str:
    """
    Generate README.md with deployment instructions for the Lambda project.

    Covers prerequisites, first deploy, local testing, and entity endpoint list.
    """
    slug = project_name.lower().replace(" ", "-")
    entity_names = [
        e.get("name", e.get("table", "item")) for e in entities[:8]
    ]
    endpoint_rows = "\n".join(
        f"| `/{name}s` | GET / POST | List and create {name}s |\n"
        f"| `/{name}s/{{id}}` | GET / PUT / DELETE | Single {name} operations |"
        for name in entity_names
    )

    return textwrap.dedent(f"""\
        # {project_name} — AWS Lambda Deployment

        Generated by AetherOS. Uses AWS SAM + Mangum (FastAPI on Lambda).

        ## Prerequisites

        - AWS CLI configured (`aws configure`)
        - SAM CLI installed (`brew install aws-sam-cli` / `pip install aws-sam-cli`)
        - Python 3.12
        - An S3 bucket for SAM artifacts: `{slug}-sam-artifacts`
        - A PostgreSQL database (RDS, Aurora Serverless, or external)

        ## First Deploy

        ```bash
        # 1. Build the Lambda package
        make build

        # 2. Create SAM artifact bucket (one-time)
        aws s3 mb s3://{slug}-sam-artifacts --region us-east-1

        # 3. Deploy (interactive first time — saves answers to samconfig.toml)
        make deploy
        # Enter: DATABASE_URL, SECRET_KEY when prompted
        ```

        After deploy, the API Gateway URL is shown in Outputs.

        ## Local Development

        ```bash
        # Start local API (hot reload via SAM)
        make local
        # API available at http://localhost:3000
        ```

        ## Running Tests

        ```bash
        make test
        ```

        ## API Endpoints

        | Path | Methods | Description |
        |------|---------|-------------|
        | `/health` | GET | Health check |
        {endpoint_rows}

        ## Architecture

        ```
        Internet → API Gateway → Lambda (Mangum) → FastAPI app → PostgreSQL (RDS)
                                ↓
                         Per-entity handlers (direct Lambda invocations)
        ```

        - **Cold start**: ~1-2s (Python 3.12 + dependencies layer)
        - **Warm invocation**: ~20ms
        - **Concurrency**: up to 1000 concurrent Lambda executions (default quota)
        - **Scale**: auto-scales to 500K+ users with zero config

        ## Environment Variables

        | Variable | Required | Description |
        |----------|----------|-------------|
        | `DATABASE_URL` | Yes | PostgreSQL connection string |
        | `SECRET_KEY` | Yes | JWT signing secret |
        | `ENVIRONMENT` | No | `dev` / `staging` / `prod` (default: prod) |
        | `LOG_LEVEL` | No | Python log level (default: INFO) |

        ## Cost Estimate (500K users/month)

        | Service | Usage | Estimated Cost |
        |---------|-------|----------------|
        | Lambda | 10M requests × 512MB × 100ms | ~$20/mo |
        | API Gateway | 10M requests | ~$35/mo |
        | RDS (db.t3.medium) | Always-on | ~$50/mo |
        | **Total** | | **~$105/mo** |

        ## Viewing Logs

        ```bash
        make logs
        # or directly:
        sam logs --stack-name {slug} --tail
        ```
    """)
