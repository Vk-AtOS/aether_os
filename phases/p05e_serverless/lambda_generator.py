"""
AWS Lambda + API Gateway serverless scaffolding generator.

Generates SAM (Serverless Application Model) templates, Lambda function
handlers (using Mangum adapter for FastAPI), and API Gateway config.

Output layout (under output_dir/serverless/aws/):
  template.yaml          — SAM template (API Gateway + Lambda functions)
  requirements.txt       — Lambda layer dependencies
  src/
    handler.py           — Mangum adapter entry point (wraps FastAPI app)
    <entity>_handler.py  — Per-entity Lambda function with CRUD operations
  layers/
    requirements.txt     — Dependencies for Lambda layer
  Makefile               — Build, deploy, test commands
  samconfig.toml         — SAM CLI config
  README.md              — Deployment instructions
"""
from __future__ import annotations

import textwrap
from typing import List


def gen_sam_template(
    project_name: str,
    entities: List[dict],
    region: str = "us-east-1",
) -> str:
    """
    Generate SAM template.yaml for the project.

    Includes:
      - AWS::Serverless::Api (API Gateway REST API)
      - AWS::Serverless::Function for the main Mangum-wrapped FastAPI app
      - AWS::Serverless::LayerVersion for Python dependencies
      - Environment variables: DATABASE_URL, SECRET_KEY, ENVIRONMENT
    RDS is omitted by default — DATABASE_URL points to an external PG endpoint
    or can be swapped for DynamoDB by setting USE_DYNAMODB=true.
    """
    slug = project_name.lower().replace(" ", "-")
    safe_name = project_name.replace(" ", "").replace("-", "")

    # Build one function resource block per entity (max 8 enforced by caller)
    entity_functions = ""
    for ent in entities[:8]:
        name = ent.get("name", ent.get("table", "item"))
        title = name.capitalize()
        fn_slug = name.lower().replace("_", "").replace("-", "")
        entity_functions += textwrap.dedent(f"""\

          {title}Function:
            Type: AWS::Serverless::Function
            Properties:
              FunctionName: !Sub "{slug}-{name}-${{Environment}}"
              CodeUri: src/
              Handler: {name}_handler.lambda_handler
              Runtime: python3.12
              Layers:
                - !Ref DependenciesLayer
              Environment:
                Variables:
                  DATABASE_URL: !Ref DatabaseUrl
                  SECRET_KEY: !Ref SecretKey
                  ENVIRONMENT: !Ref Environment
                  ENTITY_NAME: "{name}"
              Events:
                List{title}:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{name}s
                    Method: GET
                Create{title}:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{name}s
                    Method: POST
                Get{title}:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{name}s/{{id}}
                    Method: GET
                Update{title}:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{name}s/{{id}}
                    Method: PUT
                Delete{title}:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{name}s/{{id}}
                    Method: DELETE
        """)

    return textwrap.dedent(f"""\
        # SAM template — {project_name}
        # Generated by AetherOS
        # Deploy: sam build && sam deploy --guided
        AWSTemplateFormatVersion: "2010-09-09"
        Transform: AWS::Serverless-2016-10-31
        Description: "{project_name} — AWS Lambda + API Gateway (AetherOS)"

        Globals:
          Function:
            Timeout: 30
            MemorySize: 512
            Runtime: python3.12
            Architectures:
              - x86_64
            Tracing: Active
            Environment:
              Variables:
                LOG_LEVEL: INFO

        Parameters:
          Environment:
            Type: String
            Default: prod
            AllowedValues: [dev, staging, prod]
          DatabaseUrl:
            Type: String
            NoEcho: true
            Description: PostgreSQL connection string (e.g. postgresql://user:pass@host/db)
          SecretKey:
            Type: String
            NoEcho: true
            Description: JWT / app secret key

        Resources:

          {safe_name}Api:
            Type: AWS::Serverless::Api
            Properties:
              Name: !Sub "{slug}-api-${{Environment}}"
              StageName: !Ref Environment
              Cors:
                AllowMethods: "'GET,POST,PUT,DELETE,OPTIONS'"
                AllowHeaders: "'Content-Type,Authorization'"
                AllowOrigin: "'*'"
              Auth:
                DefaultAuthorizer: NONE  # Replace with AWS_IAM or Cognito authorizer for production

          MainAppFunction:
            Type: AWS::Serverless::Function
            Properties:
              FunctionName: !Sub "{slug}-main-${{Environment}}"
              CodeUri: src/
              Handler: handler.handler
              Runtime: python3.12
              Layers:
                - !Ref DependenciesLayer
              Environment:
                Variables:
                  DATABASE_URL: !Ref DatabaseUrl
                  SECRET_KEY: !Ref SecretKey
                  ENVIRONMENT: !Ref Environment
              Events:
                ProxyRoot:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /
                    Method: ANY
                ProxyAll:
                  Type: Api
                  Properties:
                    RestApiId: !Ref {safe_name}Api
                    Path: /{{proxy+}}
                    Method: ANY
        {entity_functions}
          DependenciesLayer:
            Type: AWS::Serverless::LayerVersion
            Properties:
              LayerName: !Sub "{slug}-deps-${{Environment}}"
              Description: "Python dependencies for {project_name}"
              ContentUri: layers/
              CompatibleRuntimes:
                - python3.12
              RetentionPolicy: Retain

        Outputs:
          ApiUrl:
            Description: "API Gateway endpoint URL"
            Value: !Sub "https://${{ServerlessRestApi}}.execute-api.${{AWS::Region}}.amazonaws.com/${{Environment}}/"
          MainFunctionArn:
            Description: "Main Lambda function ARN"
            Value: !GetAtt MainAppFunction.Arn
    """)


def gen_mangum_handler(project_name: str) -> str:
    """
    Generate src/handler.py — Mangum adapter wrapping the FastAPI app.

    Mangum translates API Gateway events to ASGI (FastAPI/Starlette) calls.
    lifespan="off" avoids startup/shutdown lifecycle issues in Lambda cold starts.
    """
    return textwrap.dedent(f"""\
        \"\"\"
        AWS Lambda entry point for {project_name}.
        Mangum wraps the FastAPI ASGI app for API Gateway proxy integration.
        \"\"\"
        from __future__ import annotations

        import logging
        import os

        logger = logging.getLogger(__name__)
        logger.setLevel(os.environ.get("LOG_LEVEL", "INFO"))

        try:
            from mangum import Mangum
            from main import app  # generated FastAPI application

            # lifespan="off" prevents Lambda cold-start timeouts on app startup events
            handler = Mangum(app, lifespan="off")
            logger.info("Mangum handler initialized for {project_name}")
        except ImportError as e:
            logger.error("Failed to import Mangum or FastAPI app: %s", e)
            raise
    """)


def gen_entity_lambda_handler(entity: dict) -> str:
    """
    Generate a per-entity Lambda handler with CRUD operations.

    Uses SQLAlchemy Core (sync) for RDS/PostgreSQL access.
    Each operation (list, create, get, update, delete) is a self-contained
    function called by the main lambda_handler dispatcher.
    """
    name = entity.get("name", entity.get("table", "item"))
    fields = entity.get("fields") or []

    # Build field list for INSERT
    field_names = [f.get("name", "value") for f in fields if f.get("name") != "id"]
    if not field_names:
        field_names = ["name", "description"]

    insert_params = ", ".join(f'"{f}": body.get("{f}")' for f in field_names)
    col_list = ", ".join(field_names)
    val_list = ", ".join(f":{f}" for f in field_names)

    return textwrap.dedent(f"""\
        \"\"\"
        Lambda handler for {name} CRUD operations.
        Generated by AetherOS — uses SQLAlchemy Core against RDS PostgreSQL.
        \"\"\"
        from __future__ import annotations

        import json
        import logging
        import os
        from typing import Any, Dict

        import sqlalchemy as sa

        logger = logging.getLogger(__name__)
        logger.setLevel(os.environ.get("LOG_LEVEL", "INFO"))

        _engine: sa.engine.Engine | None = None


        def _get_engine() -> sa.engine.Engine:
            \"\"\"Lazy-init DB engine; reused across warm Lambda invocations.\"\"\"
            global _engine
            if _engine is None:
                db_url = os.environ["DATABASE_URL"]
                _engine = sa.create_engine(db_url, pool_pre_ping=True, pool_size=2)
            return _engine


        def _resp(status: int, body: Any) -> Dict:
            return {{
                "statusCode": status,
                "headers": {{"Content-Type": "application/json", "Access-Control-Allow-Origin": "*"}},
                "body": json.dumps(body, default=str),
            }}


        def _list_{name}s() -> Dict:
            with _get_engine().connect() as conn:
                rows = conn.execute(
                    sa.text("SELECT * FROM {name}s ORDER BY id LIMIT 100")
                ).mappings().all()
            return _resp(200, [dict(r) for r in rows])


        def _create_{name}(body: Dict) -> Dict:
            with _get_engine().begin() as conn:
                result = conn.execute(
                    sa.text(
                        "INSERT INTO {name}s ({col_list}) VALUES ({val_list}) RETURNING *"
                    ),
                    {{{insert_params}}},
                )
                row = result.mappings().first()
            return _resp(201, dict(row) if row else {{}})


        def _get_{name}(item_id: str) -> Dict:
            with _get_engine().connect() as conn:
                row = conn.execute(
                    sa.text("SELECT * FROM {name}s WHERE id = :id"),
                    {{"id": item_id}},
                ).mappings().first()
            if row is None:
                return _resp(404, {{"detail": "{name} not found"}})
            return _resp(200, dict(row))


        def _update_{name}(item_id: str, body: Dict) -> Dict:
            set_clause = ", ".join(f"{{k}} = :{{k}}" for k in body if k != "id")
            if not set_clause:
                return _resp(400, {{"detail": "No fields to update"}})
            params = {{**body, "id": item_id}}
            with _get_engine().begin() as conn:
                result = conn.execute(
                    sa.text(f"UPDATE {name}s SET {{set_clause}} WHERE id = :id RETURNING *"),
                    params,
                )
                row = result.mappings().first()
            if row is None:
                return _resp(404, {{"detail": "{name} not found"}})
            return _resp(200, dict(row))


        def _delete_{name}(item_id: str) -> Dict:
            with _get_engine().begin() as conn:
                conn.execute(
                    sa.text("DELETE FROM {name}s WHERE id = :id"),
                    {{"id": item_id}},
                )
            return _resp(204, {{}})


        def lambda_handler(event: Dict, context: Any) -> Dict:
            \"\"\"Main Lambda handler — dispatches CRUD by HTTP method.\"\"\"
            method = (event.get("httpMethod") or "GET").upper()
            path_params = event.get("pathParameters") or {{}}
            item_id = path_params.get("id", "")

            try:
                raw_body = event.get("body") or "{{}}"
                body = json.loads(raw_body) if raw_body else {{}}
            except (json.JSONDecodeError, TypeError) as exc:
                logger.warning("{name} handler: invalid JSON body: %s", exc)
                return _resp(400, {{"detail": "Invalid JSON body"}})

            try:
                if method == "GET" and not item_id:
                    return _list_{name}s()
                elif method == "GET":
                    return _get_{name}(item_id)
                elif method == "POST":
                    return _create_{name}(body)
                elif method == "PUT":
                    return _update_{name}(item_id, body)
                elif method == "DELETE":
                    return _delete_{name}(item_id)
                else:
                    return _resp(405, {{"detail": "Method not allowed"}})
            except Exception as exc:
                logger.warning("{name} handler: unhandled error method=%s: %s", method, exc)
                return _resp(500, {{"detail": "Internal server error"}})
    """)


