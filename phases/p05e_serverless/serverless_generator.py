def generate_knative_broker_trigger(
    entity: str,
    slug: str,
    event_type: str,
) -> str:
    """
    Knative Broker + Trigger YAML.

    Filters by ce-type=com.{slug}.{entity}.{event_type}.
    Routes to the Knative Service.
    """
    fn_name = f"{slug}-{entity}-{event_type}"
    ce_type = f"com.{slug}.{entity}.{event_type}"
    return f"""\
## Knative Broker + Trigger — generated by AetherOS for {slug}/{entity}/{event_type}
apiVersion: eventing.knative.dev/v1
kind: Broker
metadata:
  name: {slug}-broker
  namespace: {slug}-functions
---
apiVersion: eventing.knative.dev/v1
kind: Trigger
metadata:
  name: {fn_name}-trigger
  namespace: {slug}-functions
spec:
  broker: {slug}-broker
  filter:
    attributes:
      type: {ce_type}
  subscriber:
    ref:
      apiVersion: serving.knative.dev/v1
      kind: Service
      name: {fn_name}
"""


def generate_knative_dockerfile(backend_lang: str) -> str:
    """
    Minimal Dockerfile for the function handler.
    python:3.12-slim for Python, golang:1.21-alpine for Go.
    """
    if backend_lang == "go":
        return """\
## Knative function Dockerfile (Go) — generated by AetherOS
FROM golang:1.21-alpine AS builder
WORKDIR /app
COPY go.mod go.sum ./
RUN go mod download
COPY . .
RUN CGO_ENABLED=0 GOOS=linux go build -o handler .

FROM alpine:3.19
RUN apk --no-cache add ca-certificates
WORKDIR /app
COPY --from=builder /app/handler .
EXPOSE 8080
CMD ["./handler"]
"""
    # Default: Python
    return """\
## Knative function Dockerfile (Python) — generated by AetherOS
FROM python:3.12-slim
WORKDIR /app
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY handler.py .
EXPOSE 8080
CMD ["uvicorn", "handler:app", "--host", "0.0.0.0", "--port", "8080"]
"""


def generate_serverless_package(
    entities: List[dict],
    slug: str,
    output_dir: Path,
    backend_lang: str,
) -> Path:
    """
    Writes all manifests + handlers to output_dir/serverless/.
    One subdir per entity+event_type (e.g., serverless/order-created/).
    Returns the serverless directory Path.
    """
    serverless_dir = output_dir / "serverless"
    serverless_dir.mkdir(parents=True, exist_ok=True)

    default_events = ["created", "updated", "deleted"]
    fn_count = 0

    for entity in entities:
        table = entity.get("table", "item")
        for event_type in default_events:
            fn_dir = serverless_dir / f"{table}-{event_type}"
            fn_dir.mkdir(exist_ok=True)

            image = f"registry.{slug}.internal/{slug}-{table}-{event_type}:latest"

            (fn_dir / "knative-service.yaml").write_text(
                generate_knative_service_manifest(table, event_type, slug, image)
            )
            (fn_dir / "broker-trigger.yaml").write_text(
                generate_knative_broker_trigger(table, slug, event_type)
            )
            (fn_dir / "Dockerfile").write_text(
                generate_knative_dockerfile(backend_lang)
            )

            if backend_lang == "go":
                (fn_dir / "main.go").write_text(
                    generate_function_handler_go(table, event_type)
                )
            else:
                (fn_dir / "handler.py").write_text(
                    generate_function_handler_python(table, event_type)
                )
                (fn_dir / "requirements.txt").write_text(
                    "fastapi==0.111.0\nhttpx==0.27.0\nuvicorn==0.30.1\n"
                )

            fn_count += 1

    logger.info(
        "p05e_serverless: generated %d functions at %s (lang=%s)",
        fn_count,
        serverless_dir,
        backend_lang,
    )
    return serverless_dir
