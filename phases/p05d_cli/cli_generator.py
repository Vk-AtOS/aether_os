# ── Go / Cobra ────────────────────────────────────────────────────────────────

def gen_go_root_cmd(project_name: str) -> str:
    slug = project_name.lower().replace(" ", "-")
    return f"""\
package cmd

import (
\t"fmt"
\t"os"

\t"github.com/spf13/cobra"
)

var apiBase string

var rootCmd = &cobra.Command{{
\tUse:   "{slug}",
\tShort: "{project_name} CLI — generated by AetherOS",
}}

func Execute() {{
\tif err := rootCmd.Execute(); err != nil {{
\t\tfmt.Fprintln(os.Stderr, err)
\t\tos.Exit(1)
\t}}
}}

func init() {{
\trootCmd.PersistentFlags().StringVar(&apiBase, "api", "http://localhost:8000", "API base URL")
}}
"""


def gen_go_entity_cmd(entity: Dict) -> str:
    table = entity.get("table", "item")
    fields = [f for f in entity.get("fields", []) if f.get("name") not in ("id", "created_at", "updated_at")]
    pascal = _pascal(table)
    label = _label(table)

    flag_vars = "\n\t".join(f'var {table}{_pascal(f["name"])} string' for f in fields)
    flag_defs = "\n\t".join(
        f'create{pascal}Cmd.Flags().StringVar(&{table}{_pascal(f["name"])}, "{f["name"]}", "", "{_label(f["name"])}")'
        for f in fields
    )
    json_build = '\\n'.join(f'\\t\\"{f["name"]}\\": \\"" + {table}{_pascal(f["name"])} + "\\"' for f in fields)

    return f"""\
package cmd

import (
\t"fmt"
\t"io"
\t"net/http"
\t"strings"

\t"github.com/spf13/cobra"
)

{flag_vars}

var list{pascal}Cmd = &cobra.Command{{
\tUse:   "list",
\tShort: "List {label} records",
\tRunE: func(cmd *cobra.Command, args []string) error {{
\t\tresp, err := http.Get(apiBase + "/{table}s")
\t\tif err != nil {{ return err }}
\t\tdefer resp.Body.Close()
\t\tbody, _ := io.ReadAll(resp.Body)
\t\tfmt.Println(string(body))
\t\treturn nil
\t}},
}}

var create{pascal}Cmd = &cobra.Command{{
\tUse:   "create",
\tShort: "Create a {label}",
\tRunE: func(cmd *cobra.Command, args []string) error {{
\t\tbody := `{{{json_build}}}`
\t\tresp, err := http.Post(apiBase+"/{table}s", "application/json", strings.NewReader(body))
\t\tif err != nil {{ return err }}
\t\tdefer resp.Body.Close()
\t\tout, _ := io.ReadAll(resp.Body)
\t\tfmt.Println(string(out))
\t\treturn nil
\t}},
}}

var {table}Cmd = &cobra.Command{{
\tUse:   "{table}",
\tShort: "Manage {label} records",
}}

func init() {{
\t{flag_defs}
\t{table}Cmd.AddCommand(list{pascal}Cmd, create{pascal}Cmd)
\trootCmd.AddCommand({table}Cmd)
}}
"""


