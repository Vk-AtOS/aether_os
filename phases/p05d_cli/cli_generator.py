# ── Entry point ───────────────────────────────────────────────────────────────

async def generate_python_cli(
    entities: List[Dict], project_name: str, output_dir: Path
) -> Path:
    cli_dir = output_dir / "cli"
    commands_dir = cli_dir / "commands"
    commands_dir.mkdir(parents=True, exist_ok=True)

    # Core project files
    (cli_dir / "pyproject.toml").write_text(gen_pyproject_toml(project_name))
    (cli_dir / "config.py").write_text(gen_config_py(project_name))
    (cli_dir / "cli.py").write_text(gen_cli_main(project_name, entities))
    (cli_dir / "README.md").write_text(gen_python_readme(project_name))
    (commands_dir / "__init__.py").write_text("")

    # Built-in subgroups: auth + config
    (commands_dir / "auth.py").write_text(gen_auth_commands_py())
    (commands_dir / "config.py").write_text(gen_config_commands_py())

    # Per-entity CRUD subgroups
    for entity in entities:
        table = entity.get("table", "item")
        (commands_dir / f"{table}.py").write_text(gen_entity_command_py(entity))
        logger.info("[p05d_cli] wrote commands/%s.py for entity '%s'", table, entity.get("name", table))

    logger.info(
        "[p05d_cli] Python CLI written to %s (%d entities + auth + config)",
        cli_dir, len(entities),
    )
    return cli_dir


async def generate_go_cli(
    entities: List[Dict], project_name: str, output_dir: Path
) -> Path:
    cli_dir = output_dir / "cli"
    cmd_dir = cli_dir / "cmd"
    cmd_dir.mkdir(parents=True, exist_ok=True)

    (cli_dir / "main.go").write_text(gen_go_main(project_name))
    (cli_dir / "go.mod").write_text(gen_go_mod(project_name))
    (cli_dir / "README.md").write_text(gen_go_readme(project_name))
    (cmd_dir / "root.go").write_text(gen_go_root_cmd(project_name))

    for entity in entities:
        table = entity.get("table", "item")
        (cmd_dir / f"{table}.go").write_text(gen_go_entity_cmd(entity))

    return cli_dir


async def generate_cli_project(
    entities: List[Dict],
    project_name: str,
    output_dir: Path,
    backend_lang: str = "python",
) -> Path:
    if backend_lang == "go":
        cli_dir = await generate_go_cli(entities, project_name, output_dir)
    else:
        cli_dir = await generate_python_cli(entities, project_name, output_dir)
    logger.info("p05d_cli: %s CLI generated at %s (%d entities)", backend_lang, cli_dir, len(entities))
    return cli_dir
