"""
CLI generator for AetherOS P05d phase.

Generates a production-ready CLI tool from domain IR entities.
- Python backend → Click CLI with Rich output
- Go backend     → Cobra CLI

Output layout (under output_dir/cli/):

Python (Click):
  pyproject.toml
  cli.py                    — Click group entry point
  commands/<entity>.py      — list/get/create/update/delete per entity
  config.py                 — local config (API URL, token storage)
  README.md

Go (Cobra):
  main.go
  cmd/root.go
  cmd/<entity>.go
  go.mod
  README.md
"""
from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import Any, Dict, List

from aether_os.phases.p05d_cli.cli_templates import (
    gen_auth_commands_py,
    gen_config_commands_py,
    gen_entity_command_py,
)

logger = logging.getLogger(__name__)


def _pascal(name: str) -> str:
    return "".join(w.capitalize() for w in name.replace("-", "_").split("_"))


def _label(name: str) -> str:
    return name.replace("_", " ").title()


# ── Python / Click ────────────────────────────────────────────────────────────

def gen_pyproject_toml(project_name: str) -> str:
    slug = project_name.lower().replace(" ", "-")
    return f"""\
[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[project]
name = "{slug}-cli"
version = "1.0.0"
description = "{project_name} command-line interface — generated by AetherOS"
requires-python = ">=3.11"
dependencies = [
    "click>=8.1",
    "httpx>=0.26",
    "rich>=13.7",
    "keyring>=24.3",
]

[project.scripts]
{slug} = "cli:cli"
"""


def gen_config_py(project_name: str = "app") -> str:
    # One keyring service per generated CLI: a shared name made every CLI read and overwrite
    # the same stored token and API URL.
    service = "aetheros-" + (re.sub(r"[^a-z0-9]+", "-", project_name.lower()).strip("-") or "app")
    return """\
\"\"\"Local config — API URL and token storage via keyring.\"\"\"
import logging
import os
import keyring

logger = logging.getLogger(__name__)

SERVICE = "__SERVICE__"
_DEFAULT_API = "http://localhost:8000"

def get_api_base() -> str:
    \"\"\"Return the API base URL (env var > keyring > default).\"\"\"
    return (
        os.environ.get("API_BASE")
        or keyring.get_password(SERVICE, "api_base")
        or _DEFAULT_API
    )

def set_api_base(url: str) -> None:
    \"\"\"Persist the API base URL in the system keyring.\"\"\"
    keyring.set_password(SERVICE, "api_base", url)

def reset_config() -> None:
    \"\"\"Reset all stored config values to defaults.\"\"\"
    try:
        keyring.delete_password(SERVICE, "token")
    except Exception as e:
        logger.warning("[cli_generator] keyring.delete_password(token) failed: %s", e)
    try:
        keyring.delete_password(SERVICE, "api_base")
    except Exception as e:
        logger.warning("[cli_generator] keyring.delete_password(api_base) failed: %s", e)

def get_token() -> str:
    return keyring.get_password(SERVICE, "token") or ""

def set_token(token: str) -> None:
    keyring.set_password(SERVICE, "token", token)

def auth_header() -> dict:
    t = get_token()
    return {"Authorization": f"Bearer {t}"} if t else {}
""".replace("__SERVICE__", service)


def gen_cli_main(project_name: str, entities: List[Dict]) -> str:
    entity_imports = "\n".join(
        f"from commands.{e.get('table', 'item')} import {e.get('table', 'item')}_group"
        for e in entities
    )
    entity_adds = "\n".join(
        f"cli.add_command({e.get('table', 'item')}_group, name='{e.get('table', 'item')}')"
        for e in entities
    )
    slug = project_name.lower().replace(" ", "-")
    return f"""\
\"\"\"
{project_name} CLI — generated by AetherOS.

Usage:
  {slug} auth login --email you@example.com
  {slug} auth whoami
  {slug} config set api-url https://api.example.com
  {slug} <entity> list [--limit N] [--json]
  {slug} <entity> create --interactive
  {slug} <entity> update <id> --data field=value
  {slug} <entity> delete <id>
\"\"\"
import click
from commands.auth import auth_group
from commands.config import config_group
{entity_imports}


@click.group()
@click.version_option("1.0.0", prog_name="{slug}")
def cli():
    \"\"\"Manage {project_name} from the command line.

    Authenticate first:  {slug} auth login
    Set API URL:         {slug} config set api-url <URL>
    \"\"\"


# ── built-in subgroups ────────────────────────────────────────────────────────
cli.add_command(auth_group, name="auth")
cli.add_command(config_group, name="config")

# ── entity subgroups (one per model) ─────────────────────────────────────────
{entity_adds}

if __name__ == "__main__":
    cli()
"""


